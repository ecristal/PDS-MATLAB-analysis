function metrics = evaluateTransferFunctionResponse( ...
        target, predicted, options)
%EVALUATETRANSFERFUNCTIONRESPONSE Compare peak, undershoot, tail, and return.

arguments
    target
    predicted
    options.SampleTime = []
    options.TailStartIndex = []
    options.ReturnBand = 0.01
    options.ReturnConsecutiveSamples = 3
end

[target, predicted] = validateSignals(target, predicted);
sampleTime = validatePositiveScalar(options.SampleTime, ...
    'pds:identification:evaluateTransferFunctionResponse:InvalidSampleTime');
returnBand = validateNonnegativeScalar(options.ReturnBand, ...
    'pds:identification:evaluateTransferFunctionResponse:InvalidReturnBand');
returnConsecutiveSamples = validatePositiveInteger( ...
    options.ReturnConsecutiveSamples, ...
    'pds:identification:evaluateTransferFunctionResponse:InvalidReturnConsecutiveSamples');

[~, targetPeakIndex] = max(abs(target));
[~, predictedPeakIndex] = max(abs(predicted));
targetPeakAmplitude = target(targetPeakIndex);
predictedPeakAmplitude = predicted(predictedPeakIndex);

if isempty(options.TailStartIndex)
    tailStartIndex = targetPeakIndex;
else
    tailStartIndex = validatePositiveInteger(options.TailStartIndex, ...
        'pds:identification:evaluateTransferFunctionResponse:InvalidTailStartIndex');
    if tailStartIndex > numel(target)
        error('pds:identification:evaluateTransferFunctionResponse:InvalidTailStartIndex', ...
            'TailStartIndex must not exceed the signal length.');
    end
end

[targetUndershootAmplitude, targetUndershootIndex] = ...
    undershoot(target, targetPeakIndex, sign(targetPeakAmplitude));
[predictedUndershootAmplitude, predictedUndershootIndex] = ...
    undershoot(predicted, predictedPeakIndex, sign(predictedPeakAmplitude));

[targetReturned, targetReturnIndex] = returnToBand( ...
    target, targetPeakIndex, returnBand, returnConsecutiveSamples);
[predictedReturned, predictedReturnIndex] = returnToBand( ...
    predicted, predictedPeakIndex, returnBand, returnConsecutiveSamples);
[targetSettled, targetSettlingIndex] = settleToBand( ...
    target, targetPeakIndex, returnBand, returnConsecutiveSamples);
[predictedSettled, predictedSettlingIndex] = settleToBand( ...
    predicted, predictedPeakIndex, returnBand, returnConsecutiveSamples);

targetReturnTime = indexToTime(targetReturnIndex, sampleTime);
predictedReturnTime = indexToTime(predictedReturnIndex, sampleTime);
residual = target - predicted;
tailIndices = tailStartIndex:numel(target);

metrics = struct( ...
    'sampleTime', sampleTime, ...
    'targetPolarity', sign(targetPeakAmplitude), ...
    'predictedPolarity', sign(predictedPeakAmplitude), ...
    'targetPeakAmplitude', targetPeakAmplitude, ...
    'predictedPeakAmplitude', predictedPeakAmplitude, ...
    'targetPeakIndex', targetPeakIndex, ...
    'predictedPeakIndex', predictedPeakIndex, ...
    'peakAmplitudeError', predictedPeakAmplitude - targetPeakAmplitude, ...
    'peakTimingErrorSamples', predictedPeakIndex - targetPeakIndex, ...
    'peakTimingError', (predictedPeakIndex - targetPeakIndex) * sampleTime, ...
    'targetUndershootAmplitude', targetUndershootAmplitude, ...
    'predictedUndershootAmplitude', predictedUndershootAmplitude, ...
    'targetUndershootIndex', targetUndershootIndex, ...
    'predictedUndershootIndex', predictedUndershootIndex, ...
    'undershootAmplitudeError', ...
        predictedUndershootAmplitude - targetUndershootAmplitude, ...
    'negativeAreaStartIndex', targetPeakIndex, ...
    'targetNegativeArea', ...
        sum(max(-target(targetPeakIndex:end), 0)) * sampleTime, ...
    'predictedNegativeArea', ...
        sum(max(-predicted(targetPeakIndex:end), 0)) * sampleTime, ...
    'targetTotalNegativeArea', sum(max(-target, 0)) * sampleTime, ...
    'predictedTotalNegativeArea', sum(max(-predicted, 0)) * sampleTime, ...
    'rmse', sqrt(mean(residual.^2)), ...
    'tailStartIndex', tailStartIndex, ...
    'tailRmse', sqrt(mean(residual(tailIndices).^2)), ...
    'targetTailEndAmplitude', target(end), ...
    'predictedTailEndAmplitude', predicted(end), ...
    'targetReturnedToBand', targetReturned, ...
    'predictedReturnedToBand', predictedReturned, ...
    'targetReturnIndex', targetReturnIndex, ...
    'predictedReturnIndex', predictedReturnIndex, ...
    'targetReturnTime', targetReturnTime, ...
    'predictedReturnTime', predictedReturnTime, ...
    'targetSettledToBand', targetSettled, ...
    'predictedSettledToBand', predictedSettled, ...
    'targetSettlingIndex', targetSettlingIndex, ...
    'predictedSettlingIndex', predictedSettlingIndex, ...
    'targetSettlingTime', indexToTime(targetSettlingIndex, sampleTime), ...
    'predictedSettlingTime', ...
        indexToTime(predictedSettlingIndex, sampleTime), ...
    'returnBand', returnBand, ...
    'returnConsecutiveSamples', returnConsecutiveSamples);
end


function [target, predicted] = validateSignals(target, predicted)
errorIdentifier = ...
    'pds:identification:evaluateTransferFunctionResponse:InvalidSignals';
if ~isnumeric(target) || ~isnumeric(predicted) || ...
        ~isvector(target) || ~isvector(predicted) || isempty(target) || ...
        numel(target) ~= numel(predicted) || numel(target) < 2 || ...
        ~isreal(target) || ~isreal(predicted) || ...
        any(~isfinite(target(:))) || any(~isfinite(predicted(:)))
    error(errorIdentifier, ...
        'Target and predicted signals must be equal-length finite real vectors.');
end
validateExactIntegerConversion(target, errorIdentifier, 'Target');
validateExactIntegerConversion(predicted, errorIdentifier, 'Predicted signal');
target = double(target(:).');
predicted = double(predicted(:).');
end


function [value, index] = undershoot(signal, peakIndex, peakSign)
postPeak = signal(peakIndex:end);
if peakSign >= 0
    [value, localIndex] = min(postPeak);
else
    [value, localIndex] = max(postPeak);
end
index = peakIndex + localIndex - 1;
end


function [returned, returnIndex] = returnToBand( ...
        signal, peakIndex, band, consecutiveSamples)
returned = false;
returnIndex = NaN;
firstCandidate = peakIndex + 1;
lastCandidate = numel(signal) - consecutiveSamples + 1;
for index = firstCandidate:lastCandidate
    local = signal(index:(index + consecutiveSamples - 1));
    if all(abs(local) <= band)
        returned = true;
        returnIndex = index;
        return;
    end
end
end


function [settled, settlingIndex] = settleToBand( ...
        signal, peakIndex, band, consecutiveSamples)
settled = false;
settlingIndex = NaN;
for index = (peakIndex + 1):numel(signal)
    remaining = signal(index:end);
    if numel(remaining) >= consecutiveSamples && all(abs(remaining) <= band)
        settled = true;
        settlingIndex = index;
        return;
    end
end
end


function time = indexToTime(index, sampleTime)
if isnan(index)
    time = NaN;
else
    time = (index - 1) * sampleTime;
end
end


function value = validatePositiveScalar(value, errorIdentifier)
if ~isnumeric(value) || ~isscalar(value) || ~isreal(value) || ...
        ~isfinite(value) || value <= 0
    error(errorIdentifier, 'Value must be a finite positive real scalar.');
end
validateExactIntegerConversion(value, errorIdentifier, 'Value');
value = double(value);
end


function value = validateNonnegativeScalar(value, errorIdentifier)
if ~isnumeric(value) || ~isscalar(value) || ~isreal(value) || ...
        ~isfinite(value) || value < 0
    error(errorIdentifier, 'Value must be a finite nonnegative real scalar.');
end
validateExactIntegerConversion(value, errorIdentifier, 'Value');
value = double(value);
end


function value = validatePositiveInteger(value, errorIdentifier)
value = validatePositiveScalar(value, errorIdentifier);
if value ~= fix(value)
    error(errorIdentifier, 'Value must be a positive integer scalar.');
end
end


function validateExactIntegerConversion(value, errorIdentifier, label)
if isa(value, 'uint64')
    unsafe = any(value(:) > uint64(flintmax));
elseif isa(value, 'int64')
    limit = int64(flintmax);
    unsafe = any(value(:) > limit | value(:) < -limit);
else
    unsafe = false;
end
if unsafe
    error(errorIdentifier, ...
        '%s contains integers outside double contiguous exact range.', label);
end
end
