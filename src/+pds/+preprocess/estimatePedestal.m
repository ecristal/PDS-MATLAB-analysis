function [pedestalLevel, diagnostics] = estimatePedestal(waveforms, options)
%ESTIMATEPEDESTAL Estimate one pedestal level per waveform.
%
% Rows are events and columns are samples. The pedestal region is explicit.

arguments
    waveforms {mustBeNumeric, mustBeReal, mustBeFinite}
    options.SampleIndices {mustBeNumeric, mustBeReal, mustBeFinite} = []
    options.Method (1, 1) string = "mean"
    options.BlockSize {mustBeNumeric, mustBeReal, mustBeFinite} = []
    options.MinimumQualitySampleCount {mustBeNumeric, mustBeReal, mustBeFinite} = 8
    options.NonstationarityThreshold {mustBeNumeric, mustBeReal, mustBeFinite} = 3
    options.OutlierThreshold {mustBeNumeric, mustBeReal, mustBeFinite} = 3.5
    options.MaximumOutlierFraction {mustBeNumeric, mustBeReal, mustBeFinite} = 0.1
    options.QualityBlockCount {mustBeNumeric, mustBeReal, mustBeFinite} = 4
    options.BlockLocationThreshold {mustBeNumeric, mustBeReal, mustBeFinite} = 3
    options.BlockScaleRatioThreshold {mustBeNumeric, mustBeReal, mustBeFinite} = 3
end

if isempty(waveforms) || ~ismatrix(waveforms)
    error('pds:preprocess:estimatePedestal:InvalidWaveforms', ...
        'Waveforms must be a nonempty two-dimensional numeric array.');
end
if iscolumn(waveforms) && numel(waveforms) > 1
    error('pds:preprocess:estimatePedestal:AmbiguousColumnVector', ...
        ['A column vector is ambiguous under the events-by-samples ' ...
        'contract; provide one waveform as a row vector.']);
end
if hasInexactIntegerValues(waveforms)
    error('pds:preprocess:estimatePedestal:InexactIntegerConversion', ...
        'Integer waveform values must be exactly representable as double.');
end
if isvector(waveforms)
    waveforms = reshape(waveforms, 1, []);
end
waveforms = double(waveforms);

sampleIndices = options.SampleIndices;
if isempty(sampleIndices)
    error('pds:preprocess:estimatePedestal:MissingSampleIndices', ...
        'SampleIndices must explicitly identify the pedestal region.');
end
if hasInexactIntegerValues(sampleIndices)
    error('pds:preprocess:estimatePedestal:InvalidSampleIndices', ...
        'SampleIndices must be exactly representable as double.');
end
sampleIndices = double(sampleIndices(:).');
if any(sampleIndices < 1 | sampleIndices > size(waveforms, 2) | ...
        sampleIndices ~= fix(sampleIndices)) || ...
        any(diff(sampleIndices) <= 0)
    error('pds:preprocess:estimatePedestal:InvalidSampleIndices', ...
        ['SampleIndices must contain strictly increasing integer sample ' ...
        'indices in range.']);
end

method = lower(options.Method);
pedestalSamples = waveforms(:, sampleIndices);
sampleCount = numel(sampleIndices);
[minimumQualitySampleCount, nonstationarityThreshold, ...
    outlierThreshold, maximumOutlierFraction, qualityBlockCount, ...
    blockLocationThreshold, blockScaleRatioThreshold] = ...
    validateQualityOptions(options.MinimumQualitySampleCount, ...
    options.NonstationarityThreshold, options.OutlierThreshold, ...
    options.MaximumOutlierFraction, options.QualityBlockCount, ...
    options.BlockLocationThreshold, options.BlockScaleRatioThreshold);
blockMeans = zeros(size(waveforms, 1), 0);
blockCount = 0;
blockSize = 0;

switch method
    case "mean"
        pedestalLevel = mean(pedestalSamples, 2);
        sampleNoiseSigma = std(pedestalSamples, 0, 2);
        pedestalStandardError = sampleNoiseSigma / sqrt(sampleCount);
    case "median"
        pedestalLevel = median(pedestalSamples, 2);
        sampleNoiseSigma = 1.4826 * median( ...
            abs(pedestalSamples - pedestalLevel), 2);
        pedestalStandardError = sqrt(pi / 2) * ...
            sampleNoiseSigma / sqrt(sampleCount);
    case "median-of-means"
        blockSize = validateBlockSize(options.BlockSize, sampleCount);
        blockCount = sampleCount / blockSize;
        blockMeans = zeros(size(waveforms, 1), blockCount);
        for blockIndex = 1:blockCount
            firstIndex = (blockIndex - 1) * blockSize + 1;
            localIndices = firstIndex:(firstIndex + blockSize - 1);
            blockMeans(:, blockIndex) = mean( ...
                pedestalSamples(:, localIndices), 2);
        end
        pedestalLevel = median(blockMeans, 2);
        sampleMedian = median(pedestalSamples, 2);
        sampleNoiseSigma = 1.4826 * median( ...
            abs(pedestalSamples - sampleMedian), 2);
        pedestalStandardError = NaN(size(pedestalLevel));
    otherwise
        error('pds:preprocess:estimatePedestal:UnknownMethod', ...
            'Unsupported pedestal method: %s.', options.Method);
end

[qualityStatistics, qualityFlags] = assessQuality( ...
    pedestalSamples, sampleIndices, minimumQualitySampleCount, ...
    nonstationarityThreshold, outlierThreshold, maximumOutlierFraction, ...
    qualityBlockCount, blockLocationThreshold, blockScaleRatioThreshold);

diagnostics = struct( ...
    'method', method, ...
    'sampleIndices', sampleIndices, ...
    'sampleCount', sampleCount, ...
    'sampleNoiseSigma', sampleNoiseSigma, ...
    'pedestalStandardError', pedestalStandardError, ...
    'blockSize', blockSize, ...
    'blockCount', blockCount, ...
    'blockMeans', blockMeans, ...
    'q25', qualityStatistics.q25, ...
    'q75', qualityStatistics.q75, ...
    'iqr', qualityStatistics.iqr, ...
    'mad', qualityStatistics.mad, ...
    'slopePerSample', qualityStatistics.slopePerSample, ...
    'nonstationarityScore', qualityStatistics.nonstationarityScore, ...
    'outlierFraction', qualityStatistics.outlierFraction, ...
    'qualityBlockMeans', qualityStatistics.blockMeans, ...
    'qualityBlockScales', qualityStatistics.blockScales, ...
    'effectiveQualityBlockCount', ...
        qualityStatistics.effectiveBlockCount, ...
    'blockLocationScore', qualityStatistics.blockLocationScore, ...
    'blockScaleRatio', qualityStatistics.blockScaleRatio, ...
    'qualityFlags', qualityFlags, ...
    'validEventMask', ~qualityFlags.insufficientSamples & ...
        ~qualityFlags.nonstationaryBaseline & ...
        ~qualityFlags.pretriggerContaminated & ...
        ~qualityFlags.excessiveOutliers & ...
        ~qualityFlags.unstableBlocks, ...
    'thresholds', struct( ...
        'minimumSampleCount', minimumQualitySampleCount, ...
        'nonstationarity', nonstationarityThreshold, ...
        'outlier', outlierThreshold, ...
        'maximumOutlierFraction', maximumOutlierFraction, ...
        'qualityBlockCount', qualityBlockCount, ...
        'blockLocation', blockLocationThreshold, ...
        'blockScaleRatio', blockScaleRatioThreshold));
end

function tf = hasInexactIntegerValues(value)
if isa(value, 'uint64')
    tf = any(value(:) > uint64(flintmax));
elseif isa(value, 'int64')
    limit = int64(flintmax);
    tf = any(value(:) > limit | value(:) < -limit);
else
    tf = false;
end
end

function blockSize = validateBlockSize(value, sampleCount)
if hasInexactIntegerValues(value)
    error('pds:preprocess:estimatePedestal:InvalidBlockSize', ...
        'BlockSize must be exactly representable as double.');
end
blockSize = double(value);
if ~isscalar(blockSize) || blockSize < 1 || ...
        blockSize ~= fix(blockSize) || mod(sampleCount, blockSize) ~= 0
    error('pds:preprocess:estimatePedestal:InvalidBlockSize', ...
        'BlockSize must be a positive integer divisor of the sample count.');
end
end


function [minimumSampleCount, nonstationarityThreshold, ...
        outlierThreshold, maximumOutlierFraction, qualityBlockCount, ...
        blockLocationThreshold, blockScaleRatioThreshold] = ...
        validateQualityOptions(minimumSampleCount, nonstationarityThreshold, ...
        outlierThreshold, maximumOutlierFraction, qualityBlockCount, ...
        blockLocationThreshold, blockScaleRatioThreshold)
validateExactQualityOption(minimumSampleCount, ...
    'InvalidMinimumQualitySampleCount', 'MinimumQualitySampleCount');
validateExactQualityOption(nonstationarityThreshold, ...
    'InvalidNonstationarityThreshold', 'NonstationarityThreshold');
validateExactQualityOption(outlierThreshold, ...
    'InvalidOutlierThreshold', 'OutlierThreshold');
validateExactQualityOption(maximumOutlierFraction, ...
    'InvalidMaximumOutlierFraction', 'MaximumOutlierFraction');
validateExactQualityOption(qualityBlockCount, ...
    'InvalidQualityBlockCount', 'QualityBlockCount');
validateExactQualityOption(blockLocationThreshold, ...
    'InvalidBlockLocationThreshold', 'BlockLocationThreshold');
validateExactQualityOption(blockScaleRatioThreshold, ...
    'InvalidBlockScaleRatioThreshold', 'BlockScaleRatioThreshold');
minimumSampleCount = double(minimumSampleCount);
nonstationarityThreshold = double(nonstationarityThreshold);
outlierThreshold = double(outlierThreshold);
maximumOutlierFraction = double(maximumOutlierFraction);
qualityBlockCount = double(qualityBlockCount);
blockLocationThreshold = double(blockLocationThreshold);
blockScaleRatioThreshold = double(blockScaleRatioThreshold);
if ~isscalar(minimumSampleCount) || minimumSampleCount < 2 || ...
        minimumSampleCount ~= fix(minimumSampleCount)
    error('pds:preprocess:estimatePedestal:InvalidMinimumQualitySampleCount', ...
        'MinimumQualitySampleCount must be an integer scalar of at least two.');
end
if ~isscalar(nonstationarityThreshold) || nonstationarityThreshold <= 0
    error('pds:preprocess:estimatePedestal:InvalidNonstationarityThreshold', ...
        'NonstationarityThreshold must be a positive scalar.');
end
if ~isscalar(outlierThreshold) || outlierThreshold <= 0
    error('pds:preprocess:estimatePedestal:InvalidOutlierThreshold', ...
        'OutlierThreshold must be a positive scalar.');
end
if ~isscalar(maximumOutlierFraction) || maximumOutlierFraction < 0 || ...
        maximumOutlierFraction > 1
    error('pds:preprocess:estimatePedestal:InvalidMaximumOutlierFraction', ...
        'MaximumOutlierFraction must be a scalar in the interval [0, 1].');
end
if ~isscalar(qualityBlockCount) || qualityBlockCount < 2 || ...
        qualityBlockCount ~= fix(qualityBlockCount)
    error('pds:preprocess:estimatePedestal:InvalidQualityBlockCount', ...
        'QualityBlockCount must be an integer scalar of at least two.');
end
if ~isscalar(blockLocationThreshold) || blockLocationThreshold <= 0
    error('pds:preprocess:estimatePedestal:InvalidBlockLocationThreshold', ...
        'BlockLocationThreshold must be a positive scalar.');
end
if ~isscalar(blockScaleRatioThreshold) || blockScaleRatioThreshold <= 1
    error('pds:preprocess:estimatePedestal:InvalidBlockScaleRatioThreshold', ...
        'BlockScaleRatioThreshold must be a scalar greater than one.');
end
end


function validateExactQualityOption(value, suffix, label)
if hasInexactIntegerValues(value)
    error("pds:preprocess:estimatePedestal:" + suffix, ...
        '%s must be exactly representable as double.', label);
end
end


function [statistics, flags] = assessQuality(samples, sampleIndices, ...
        minimumSampleCount, nonstationarityThreshold, outlierThreshold, ...
        maximumOutlierFraction, qualityBlockCount, ...
        blockLocationThreshold, blockScaleRatioThreshold)
q25 = prctile(samples, 25, 2);
q75 = prctile(samples, 75, 2);
sampleMedian = median(samples, 2);
madValue = median(abs(samples - sampleMedian), 2);

centeredIndices = sampleIndices - mean(sampleIndices);
[trendCenter, slope] = robustLinearTrend(samples, centeredIndices);
fitted = trendCenter + slope .* centeredIndices;
residual = samples - fitted;
residualMedian = median(residual, 2);
residualScale = 1.4826 * median(abs(residual - residualMedian), 2);
fallbackScale = std(residual, 0, 2);
fallbackScale(~isfinite(fallbackScale)) = 0;
scaleFloor = eps(max(1, max(abs(samples), [], 2)));
useFallback = residualScale <= scaleFloor;
residualScale(useFallback) = fallbackScale(useFallback);
residualScale = max(residualScale, scaleFloor);

trendExcursion = abs(slope) * (sampleIndices(end) - sampleIndices(1));
nonstationarityScore = trendExcursion ./ residualScale;
robustResidualZ = abs(residual - residualMedian) ./ residualScale;
outlierFraction = mean(robustResidualZ > outlierThreshold, 2);
insufficient = repmat(numel(sampleIndices) < minimumSampleCount, ...
    size(samples, 1), 1);
nonstationary = nonstationarityScore > nonstationarityThreshold;
contaminated = outlierFraction > 0;
excessiveOutliers = outlierFraction > maximumOutlierFraction;

effectiveBlockCount = min(qualityBlockCount, size(samples, 2));
[qualityBlockMeans, qualityBlockScales] = blockStatistics( ...
    samples, effectiveBlockCount);
blockLocationRange = max(qualityBlockMeans, [], 2) - ...
    min(qualityBlockMeans, [], 2);
blockLocationScore = blockLocationRange ./ residualScale;
positiveBlockScale = max(qualityBlockScales, scaleFloor);
blockScaleRatio = max(positiveBlockScale, [], 2) ./ ...
    min(positiveBlockScale, [], 2);
unstableBlocks = blockLocationScore > blockLocationThreshold | ...
    blockScaleRatio > blockScaleRatioThreshold;

statistics = struct( ...
    'q25', q25, ...
    'q75', q75, ...
    'iqr', q75 - q25, ...
    'mad', madValue, ...
    'slopePerSample', slope, ...
    'nonstationarityScore', nonstationarityScore, ...
    'outlierFraction', outlierFraction, ...
    'blockMeans', qualityBlockMeans, ...
    'blockScales', qualityBlockScales, ...
    'effectiveBlockCount', effectiveBlockCount, ...
    'blockLocationScore', blockLocationScore, ...
    'blockScaleRatio', blockScaleRatio);
flags = struct( ...
    'insufficientSamples', insufficient, ...
    'nonstationaryBaseline', nonstationary, ...
    'pretriggerContaminated', contaminated, ...
    'excessiveOutliers', excessiveOutliers, ...
    'unstableBlocks', unstableBlocks);
end


function [intercept, slope] = robustLinearTrend(samples, centeredIndices)
eventCount = size(samples, 1);
if numel(centeredIndices) < 2 || all(centeredIndices == 0)
    intercept = median(samples, 2);
    slope = zeros(eventCount, 1);
    return
end

indexEnergy = sum(centeredIndices.^2);
slope = (samples * centeredIndices.') / indexEnergy;
intercept = median(samples - slope .* centeredIndices, 2);
for iteration = 1:6
    residual = samples - (intercept + slope .* centeredIndices);
    residualMedian = median(residual, 2);
    residualScale = 1.4826 * median( ...
        abs(residual - residualMedian), 2);
    scaleFloor = eps(max(1, max(abs(samples), [], 2)));
    residualScale = max(residualScale, scaleFloor);
    standardizedResidual = (residual - residualMedian) ./ ...
        (4.685 * residualScale);
    weights = (abs(standardizedResidual) < 1) .* ...
        (1 - standardizedResidual.^2).^2;

    weightSum = sum(weights, 2);
    weightedIndexMean = sum(weights .* centeredIndices, 2) ./ ...
        max(weightSum, 1);
    weightedSampleMean = sum(weights .* samples, 2) ./ max(weightSum, 1);
    centeredWeightedIndices = centeredIndices - weightedIndexMean;
    denominator = sum(weights .* centeredWeightedIndices.^2, 2);
    numerator = sum(weights .* centeredWeightedIndices .* ...
        (samples - weightedSampleMean), 2);
    validFit = weightSum >= 2 & denominator > 0;
    slope(validFit) = numerator(validFit) ./ denominator(validFit);
    intercept(validFit) = weightedSampleMean(validFit) - ...
        slope(validFit) .* weightedIndexMean(validFit);
end
end


function [blockMeans, blockScales] = blockStatistics(samples, blockCount)
sampleCount = size(samples, 2);
edges = floor((0:blockCount) * sampleCount / blockCount) + 1;
blockMeans = zeros(size(samples, 1), blockCount);
blockScales = zeros(size(samples, 1), blockCount);
for blockIndex = 1:blockCount
    localIndices = edges(blockIndex):(edges(blockIndex + 1) - 1);
    localSamples = samples(:, localIndices);
    blockMeans(:, blockIndex) = mean(localSamples, 2);
    localMedian = median(localSamples, 2);
    robustScale = 1.4826 * median(abs(localSamples - localMedian), 2);
    fallbackScale = std(localSamples, 0, 2);
    fallbackScale(~isfinite(fallbackScale)) = 0;
    useFallback = robustScale <= eps(max(1, max(abs(localSamples), [], 2)));
    robustScale(useFallback) = fallbackScale(useFallback);
    blockScales(:, blockIndex) = robustScale;
end
end
