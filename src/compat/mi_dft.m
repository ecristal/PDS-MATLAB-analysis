function [frequencyHz, coefficients, powerSpectralDensity] = mi_dft( ...
        waveform, windowFunction, sampleRateHz, sampleShift)
%MI_DFT Deprecated compatibility wrapper for pds.signal.forwardDft.
%   This wrapper preserves the historical four-input/three-output signature,
%   while correcting the legacy window bug: WINDOWFUNCTION is now applied to
%   the waveform and used for PSD window-power normalization.

    warning('PDS:mi_dft:Deprecated', ...
        ['mi_dft is deprecated. Use pds.signal.forwardDft for transform ', ...
         'coefficients and pds.signal.estimateNoisePsd for PSD estimates.']);

    if ~isnumeric(sampleRateHz) || ~isscalar(sampleRateHz) || ...
            ~isreal(sampleRateHz) || ~isfinite(sampleRateHz) || sampleRateHz <= 0
        error('PDS:mi_dft:InvalidSampleRate', ...
            'sampleRateHz must be a finite positive real scalar.');
    end
    window = pds.signal.createWindow(numel(waveform), windowFunction);
    [coefficients, ~] = pds.signal.forwardDft( ...
        waveform, 1 / sampleRateHz, Window=window, SampleShift=sampleShift);
    frequencyHz = (0:(numel(waveform) - 1)) * ...
        (sampleRateHz / numel(waveform));
    powerSpectralDensity = abs(coefficients).^2 / ...
        (sampleRateHz * sum(window.^2));
end
