classdef TestGenerateEventTrain < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addProjectSource(testCase)
            repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            addpath(sourceDirectory);
            testCase.addTeardown(@() rmpath(sourceDirectory));
        end
    end

    methods (Test)
        function zeroRatesProduceOnlyExactReferenceAndCompleteTruth(testCase)
            [eventTrain, truth] = pds.simulation.generateEventTrain( ...
                16, 2e-9, EventCount=3, ReferenceIndex=7, ...
                ReferenceAmplitude=2.5, DarkRateHz=0, ...
                LargeEventRateHz=0, Seed=19);

            expected = zeros(3, 16);
            expected(:, 7) = 2.5;
            testCase.verifyEqual(eventTrain, expected, AbsTol=0);
            testCase.verifyEqual(truth.referenceComponent, expected, AbsTol=0);
            testCase.verifyEqual(truth.darkComponent, zeros(3, 16), AbsTol=0);
            testCase.verifyEqual(truth.largeEventComponent, ...
                zeros(3, 16), AbsTol=0);
            testCase.verifyEqual(truth.unsaturatedEventTrain, expected, AbsTol=0);
            testCase.verifyEqual(truth.saturationMask, false(3, 16));
            testCase.verifyEqual(truth.darkEventCount, zeros(3, 1));
            testCase.verifyEqual(truth.largeEventCount, zeros(3, 1));
            testCase.verifyEqual(truth.referenceIndex, 7);
            testCase.verifyEqual(truth.referenceAmplitude, 2.5);
            testCase.verifyEqual(truth.eventCount, 3);
            testCase.verifyEqual(truth.sampleCount, 16);
            testCase.verifyEqual(truth.samplePeriod, 2e-9);
            testCase.verifyEqual(truth.randomSource, "seed");
            testCase.verifyEqual(truth.seed, 19);
            testCase.verifyTrue(all(cellfun(@isempty, truth.darkEventIndices)));
            testCase.verifyTrue(all(cellfun(@isempty, truth.largeEventIndices)));
        end

        function poissonProcessesRemainSeparateAndSuperposeExactly(testCase)
            [eventTrain, truth] = pds.simulation.generateEventTrain( ...
                4, 0.1, EventCount=2, ReferenceIndex=2, ...
                ReferenceAmplitude=3, DarkRateHz=30, ...
                LargeEventRateHz=10, LargeAmplitude=8000, Seed=23);

            reconstructedDark = zeros(2, 4);
            reconstructedLarge = zeros(2, 4);
            for eventIndex = 1:2
                darkIndices = truth.darkEventIndices{eventIndex};
                darkAmplitudes = truth.darkEventAmplitudes{eventIndex};
                largeIndices = truth.largeEventIndices{eventIndex};
                largeAmplitudes = truth.largeEventAmplitudes{eventIndex};
                for occurrence = 1:numel(darkIndices)
                    reconstructedDark(eventIndex, darkIndices(occurrence)) = ...
                        reconstructedDark(eventIndex, darkIndices(occurrence)) + ...
                        darkAmplitudes(occurrence);
                end
                for occurrence = 1:numel(largeIndices)
                    reconstructedLarge(eventIndex, largeIndices(occurrence)) = ...
                        reconstructedLarge(eventIndex, largeIndices(occurrence)) + ...
                        largeAmplitudes(occurrence);
                end
                testCase.verifyEqual(darkAmplitudes, ...
                    ones(1, truth.darkEventCount(eventIndex)), AbsTol=0);
                testCase.verifyEqual(largeAmplitudes, ...
                    8000 * ones(1, truth.largeEventCount(eventIndex)), AbsTol=0);
                testCase.verifyGreaterThanOrEqual( ...
                    truth.darkEventTimesSeconds{eventIndex}, 0);
                testCase.verifyLessThan( ...
                    truth.darkEventTimesSeconds{eventIndex}, truth.durationSeconds);
                testCase.verifyGreaterThanOrEqual( ...
                    truth.largeEventTimesSeconds{eventIndex}, 0);
                testCase.verifyLessThan( ...
                    truth.largeEventTimesSeconds{eventIndex}, truth.durationSeconds);
            end

            testCase.verifyEqual(truth.darkComponent, reconstructedDark, AbsTol=0);
            testCase.verifyEqual(truth.largeEventComponent, ...
                reconstructedLarge, AbsTol=0);
            testCase.verifyEqual(truth.darkEventCount, ...
                cellfun(@numel, truth.darkEventIndices));
            testCase.verifyEqual(truth.largeEventCount, ...
                cellfun(@numel, truth.largeEventIndices));
            testCase.verifyEqual(truth.unsaturatedEventTrain, ...
                truth.referenceComponent + reconstructedDark + ...
                reconstructedLarge, AbsTol=0);
            testCase.verifyEqual(eventTrain, truth.unsaturatedEventTrain, AbsTol=0);
            testCase.verifyGreaterThan(max(reconstructedDark, [], 'all'), 1);
            testCase.verifyTrue(any(reconstructedLarge(:) > 0));
        end

        function localRngAndPoissonCountStatisticsAreTraceable(testCase)
            sampleCount = 64;
            samplePeriod = 5e-7;
            durationSeconds = sampleCount * samplePeriod;
            eventCount = 6000;
            darkRatesHz = [1e3, 1e4, 1e5];

            originalCallerState = rng;
            cleanup = onCleanup(@() rng(originalCallerState));
            rng(91, 'twister');
            callerState = rng;
            [firstTrain, firstTruth] = pds.simulation.generateEventTrain( ...
                128, 16e-9, EventCount=5, DarkRateHz=1e5, ...
                LargeEventRateHz=2e4, Seed=71);
            stateAfter = rng;
            [secondTrain, secondTruth] = pds.simulation.generateEventTrain( ...
                128, 16e-9, EventCount=5, DarkRateHz=1e5, ...
                LargeEventRateHz=2e4, Seed=71);
            testCase.verifyEqual(stateAfter, callerState);
            testCase.verifyEqual(secondTrain, firstTrain, AbsTol=0);
            testCase.verifyEqual(secondTruth.darkEventIndices, ...
                firstTruth.darkEventIndices);
            testCase.verifyEqual(secondTruth.largeEventIndices, ...
                firstTruth.largeEventIndices);

            for rateIndex = 1:numel(darkRatesHz)
                rateHz = darkRatesHz(rateIndex);
                [~, truth] = pds.simulation.generateEventTrain( ...
                    sampleCount, samplePeriod, EventCount=eventCount, ...
                    DarkRateHz=rateHz, Seed=100 + rateIndex);
                expectedCount = rateHz * durationSeconds;
                testCase.verifyEqual(truth.expectedDarkEventCount, ...
                    expectedCount, AbsTol=0);
                meanTolerance = 6 * sqrt(expectedCount / eventCount) + 0.01;
                varianceTolerance = 6 * sqrt( ...
                    (expectedCount + 2 * expectedCount^2) / eventCount) + 0.02;
                testCase.verifyEqual(mean(truth.darkEventCount), ...
                    expectedCount, AbsTol=meanTolerance);
                testCase.verifyEqual(var(truth.darkEventCount, 1), ...
                    expectedCount, AbsTol=varianceTolerance);
            end

            largeRateHz = 2e4;
            [~, largeTruth] = pds.simulation.generateEventTrain( ...
                sampleCount, samplePeriod, EventCount=eventCount, ...
                LargeEventRateHz=largeRateHz, Seed=205);
            expectedLargeCount = largeRateHz * durationSeconds;
            testCase.verifyEqual(largeTruth.expectedLargeEventCount, ...
                expectedLargeCount, AbsTol=0);
            testCase.verifyEqual(mean(largeTruth.largeEventCount), ...
                expectedLargeCount, AbsTol=0.08);
            testCase.verifyEqual(var(largeTruth.largeEventCount, 1), ...
                expectedLargeCount, AbsTol=0.12);
        end

        function largeAmplitudeModesAndExplicitSaturationPreserveTruth(testCase)
            fixedAmplitudes = [8000, 2^14, 20000];
            for amplitudeIndex = 1:numel(fixedAmplitudes)
                amplitude = fixedAmplitudes(amplitudeIndex);
                [eventTrain, truth] = pds.simulation.generateEventTrain( ...
                    4, 0.1, EventCount=2, ReferenceAmplitude=1, ...
                    LargeEventRateHz=20, LargeAmplitude=amplitude, ...
                    Seed=300 + amplitudeIndex);
                allLargeAmplitudes = [truth.largeEventAmplitudes{:}];
                testCase.verifyNotEmpty(allLargeAmplitudes);
                testCase.verifyEqual(allLargeAmplitudes, ...
                    amplitude * ones(size(allLargeAmplitudes)), AbsTol=0);
                testCase.verifyClass(eventTrain, 'double');
                testCase.verifyEqual(eventTrain, ...
                    truth.unsaturatedEventTrain, AbsTol=0);
                testCase.verifyFalse(any(truth.saturationMask, 'all'));
            end

            [uniformTrain, uniformTruth] = ...
                pds.simulation.generateEventTrain( ...
                8, 0.1, EventCount=5, LargeEventRateHz=20, ...
                LargeAmplitudeDistribution="uniform", ...
                LargeAmplitudeRange=[9000, 17000], Seed=401);
            uniformAmplitudes = [uniformTruth.largeEventAmplitudes{:}];
            testCase.verifyNotEmpty(uniformAmplitudes);
            testCase.verifyGreaterThanOrEqual(uniformAmplitudes, 9000);
            testCase.verifyLessThanOrEqual(uniformAmplitudes, 17000);
            testCase.verifyGreaterThan(max(uniformAmplitudes) - ...
                min(uniformAmplitudes), 0);
            testCase.verifyEqual(uniformTruth.largeAmplitudeDistribution, ...
                "uniform");
            testCase.verifyClass(uniformTrain, 'double');

            [saturated, saturationTruth] = ...
                pds.simulation.generateEventTrain( ...
                5, 1, ReferenceIndex=3, ReferenceAmplitude=20000, ...
                SaturationRange=[0, 16383], Seed=7);
            expectedUnsaturated = [0, 0, 20000, 0, 0];
            expectedSaturated = [0, 0, 16383, 0, 0];
            expectedMask = [false, false, true, false, false];
            testCase.verifyClass(saturated, 'double');
            testCase.verifyEqual(saturationTruth.unsaturatedEventTrain, ...
                expectedUnsaturated, AbsTol=0);
            testCase.verifyEqual(saturated, expectedSaturated, AbsTol=0);
            testCase.verifyEqual(saturationTruth.saturationMask, expectedMask);
            testCase.verifyEqual(saturationTruth.saturationRange, [0, 16383]);
        end

        function timeMappingOrderingAndPoissonIncrementsAreExplicit(testCase)
            sampleCount = 20;
            samplePeriod = 1e-3;
            eventCount = 5000;
            rateHz = 100;
            [~, truth] = pds.simulation.generateEventTrain( ...
                sampleCount, samplePeriod, EventCount=eventCount, ...
                DarkRateHz=rateHz, Seed=510);

            for eventIndex = 1:eventCount
                times = truth.darkEventTimesSeconds{eventIndex};
                indices = truth.darkEventIndices{eventIndex};
                testCase.verifyTrue(all(diff(times) > 0));
                testCase.verifyEqual(indices, ...
                    floor(times / samplePeriod) + 1, AbsTol=0);
            end

            firstHalfCount = sum(truth.darkComponent(:, 1:10), 2);
            secondHalfCount = sum(truth.darkComponent(:, 11:20), 2);
            expectedHalfCount = rateHz * 10 * samplePeriod;
            meanTolerance = 6 * sqrt(expectedHalfCount / eventCount) + 0.01;
            varianceTolerance = 6 * sqrt((expectedHalfCount + ...
                2 * expectedHalfCount^2) / eventCount) + 0.01;
            testCase.verifyEqual(mean(firstHalfCount), expectedHalfCount, ...
                AbsTol=meanTolerance);
            testCase.verifyEqual(mean(secondHalfCount), expectedHalfCount, ...
                AbsTol=meanTolerance);
            testCase.verifyEqual(var(firstHalfCount, 1), expectedHalfCount, ...
                AbsTol=varianceTolerance);
            testCase.verifyEqual(var(secondHalfCount, 1), expectedHalfCount, ...
                AbsTol=varianceTolerance);
            incrementCovariance = cov(firstHalfCount, secondHalfCount, 1);
            covarianceTolerance = 6 * sqrt( ...
                expectedHalfCount^2 / eventCount) + 0.01;
            testCase.verifyEqual(incrementCovariance(1, 2), 0, ...
                AbsTol=covarianceTolerance);
        end

        function unequalProcessesAreIndependentAndCanCollideWithTarget(testCase)
            sampleCount = 64;
            samplePeriod = 5e-7;
            eventCount = 6000;
            darkRateHz = 1e5;
            largeRateHz = 2e4;
            [~, truth] = pds.simulation.generateEventTrain( ...
                sampleCount, samplePeriod, EventCount=eventCount, ...
                DarkRateHz=darkRateHz, LargeEventRateHz=largeRateHz, ...
                Seed=520);

            expectedDark = darkRateHz * sampleCount * samplePeriod;
            expectedLarge = largeRateHz * sampleCount * samplePeriod;
            testCase.verifyEqual(mean(truth.darkEventCount), expectedDark, ...
                AbsTol=6 * sqrt(expectedDark / eventCount) + 0.01);
            testCase.verifyEqual(mean(truth.largeEventCount), expectedLarge, ...
                AbsTol=6 * sqrt(expectedLarge / eventCount) + 0.01);
            countCovariance = cov( ...
                truth.darkEventCount, truth.largeEventCount, 1);
            covarianceTolerance = 6 * sqrt( ...
                expectedDark * expectedLarge / eventCount) + 0.01;
            testCase.verifyEqual(countCovariance(1, 2), 0, ...
                AbsTol=covarianceTolerance);
            testCase.verifyEqual(truth.darkRateHz, darkRateHz);
            testCase.verifyEqual(truth.largeEventRateHz, largeRateHz);

            [collisionTrain, collisionTruth] = ...
                pds.simulation.generateEventTrain( ...
                1, 1, ReferenceIndex=1, ReferenceAmplitude=10, ...
                DarkRateHz=10, LargeEventRateHz=10, ...
                LargeAmplitude=100, Seed=521);
            testCase.verifyGreaterThan(collisionTruth.darkEventCount, 0);
            testCase.verifyGreaterThan(collisionTruth.largeEventCount, 0);
            testCase.verifyTrue(collisionTruth.darkEventMask(1));
            testCase.verifyTrue(collisionTruth.largeEventMask(1));
            testCase.verifyEqual(collisionTrain, ...
                collisionTruth.referenceComponent + ...
                collisionTruth.darkComponent + ...
                collisionTruth.largeEventComponent, AbsTol=0);
        end

        function safeIntegerInputsAndAllRandomSourcesAreEquivalent(testCase)
            [doubleTrain, doubleTruth] = pds.simulation.generateEventTrain( ...
                8, 1, EventCount=2, ReferenceIndex=3, ...
                ReferenceAmplitude=2, DarkRateHz=2, ...
                LargeEventRateHz=1, LargeAmplitude=8000, Seed=17);
            [integerTrain, integerTruth] = ...
                pds.simulation.generateEventTrain( ...
                uint8(8), uint8(1), EventCount=uint8(2), ...
                ReferenceIndex=uint8(3), ReferenceAmplitude=uint8(2), ...
                DarkRateHz=uint8(2), LargeEventRateHz=uint8(1), ...
                LargeAmplitude=uint16(8000), ...
                LargeAmplitudeRange=uint16([8000, 16000]), ...
                Seed=uint8(17));
            testCase.verifyEqual(integerTrain, doubleTrain, AbsTol=0);
            testCase.verifyEqual(integerTruth.darkEventIndices, ...
                doubleTruth.darkEventIndices);
            testCase.verifyEqual(integerTruth.largeEventAmplitudes, ...
                doubleTruth.largeEventAmplitudes);
            testCase.verifyClass(integerTrain, 'double');
            testCase.verifyClass(integerTruth.sampleCount, 'double');
            testCase.verifyClass(integerTruth.darkRateHz, 'double');

            originalCallerState = rng;
            cleanup = onCleanup(@() rng(originalCallerState));
            rng(777, 'twister');
            callerState = rng;
            [defaultA, defaultTruthA] = ...
                pds.simulation.generateEventTrain(8, 1, DarkRateHz=2);
            stateAfterDefault = rng;
            [defaultB, defaultTruthB] = ...
                pds.simulation.generateEventTrain(8, 1, DarkRateHz=2);
            suppliedStream = RandStream('mt19937ar', 'Seed', 31);
            pds.simulation.generateEventTrain( ...
                8, 1, DarkRateHz=2, RandomStream=suppliedStream);
            stateAfterStream = rng;

            testCase.verifyEqual(stateAfterDefault, callerState);
            testCase.verifyEqual(stateAfterStream, callerState);
            testCase.verifyEqual(defaultB, defaultA, AbsTol=0);
            testCase.verifyEqual(defaultTruthB.darkEventIndices, ...
                defaultTruthA.darkEventIndices);
            testCase.verifyEqual(defaultTruthA.randomSource, "default-seed");
            testCase.verifyEqual(defaultTruthA.seed, 0);
        end

        function saturationCoversLowerBoundaryAndPostCollisionClipping(testCase)
            [lowerClipped, lowerTruth] = ...
                pds.simulation.generateEventTrain( ...
                3, 1, ReferenceIndex=2, ReferenceAmplitude=15, ...
                SaturationRange=[10, 20]);
            testCase.verifyEqual(lowerTruth.unsaturatedEventTrain, [0, 15, 0]);
            testCase.verifyEqual(lowerClipped, [10, 15, 10]);
            testCase.verifyEqual(lowerTruth.saturationMask, ...
                [true, false, true]);

            [onBoundary, boundaryTruth] = ...
                pds.simulation.generateEventTrain( ...
                3, 1, ReferenceIndex=2, ReferenceAmplitude=20, ...
                SaturationRange=[0, 20]);
            testCase.verifyEqual(onBoundary, [0, 20, 0]);
            testCase.verifyFalse(any(boundaryTruth.saturationMask, 'all'));

            [collisionClipped, collisionTruth] = ...
                pds.simulation.generateEventTrain( ...
                1, 1, ReferenceAmplitude=10, DarkRateHz=10, ...
                LargeEventRateHz=10, LargeAmplitude=2000, ...
                SaturationRange=[0, 1000], Seed=530);
            testCase.verifyGreaterThan(collisionTruth.darkEventCount, 0);
            testCase.verifyGreaterThan(collisionTruth.largeEventCount, 0);
            testCase.verifyGreaterThan( ...
                collisionTruth.unsaturatedEventTrain, 1000);
            testCase.verifyEqual(collisionClipped, 1000);
            testCase.verifyTrue(collisionTruth.saturationMask);
            testCase.verifyEqual(collisionTruth.unsaturatedEventTrain, ...
                collisionTruth.referenceComponent + ...
                collisionTruth.darkComponent + ...
                collisionTruth.largeEventComponent, AbsTol=0);
        end

        function invalidRatesAmplitudesDimensionsAndRandomSourcesAreRejected(testCase)
            function callGenerator(varargin)
                pds.simulation.generateEventTrain(varargin{:});
            end

            testCase.verifyError(@() callGenerator(0, 1), ...
                'pds:simulation:generateEventTrain:InvalidSampleCount');
            testCase.verifyError(@() callGenerator(8, 0), ...
                'pds:simulation:generateEventTrain:InvalidSamplePeriod');
            testCase.verifyError(@() callGenerator(8, 1, EventCount=0), ...
                'pds:simulation:generateEventTrain:InvalidEventCount');
            testCase.verifyError(@() callGenerator(8, 1, ReferenceIndex=9), ...
                'pds:simulation:generateEventTrain:InvalidReferenceIndex');
            testCase.verifyError(@() callGenerator(8, 1, ReferenceAmplitude=-1), ...
                'pds:simulation:generateEventTrain:InvalidReferenceAmplitude');
            testCase.verifyError(@() callGenerator(8, 1, DarkRateHz=-1), ...
                'pds:simulation:generateEventTrain:InvalidDarkRateHz');
            testCase.verifyError(@() callGenerator(8, 1, LargeEventRateHz=Inf), ...
                'pds:simulation:generateEventTrain:InvalidLargeEventRateHz');
            testCase.verifyError(@() callGenerator(8, 1, LargeAmplitude=0), ...
                'pds:simulation:generateEventTrain:InvalidLargeAmplitude');
            testCase.verifyError(@() callGenerator(8, 1, ...
                LargeAmplitudeDistribution="uniform", ...
                LargeAmplitudeRange=[5, 4]), ...
                'pds:simulation:generateEventTrain:InvalidLargeAmplitudeRange');
            testCase.verifyError(@() callGenerator(8, 1, ...
                LargeAmplitudeDistribution="normal"), ...
                'pds:simulation:generateEventTrain:InvalidLargeAmplitudeDistribution');
            testCase.verifyError(@() callGenerator(8, 1, ...
                SaturationRange=[1, 0]), ...
                'pds:simulation:generateEventTrain:InvalidSaturationRange');
            testCase.verifyError(@() callGenerator(8, 1, Seed=-1), ...
                'pds:simulation:generateEventTrain:InvalidSeed');
            testCase.verifyError(@() callGenerator(8, 1, RandomStream=3), ...
                'pds:simulation:generateEventTrain:InvalidRandomStream');
            testCase.verifyError(@() callGenerator(8, 1, Seed=1, ...
                RandomStream=RandStream('mt19937ar', 'Seed', 1)), ...
                'pds:simulation:generateEventTrain:ConflictingRandomSource');
            unsafeInteger = uint64(flintmax) + uint64(1);
            testCase.verifyError(@() callGenerator(unsafeInteger, 1), ...
                'pds:simulation:generateEventTrain:InvalidSampleCount');
            testCase.verifyError(@() callGenerator(8, 1, Seed=unsafeInteger), ...
                'pds:simulation:generateEventTrain:InvalidSeed');
            testCase.verifyError(@() callGenerator(2, realmax), ...
                'pds:simulation:generateEventTrain:InvalidSamplePeriod');
        end

        function eventsBeforeFutureCropRemainMarkedAndStreamsReplay(testCase)
            futureCropStart = 6;
            streamA = RandStream('mt19937ar', 'Seed', 99);
            [firstTrain, firstTruth] = pds.simulation.generateEventTrain( ...
                20, 0.1, EventCount=2, DarkRateHz=100, ...
                LargeEventRateHz=100, RandomStream=streamA);
            streamB = RandStream('mt19937ar', 'Seed', 99);
            [secondTrain, secondTruth] = pds.simulation.generateEventTrain( ...
                20, 0.1, EventCount=2, DarkRateHz=100, ...
                LargeEventRateHz=100, RandomStream=streamB);

            testCase.verifyEqual(firstTrain, secondTrain, AbsTol=0);
            testCase.verifyEqual(firstTruth.darkEventIndices, ...
                secondTruth.darkEventIndices);
            testCase.verifyEqual(firstTruth.largeEventIndices, ...
                secondTruth.largeEventIndices);
            testCase.verifyEqual(firstTruth.randomSource, "stream");
            testCase.verifyEmpty(firstTruth.seed);
            testCase.verifyEqual(firstTruth.darkEventMask, ...
                firstTruth.darkComponent ~= 0);
            testCase.verifyEqual(firstTruth.largeEventMask, ...
                firstTruth.largeEventComponent ~= 0);
            testCase.verifyTrue(any(firstTruth.darkEventMask( ...
                :, 1:(futureCropStart - 1)), 'all'));
            testCase.verifyTrue(any(firstTruth.largeEventMask( ...
                :, 1:(futureCropStart - 1)), 'all'));
            allDarkIndices = [firstTruth.darkEventIndices{:}];
            allLargeIndices = [firstTruth.largeEventIndices{:}];
            testCase.verifyTrue(any(allDarkIndices < futureCropStart));
            testCase.verifyTrue(any(allLargeIndices < futureCropStart));
        end
