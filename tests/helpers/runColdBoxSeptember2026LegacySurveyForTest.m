function results = runColdBoxSeptember2026LegacySurveyForTest( ...
        repositoryRoot, coefficientPath, outputDirectory)
%RUNCOLDBOXSEPTEMBER2026LEGACYSURVEYFORTEST Analyze all M1--M6 channels.
%   Applies one legacy shaping/fit contract. The 2 MHz low-pass stage is
%   enabled only for M3 and M4, as declared by the acquisition analysis.

    sampleCount = 1024;
    recordCount = 30000;
    sampleRateHz = 62.5e6;
    samplePeriodSeconds = 1 / sampleRateHz;
    pedestalSampleCount = 100;
    quantileLimits = [0.15, 0.85];
    scoreHalfWidth = 1;
    scoreScale = 2;
    fitComponentCount = 6;
    binWidths = 0.02:0.01:0.05;
    lowPassOrder = 3;
    lowPassCutoffHz = 2e6;
    contractId = "coldbox-september2026-legacy-shaping-v1";

    modules = repelem((1:6).', 2);
    logicalChannels = repmat((1:2).', 6, 1);
    daphneChannels = [2; 3; 0; 1; 8; 9; 10; 11; 18; 19; 20; 21];
    lowPassPolicy = ismember(modules, [3, 4]);
    coefficients = loadLegacyCoefficients(coefficientPath);
    [lowPassNumerator, lowPassDenominator] = butter( ...
        lowPassOrder, lowPassCutoffHz / (sampleRateHz / 2), 'low');

    if ~isfolder(outputDirectory)
        mkdir(outputDirectory);
    end
    rows = cell(numel(modules), 41);
    fitDiagnostics = cell(numel(modules), 1);

    for caseIndex = 1:numel(modules)
        module = modules(caseIndex);
        logicalChannel = logicalChannels(caseIndex);
        daphneChannel = daphneChannels(caseIndex);
        moduleName = "M" + module;
        moduleDirectory = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
            'ColdBox', 'September2026', moduleName);
        archivePath = fullfile(moduleDirectory, ...
            "channel_" + daphneChannel + ".7z");
        archiveMember = "channel_" + daphneChannel + ".dat";
        configPath = fullfile(moduleDirectory, 'config.txt');
        acquisition = readAcquisitionConfiguration(configPath, ...
            daphneChannel);
        archiveSha256 = sha256File(archivePath);

        data = readColdBoxArchive(archivePath, archiveMember, ...
            sampleCount, recordCount);
        rmsValues = rms(data, 2);
        rmsLimits = quantile(rmsValues, quantileLimits);
        rmsMask = rmsValues >= rmsLimits(1) & rmsValues <= rmsLimits(2);
        data = data(rmsMask, :);

        pedestal = pds.preprocess.estimatePedestal(data, ...
            SampleIndices=1:pedestalSampleCount, Method="mean");
        pedestalLimits = quantile(pedestal, quantileLimits);
        pedestalMask = pedestal >= pedestalLimits(1) & ...
            pedestal <= pedestalLimits(2);
        data = data(pedestalMask, :);
        pedestal = pedestal(pedestalMask);
        corrected = pds.preprocess.subtractPedestal(data, pedestal);
        clear data;

        if lowPassPolicy(caseIndex)
            shaped = filter(lowPassNumerator, lowPassDenominator, ...
                corrected, [], 2);
            configuredCutoffHz = lowPassCutoffHz;
            configuredOrder = lowPassOrder;
        else
            shaped = corrected;
            configuredCutoffHz = 0;
            configuredOrder = 0;
        end
        shaped = filter(coefficients.integratorNumerator, ...
            coefficients.integratorDenominator, shaped, [], 2);
        shaped = filter(coefficients.movingMeanNumerator, ...
            coefficients.movingMeanDenominator, shaped, [], 2);

        meanShaped = mean(shaped, 1);
        [normalizationScale, peakIndex] = max(meanShaped);
        if peakIndex <= scoreHalfWidth || ...
                peakIndex > sampleCount - scoreHalfWidth
            error('PDS:test:ColdBoxSurveyPeakAtBoundary', ...
                'M%d CH%d cannot support the configured score window.', ...
                module, logicalChannel);
        end
        scoreIndices = (peakIndex - scoreHalfWidth): ...
            (peakIndex + scoreHalfWidth);
        scores = scoreScale * mean(shaped(:, scoreIndices), 2) / ...
            normalizationScale;
        clear shaped;

        fitResult = fitLegacyHistogram(scores, binWidths, ...
            fitComponentCount);
        fitValid = fitResult.completed && ...
            fitResult.delta > 0.5 && fitResult.delta < 1.5 && ...
            fitResult.sigma0 > 0 && fitResult.sigma0 < 0.75 && ...
            fitResult.rSquare > 0.95;
        nominalSnr = fitResult.snr;
        if fitValid
            measurementSnr = nominalSnr;
        else
            measurementSnr = NaN;
        end
        nominalPeStructure = fitResult.completed && ...
            fitResult.delta > 0.5 && fitResult.delta < 1.5 && ...
            fitResult.sigma0 > 0 && fitResult.sigma0 < 0.75 && ...
            nominalSnr >= 3;
        if fitValid && nominalSnr >= 3
            separationAssessment = "resolved";
        elseif nominalPeStructure
            separationAssessment = "resolved-fit-failed";
        elseif fitResult.completed
            separationAssessment = "ambiguous";
        else
            separationAssessment = "unresolved";
        end

        baseName = sprintf('M%d_CH%d_channel_%d', ...
            module, logicalChannel, daphneChannel);
        histogramPath = fullfile(outputDirectory, ...
            baseName + "_histogram.png");
        singlePePath = fullfile(outputDirectory, ...
            baseName + "_average_single_pe.png");
        singlePeCsvPath = fullfile(outputDirectory, ...
            baseName + "_average_single_pe.csv");
        titleLine = sprintf(['VBIAS=%d - VGAIN %d - ', ...
            'Module M%d CH%d'], acquisition.biasRequested, ...
            acquisition.vgainRequested, module, logicalChannel);
        histogramTitle = "Histogram - COLDBOX SEPT 2026\\n" + ...
            string(titleLine);
        singlePeTitle = "Average single P.E. - COLDBOX SEPT 2026\\n" + ...
            string(titleLine);

        createHistogramPlot(fitResult, fitValid, separationAssessment, ...
            histogramPath, titleLine);
        [singlePeCount, singlePePeak, singlePePeakToPeak, ...
            singlePeSelectionStatus] = ...
            createSinglePePlot(corrected, fitResult, fitValid, ...
            lowPassPolicy(caseIndex), lowPassNumerator, ...
            lowPassDenominator, samplePeriodSeconds, singlePePath, ...
            singlePeCsvPath, titleLine);
        clear corrected;

        fitDiagnostics{caseIndex} = fitResult;
        rows(caseIndex, :) = { ...
            module, logicalChannel, daphneChannel, acquisition.afe, ...
            acquisition.biasRequested, acquisition.vgainRequested, ...
            acquisition.timestampUtc, contractId, string(archivePath), ...
            string(archiveSha256), recordCount, numel(scores), sampleCount, ...
            sampleRateHz, pedestalSampleCount, "mean", ...
            lowPassPolicy(caseIndex), configuredOrder, ...
            configuredCutoffHz, peakIndex, fitResult.rawBinWidth, ...
            fitResult.normalizationPeak, fitResult.mu0, fitResult.sigma0, ...
            fitResult.mu1, fitResult.sigma1, fitResult.delta, nominalSnr, ...
            measurementSnr, fitResult.rSquare, fitValid, ...
            separationAssessment, singlePeCount, singlePePeak, ...
            singlePePeakToPeak, singlePeSelectionStatus, ...
            histogramTitle, singlePeTitle, ...
            string(histogramPath), string(singlePePath), ...
            string(singlePeCsvPath)};
    end

    variableNames = {'Module', 'LogicalChannel', 'DaphneChannel', 'Afe', ...
        'BiasRequested', 'VgainRequested', 'TimestampUtc', 'ContractId', ...
        'ArchivePath', 'ArchiveSha256', 'RecordCount', 'SelectedCount', ...
        'SampleCount', 'SampleRateHz', 'PedestalSampleCount', ...
        'PedestalMethod', 'LowPassApplied', 'LowPassOrder', ...
        'LowPassCutoffHz', 'PeakIndex', 'SelectedRawBinWidth', ...
        'NormalizationPeak', 'Mu0', 'Sigma0', 'Mu1', 'Sigma1', ...
        'Delta', 'NominalSNR', 'SNR', 'FitRSquare', 'FitValid', ...
        'SeparationAssessment', 'SinglePeCount', 'SinglePePeak', ...
        'SinglePePeakToPeak', 'SinglePeSelectionStatus', ...
        'HistogramTitle', 'SinglePeTitle', ...
        'HistogramPlotPath', 'SinglePePlotPath', 'SinglePeCsvPath'};
    results = cell2table(rows, 'VariableNames', variableNames);
    writetable(results, fullfile(outputDirectory, 'summary.csv'));
    save(fullfile(outputDirectory, 'summary.mat'), 'results', ...
        'fitDiagnostics', 'binWidths');
    writeMarkdownSynthesis(results, fullfile(outputDirectory, 'summary.md'));
    createMontage(results.HistogramPlotPath, ...
        fullfile(outputDirectory, 'histograms_montage.png'), ...
        'Histogramas legacy - COLDBOX SEPT 2026');
    createMontage(results.SinglePePlotPath, ...
        fullfile(outputDirectory, 'average_single_pe_montage.png'), ...
        'Average single P.E. - COLDBOX SEPT 2026');
end

function fitResult = fitLegacyHistogram(scores, binWidths, componentCount)
    trialSnr = NaN(size(binWidths));
    trialCenters = cell(size(binWidths));
    for index = 1:numel(binWidths)
        figureHandle = figure('Visible', 'off');
        cleanupFigure = onCleanup(@() closeIfValid(figureHandle));
        try
            [~, ~, ~, ~, ~, snr, ~, ~, ~, centers] = ...
                gaussian_fit_SNR(scores, binWidths(index), 0.8, -0.5, ...
                -0.25, 4, -0.5, 0.5, 0.3, componentCount, 45);
            if isfinite(snr) && numel(centers) >= 2 && centers(2) ~= 0
                trialSnr(index) = snr;
                trialCenters{index} = centers;
            end
        catch
            % A failed trial cannot be selected.
        end
        clear cleanupFigure;
    end

    validTrials = find(isfinite(trialSnr));
    if isempty(validTrials)
        fitResult = emptyFitResult(scores, binWidths(1));
        return;
    end
    [~, relativeBestIndex] = max(trialSnr(validTrials));
    bestIndex = validTrials(relativeBestIndex);
    selectedCenters = trialCenters{bestIndex};
    normalizationPeak = selectedCenters(2);
    normalizedScores = scores / normalizationPeak;
    normalizedBinWidth = binWidths(bestIndex) / normalizationPeak;

    figureHandle = figure('Visible', 'off');
    cleanupFigure = onCleanup(@() closeIfValid(figureHandle));
    try
        [mu0, sigma0, mu1, sigma1, delta, snr, evaluationAxis, ...
            fittedCurve, rSquare, finalCenters] = gaussian_fit_SNR( ...
            normalizedScores, normalizedBinWidth, ...
            0.8 / normalizationPeak, -0.5, ...
            -0.25 / normalizationPeak, 4 / normalizationPeak, ...
            -0.5, 0.5, 0.3, componentCount, 45);
        completed = all(isfinite([mu0, sigma0, mu1, sigma1, delta, ...
            snr, rSquare]));
    catch
        mu0 = NaN;
        sigma0 = NaN;
        mu1 = NaN;
        sigma1 = NaN;
        delta = NaN;
        snr = NaN;
        rSquare = NaN;
        evaluationAxis = [];
        fittedCurve = [];
        finalCenters = [];
        completed = false;
    end
    clear cleanupFigure;

    fitResult = struct( ...
        'completed', completed, ...
        'scores', normalizedScores, ...
        'rawBinWidth', binWidths(bestIndex), ...
        'normalizedBinWidth', normalizedBinWidth, ...
        'normalizationPeak', normalizationPeak, ...
        'mu0', mu0, ...
        'sigma0', sigma0, ...
        'mu1', mu1, ...
        'sigma1', sigma1, ...
        'delta', delta, ...
        'snr', snr, ...
        'rSquare', rSquare, ...
        'evaluationAxis', evaluationAxis, ...
        'fittedCurve', fittedCurve, ...
        'finalCenters', finalCenters, ...
        'trialSnr', trialSnr, ...
        'trialCenters', {trialCenters});
end

function result = emptyFitResult(scores, binWidth)
    result = struct( ...
        'completed', false, ...
        'scores', scores, ...
        'rawBinWidth', binWidth, ...
        'normalizedBinWidth', binWidth, ...
        'normalizationPeak', NaN, ...
        'mu0', NaN, 'sigma0', NaN, 'mu1', NaN, 'sigma1', NaN, ...
        'delta', NaN, 'snr', NaN, 'rSquare', NaN, ...
        'evaluationAxis', [], 'fittedCurve', [], 'finalCenters', [], ...
        'trialSnr', NaN, 'trialCenters', {{}});
end

function createHistogramPlot(fitResult, fitValid, assessment, ...
        outputPath, titleLine)
    figureHandle = figure('Visible', 'off', ...
        'Position', [100, 100, 1100, 700]);
    cleanupFigure = onCleanup(@() closeIfValid(figureHandle));
    histogram(fitResult.scores, 'BinWidth', fitResult.normalizedBinWidth, ...
        'DisplayStyle', 'stairs', 'LineWidth', 2, ...
        'EdgeColor', [0, 0.4470, 0.7410]);
    hold on;
    if fitResult.completed
        plot(fitResult.evaluationAxis, fitResult.fittedCurve, ...
            'r', 'LineWidth', 1.25);
        xline(fitResult.mu0, 'r--');
        xline(fitResult.mu0 - fitResult.sigma0, 'b--');
        xline(fitResult.mu0 + fitResult.sigma0, 'b--');
        xline(fitResult.mu1, 'r--');
    end
    grid on;
    xlabel('Amplitud normalizada [PE]');
    ylabel('Entradas');
    title({'{\bf Histogram - COLDBOX SEPT 2026}', titleLine}, ...
        'Interpreter', 'tex');
    xlim([-0.5, 4.5]);
    if fitValid
        annotationText = sprintf(['\\Delta = %.4f\n\\sigma_0 = %.5f\n', ...
            'SNR = %.4f\n%s'], fitResult.delta, fitResult.sigma0, ...
            fitResult.snr, assessment);
    elseif fitResult.completed
        annotationText = sprintf(['FIT NO VALIDO\nSNR nominal = %.4f\n', ...
            'R^2 = %.4f\n%s'], fitResult.snr, fitResult.rSquare, assessment);
    else
        annotationText = sprintf('FIT NO DISPONIBLE\n%s', assessment);
    end
    annotation('textbox', [0.67, 0.66, 0.2, 0.2], ...
        'Interpreter', 'tex', 'String', annotationText, ...
        'FitBoxToText', 'on');
    overwriteExport(figureHandle, outputPath);
end

function [count, peak, peakToPeak, selectionStatus] = ...
        createSinglePePlot(corrected, ...
        fitResult, fitValid, applyLowPass, lowPassNumerator, ...
        lowPassDenominator, samplePeriodSeconds, outputPath, csvPath, ...
        titleLine)
    figureHandle = figure('Visible', 'off', ...
        'Position', [100, 100, 1100, 700]);
    cleanupFigure = onCleanup(@() closeIfValid(figureHandle));
    timeMicroseconds = (0:(size(corrected, 2) - 1)) * ...
        samplePeriodSeconds * 1e6;

    selectionUsable = fitResult.completed && isfinite(fitResult.mu1) && ...
        isfinite(fitResult.sigma1) && fitResult.sigma1 > 0;
    if selectionUsable
        singlePeMask = abs(fitResult.scores - fitResult.mu1) <= ...
            2 * fitResult.sigma1;
        count = sum(singlePeMask);
        if fitValid
            selectionStatus = "validated";
        else
            selectionStatus = "nominal-fit-failed";
        end
    else
        singlePeMask = false(size(fitResult.scores));
        count = 0;
        selectionStatus = "unavailable";
    end

    if count >= 10
        rawAverage = mean(corrected(singlePeMask, :), 1);
        if applyLowPass
            displayedAverage = filter(lowPassNumerator, ...
                lowPassDenominator, rawAverage);
            plot(timeMicroseconds, rawAverage, 'Color', [0.65, 0.65, 0.65], ...
                'LineWidth', 0.8, 'DisplayName', 'Promedio sin low-pass');
            hold on;
            plot(timeMicroseconds, displayedAverage, 'b', 'LineWidth', 1.5, ...
                'DisplayName', 'Promedio con low-pass 2 MHz');
            legend('Location', 'best');
        else
            displayedAverage = rawAverage;
            plot(timeMicroseconds, displayedAverage, 'b', 'LineWidth', 1.5);
        end
        [peak, peakIndex] = max(displayedAverage);
        peakToPeak = max(displayedAverage) - min(displayedAverage);
        xline(timeMicroseconds(peakIndex), 'r--');
        outputTable = table((0:(numel(rawAverage) - 1)).', ...
            timeMicroseconds.', rawAverage.', displayedAverage.', ...
            'VariableNames', {'SampleIndexZeroBased', 'TimeMicroseconds', ...
            'RawAverageAdu', 'DisplayedAverageAdu'});
        writetable(outputTable, csvPath);
        if fitValid
            statusText = 'Seleccion validada';
        else
            statusText = 'Seleccion nominal; fit no valido';
        end
        annotationText = sprintf(['%s\nEventos single-P.E. = %d\n', ...
            'Peak = %.3f ADU\nPeak-to-peak = %.3f ADU'], ...
            statusText, count, peak, peakToPeak);
    else
        peak = NaN;
        peakToPeak = NaN;
        axis([0, timeMicroseconds(end), -1, 1]);
        text(0.5 * timeMicroseconds(end), 0, ...
            {'Average single P.E. no disponible', ...
            'El ajuste/clasificacion no es valido'}, ...
            'HorizontalAlignment', 'center', 'FontWeight', 'bold');
        outputTable = table([], [], [], [], ...
            'VariableNames', {'SampleIndexZeroBased', 'TimeMicroseconds', ...
            'RawAverageAdu', 'DisplayedAverageAdu'});
        writetable(outputTable, csvPath);
        annotationText = 'Single-P.E. no definido';
    end
    grid on;
    xlabel('Tiempo [\mus]');
    ylabel('ADU');
    title({'{\bf Average single P.E. - COLDBOX SEPT 2026}', titleLine}, ...
        'Interpreter', 'tex');
    annotation('textbox', [0.62, 0.68, 0.22, 0.15], ...
        'String', annotationText, 'FitBoxToText', 'on');
    overwriteExport(figureHandle, outputPath);
end

function acquisition = readAcquisitionConfiguration(configPath, channel)
    text = fileread(configPath);
    configuredChannels = sscanf(extractValue(text, 'channels'), '%d').';
    if ~ismember(channel, configuredChannels)
        error('PDS:test:ColdBoxSurveyChannelMismatch', ...
            'Channel %d is not declared in %s.', channel, configPath);
    end
    acquisition = struct( ...
        'timestampUtc', string(extractValue(text, 'timestamp_utc')), ...
        'afe', str2double(extractValue(text, 'afe')), ...
        'biasRequested', str2double(extractValue(text, 'bias_requested')), ...
        'vgainRequested', str2double(extractValue(text, 'vgain_requested')));
    values = [acquisition.afe, acquisition.biasRequested, ...
        acquisition.vgainRequested];
    if any(~isfinite(values))
        error('PDS:test:ColdBoxSurveyInvalidConfiguration', ...
            'Configuration contains invalid numeric fields: %s.', configPath);
    end
end

function value = extractValue(text, key)
    token = regexp(text, ['(?m)^', regexptranslate('escape', key), ...
        '=([^\r\n]+)$'], 'tokens', 'once');
    if isempty(token)
        error('PDS:test:ColdBoxSurveyMissingConfigurationKey', ...
            'Missing configuration key: %s.', key);
    end
    value = strtrim(token{1});
end

function coefficients = loadLegacyCoefficients(path)
    required = {'numz_planta_integrator', 'denz_planta_integrator', ...
        'numz_planta_movmean_hpk', 'denz_planta_movmean_hpk'};
    contents = load(path, required{:});
    for index = 1:numel(required)
        name = required{index};
        if ~isfield(contents, name) || ~isnumeric(contents.(name)) || ...
                ~isvector(contents.(name)) || any(~isfinite(contents.(name)))
            error('PDS:test:InvalidLegacyFilterCoefficients', ...
                'Invalid or missing coefficient vector: %s.', name);
        end
    end
    coefficients = struct( ...
        'integratorNumerator', contents.numz_planta_integrator, ...
        'integratorDenominator', contents.denz_planta_integrator, ...
        'movingMeanNumerator', contents.numz_planta_movmean_hpk, ...
        'movingMeanDenominator', contents.denz_planta_movmean_hpk);
end

function data = readColdBoxArchive(archivePath, expectedMember, ...
        sampleCount, expectedRecordCount)
    sevenZipPath = 'C:\Program Files\7-Zip\7z.exe';
    if ~isfile(sevenZipPath)
        error('PDS:test:SevenZipMissing', ...
            '7-Zip executable not found: %s', sevenZipPath);
    end
    extractionDirectory = tempname;
    mkdir(extractionDirectory);
    cleanupDirectory = onCleanup(@() removeDirectory(extractionDirectory));

    listCommand = sprintf('"%s" l -slt "%s"', sevenZipPath, archivePath);
    [listStatus, listing] = system(listCommand);
    if listStatus ~= 0
        error('PDS:test:ColdBoxArchiveListFailed', ...
            '7-Zip could not list %s (status %d): %s', ...
            archivePath, listStatus, listing);
    end
    pathTokens = regexp(listing, '(?m)^Path = ([^\r\n]+)', 'tokens');
    listedPaths = string(cellfun(@(token) strtrim(token{1}), ...
        pathTokens, 'UniformOutput', false));
    if numel(listedPaths) ~= 2 || listedPaths(2) ~= expectedMember
        error('PDS:test:UnexpectedColdBoxArchiveContents', ...
            'Archive %s must contain only %s.', archivePath, expectedMember);
    end
    expectedByteCount = expectedRecordCount * sampleCount * 2;
    sizeTokens = regexp(listing, '(?m)^Size = (\d+)', 'tokens');
    if numel(sizeTokens) ~= 1 || str2double(sizeTokens{1}{1}) ~= expectedByteCount
        error('PDS:test:UnexpectedColdBoxArchiveSize', ...
            'Archive member %s must contain %d bytes.', ...
            expectedMember, expectedByteCount);
    end

    extractCommand = sprintf('"%s" x -y -o"%s" "%s"', ...
        sevenZipPath, extractionDirectory, archivePath);
    [extractStatus, message] = system(extractCommand);
    if extractStatus ~= 0
        error('PDS:test:ColdBoxExtractionFailed', ...
            '7-Zip failed with status %d: %s', extractStatus, message);
    end
    dataPath = fullfile(extractionDirectory, expectedMember);
    fileIdentifier = fopen(dataPath, 'r', 'ieee-le');
    if fileIdentifier < 0
        error('PDS:test:ColdBoxDataOpenFailed', ...
            'Unable to open extracted data: %s', dataPath);
    end
    cleanupFile = onCleanup(@() fclose(fileIdentifier));
    rawSamples = fread(fileIdentifier, Inf, 'uint16=>double');
    clear cleanupFile;
    if numel(rawSamples) ~= expectedByteCount / 2
        error('PDS:test:UnexpectedColdBoxDataSize', ...
            'Extracted member %s has an unexpected sample count.', ...
            expectedMember);
    end
    data = reshape(rawSamples, sampleCount, []).';
end

function digest = sha256File(filePath)
    fileIdentifier = fopen(filePath, 'rb');
    if fileIdentifier < 0
        error('PDS:test:ColdBoxSurveyHashOpenFailed', ...
            'Unable to hash %s.', filePath);
    end
    cleanupFile = onCleanup(@() fclose(fileIdentifier));
    bytes = fread(fileIdentifier, Inf, '*uint8');
    engine = java.security.MessageDigest.getInstance('SHA-256');
    engine.update(bytes);
    digestBytes = typecast(engine.digest(), 'uint8');
    digest = lower(reshape(dec2hex(digestBytes, 2).', 1, []));
end

function createMontage(paths, outputPath, heading)
    figureHandle = figure('Visible', 'off', ...
        'Position', [100, 100, 1800, 2100]);
    cleanupFigure = onCleanup(@() closeIfValid(figureHandle));
    layout = tiledlayout(6, 2, 'TileSpacing', 'compact', ...
        'Padding', 'compact');
    for index = 1:numel(paths)
        nexttile(layout);
        image(imread(paths(index)));
        axis image off;
    end
    title(layout, heading, 'FontWeight', 'bold');
    overwriteExport(figureHandle, outputPath);
end

function writeMarkdownSynthesis(results, outputPath)
    fileIdentifier = fopen(outputPath, 'w');
    if fileIdentifier < 0
        error('PDS:test:ColdBoxSurveySummaryOpenFailed', ...
            'Unable to create %s.', outputPath);
    end
    cleanupFile = onCleanup(@() fclose(fileIdentifier));
    fprintf(fileIdentifier, '# ColdBox September 2026: legacy survey M1--M6\n\n');
    fprintf(fileIdentifier, ['Status: exploratory acquisition-specific ', ...
        'measurement. SNR = (mu1-mu0)/sigma0.\n\n']);
    fprintf(fileIdentifier, ['The 2 MHz low-pass is applied only to M3 and ', ...
        'M4. All cases use samples 1:100 for the mean pedestal, 15--85%% ', ...
        'RMS/pedestal cuts, the legacy integrator/moving-mean chain, and ', ...
        'the same Gaussian-fit procedure.\n\n']);
    fprintf(fileIdentifier, ['| Module | Logical CH | DAPHNE CH | VBIAS | ', ...
        'Low-pass | Selected | SNR | Nominal SNR | R^2 | Status | ', ...
        'single-P.E. events |\n']);
    fprintf(fileIdentifier, ...
        '|---:|---:|---:|---:|:---:|---:|---:|---:|---:|---|---:|\n');
    for index = 1:height(results)
        fprintf(fileIdentifier, ...
            '| M%d | %d | %d | %d | %d | %d | %s | %.6f | %.6f | %s | %d |\n', ...
            results.Module(index), results.LogicalChannel(index), ...
            results.DaphneChannel(index), results.BiasRequested(index), ...
            results.LowPassApplied(index), results.SelectedCount(index), ...
            formatMetric(results.SNR(index)), results.NominalSNR(index), ...
            results.FitRSquare(index), results.SeparationAssessment(index), ...
            results.SinglePeCount(index));
    end
    fprintf(fileIdentifier, '\nSummary:\n\n');
    fprintf(fileIdentifier, '- Valid fits: %d/%d.\n', ...
        sum(results.FitValid), height(results));
    fprintf(fileIdentifier, '- Resolved channels: %d/%d.\n', ...
        sum(results.SeparationAssessment == "resolved"), height(results));
    fprintf(fileIdentifier, ['- M5/M6 record VBIAS=0 in the DAC ', ...
        'configuration. The analysis reports their observed peak ', ...
        'structure without interpreting that DAC code as a physical ', ...
        'zero-bias condition.\n']);
    fprintf(fileIdentifier, ['- Invalid/ambiguous fits carry NaN in SNR; ', ...
        'their attempted values remain in NominalSNR for diagnostics.\n']);
end

function text = formatMetric(value)
    if isnan(value)
        text = "NaN";
    else
        text = string(sprintf('%.6f', value));
    end
end

function overwriteExport(figureHandle, outputPath)
    if isfile(outputPath)
        delete(outputPath);
    end
    exportgraphics(figureHandle, outputPath, 'Resolution', 180);
end

function closeIfValid(figureHandle)
    if isgraphics(figureHandle)
        close(figureHandle);
    end
end

function removeDirectory(directory)
    if isfolder(directory)
        rmdir(directory, 's');
    end
end
