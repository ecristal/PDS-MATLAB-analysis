function results = runColdBoxM3OptimalFilterContractForTest( ...
        repositoryRoot, coefficientPath, outputDirectory)
%RUNCOLDBOXM3OPTIMALFILTERCONTRACTFORTEST Apply one frozen M3 contract.
%   Odd records train alignment, pedestal candidates, covariance, and score
%   normalization. Even records are evaluated once with fixed settings.

    contractId = "coldbox-m3-covariance-optimal-v1";
    sampleCount = 1024;
    recordCount = 30000;
    sampleRateHz = 62.5e6;
    pedestalSampleCount = 100;
    pedestalMethod = "median-of-means";
    pedestalBlockSize = 10;
    quantileLimits = [0.15, 0.85];
    filterLength = 128;
    samplesBeforePeak = 10;
    shrinkageFraction = 1e-4;
    priorWeight = 0.25;
    dedicatedNoiseRecordCount = 50000;
    dedicatedNoiseWindowStart = 501;
    normalizedBinWidth = 0.02;
    legacyBaselines = [5.81407875093461; 4.19146707701183];
    cases = { ...
        "November2025", 28, "channel_28.7z", "channel_28.dat"; ...
        "September2026", 8, "channel_8.7z", "channel_8.dat"};

    coefficients = loadLegacyCoefficients(coefficientPath);
    [lowPassNumerator, lowPassDenominator] = butter( ...
        3, 2e6 / (sampleRateHz / 2), 'low');
    templatePath = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
        'ColdBox', 'Template', 'M3', 'template.csv');
    reference = readmatrix(templatePath);
    if ~isnumeric(reference) || numel(reference) ~= sampleCount || ...
            any(~isfinite(reference(:))) || ~isreal(reference)
        error('PDS:test:InvalidColdBoxTemplate', ...
            'The M3 template must contain 1024 finite real samples.');
    end
    reference = double(reference(:).');
    referencePedestal = pds.preprocess.estimatePedestal( ...
        reference, SampleIndices=1:pedestalSampleCount, ...
        Method=pedestalMethod, BlockSize=pedestalBlockSize);
    reference = pds.preprocess.subtractPedestal( ...
        reference, referencePedestal);
    shapedReference = applyLegacyShaping(reference, ...
        lowPassNumerator, lowPassDenominator, coefficients);
    [~, templatePeakIndex] = max(shapedReference);
    referenceStart = templatePeakIndex - samplesBeforePeak;
    referenceIndices = referenceStart:(referenceStart + filterLength - 1);
    if referenceStart < 1 || referenceIndices(end) > sampleCount
        error('PDS:test:ColdBoxTemplateWindow', ...
            'The configured filter window exceeds the M3 template.');
    end
    referenceWindow = shapedReference(referenceIndices);

    dedicatedNoisePath = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
        'ColdBox', 'September2026', 'M3_noise', 'channel_8.7z');
    dedicatedNoise = readColdBoxArchive(dedicatedNoisePath, ...
        'channel_8.dat', sampleCount, dedicatedNoiseRecordCount);
    [dedicatedPedestal, dedicatedDiagnostics] = ...
        pds.preprocess.estimatePedestal(dedicatedNoise, ...
        SampleIndices=1:pedestalSampleCount, Method=pedestalMethod, ...
        BlockSize=pedestalBlockSize);
    dedicatedLimits = quantile(dedicatedPedestal, quantileLimits);
    dedicatedAccepted = dedicatedDiagnostics.validEventMask & ...
        dedicatedPedestal >= dedicatedLimits(1) & ...
        dedicatedPedestal <= dedicatedLimits(2);
    dedicatedCorrected = pds.preprocess.subtractPedestal( ...
        dedicatedNoise(dedicatedAccepted, :), ...
        dedicatedPedestal(dedicatedAccepted));
    clear dedicatedNoise;
    dedicatedShaped = applyLegacyShaping(dedicatedCorrected, ...
        lowPassNumerator, lowPassDenominator, coefficients);
    clear dedicatedCorrected;
    dedicatedIndices = dedicatedNoiseWindowStart: ...
        (dedicatedNoiseWindowStart + filterLength - 1);
    [~, dedicatedCovarianceDiagnostics] = ...
        pds.signal.designCovarianceOptimalFilter(referenceWindow, ...
        dedicatedShaped(:, dedicatedIndices), ...
        ShrinkageFraction=shrinkageFraction);
    dedicatedCovariance = ...
        dedicatedCovarianceDiagnostics.empiricalCovariance;
    dedicatedNoiseAcceptedCount = sum(dedicatedAccepted);
    clear dedicatedShaped;

    trainingMask = mod((1:recordCount).', 2) == 1;
    evaluationMask = ~trainingMask;
    resultCells = cell(size(cases, 1), 37);
    details = cell(size(cases, 1), 1);

    for caseIndex = 1:size(cases, 1)
        caseName = cases{caseIndex, 1};
        channel = cases{caseIndex, 2};
        archivePath = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
            'ColdBox', caseName, 'M3', cases{caseIndex, 3});
        waveforms = readColdBoxArchive(archivePath, cases{caseIndex, 4}, ...
            sampleCount, recordCount);

        [pedestal, pedestalDiagnostics] = ...
            pds.preprocess.estimatePedestal(waveforms, ...
            SampleIndices=1:pedestalSampleCount, Method=pedestalMethod, ...
            BlockSize=pedestalBlockSize, MinimumQualitySampleCount=8, ...
            NonstationarityThreshold=3, OutlierThreshold=3.5, ...
            MaximumOutlierFraction=0.1, QualityBlockCount=4, ...
            BlockLocationThreshold=3, BlockScaleRatioThreshold=3);
        pedestalLimits = quantile(pedestal(trainingMask), quantileLimits);
        qualityMask = pedestalDiagnostics.validEventMask & ...
            pedestal >= pedestalLimits(1) & pedestal <= pedestalLimits(2);
        trainingAccepted = trainingMask & qualityMask;
        evaluationAccepted = evaluationMask & qualityMask;

        corrected = pds.preprocess.subtractPedestal(waveforms, pedestal);
        clear waveforms;
        shaped = applyLegacyShaping(corrected, lowPassNumerator, ...
            lowPassDenominator, coefficients);
        clear corrected;

        shapedTraining = shaped(trainingAccepted, :);
        trainingMean = mean(shapedTraining, 1);
        [normalizationScale, dataPeakIndex] = max(trainingMean);
        dataStart = dataPeakIndex - samplesBeforePeak;
        dataIndices = dataStart:(dataStart + filterLength - 1);
        if dataStart < 1 || dataIndices(end) > sampleCount
            error('PDS:test:ColdBoxDataWindow', ...
                'The configured filter window exceeds %s.', caseName);
        end

        legacyTrainingScores = 2 * mean(shapedTraining(:, ...
            (dataPeakIndex - 1):(dataPeakIndex + 1)), 2) / ...
            normalizationScale;
        candidateFit = fitLegacyTrainingScores(legacyTrainingScores);
        candidateMask = abs(legacyTrainingScores - candidateFit.mu0) <= ...
            2 * candidateFit.sigma0;
        trainingWindow = shapedTraining(:, dataIndices);
        noiseCandidates = trainingWindow(candidateMask, :);

        [optimalCoefficients, optimalDiagnostics] = ...
            pds.signal.designCovarianceOptimalFilter( ...
            referenceWindow, noiseCandidates, ...
            ShrinkageFraction=shrinkageFraction, ...
            PriorCovariance=dedicatedCovariance, ...
            PriorWeight=priorWeight);
        trainingScores = pds.signal.applyOptimalFilter( ...
            trainingWindow, optimalCoefficients, PedestalSampleCount=0);
        trainingFit = anchorOptimalScoresFromLegacyClasses( ...
            trainingScores, legacyTrainingScores, candidateFit);
        trainingSpacing = trainingFit.delta;
        if ~isfinite(trainingSpacing) || trainingSpacing <= 0
            error('PDS:test:ColdBoxTrainingPeakSpacing', ...
                'Training peak spacing is invalid for %s.', caseName);
        end

        allEvaluationWindow = shaped(evaluationMask, dataIndices);
        selectedEvaluationWindow = shaped(evaluationAccepted, dataIndices);
        allEvaluationScores = pds.signal.applyOptimalFilter( ...
            allEvaluationWindow, optimalCoefficients, PedestalSampleCount=0);
        evaluationScores = pds.signal.applyOptimalFilter( ...
            selectedEvaluationWindow, optimalCoefficients, ...
            PedestalSampleCount=0);
        normalizedAllScores = (allEvaluationScores - trainingFit.mu0) / ...
            trainingSpacing;
        normalizedScores = (evaluationScores - trainingFit.mu0) / ...
            trainingSpacing;

        evaluationFit = fitFrozenGaussianPeaks( ...
            normalizedScores, normalizedBinWidth);
        mu0 = evaluationFit.mu0;
        sigma0 = evaluationFit.sigma0;
        mu1 = evaluationFit.mu1;
        sigma1 = evaluationFit.sigma1;
        delta = evaluationFit.delta;
        snr = evaluationFit.snr;
        evaluationAxis = evaluationFit.evaluationAxis;
        fittedCurve = evaluationFit.fittedCurve;
        fitRSquare = evaluationFit.rSquare;
        finalCenters = [mu0, mu1];

        fitValid = all(isfinite([mu0, sigma0, mu1, sigma1, delta, ...
            snr, fitRSquare])) && sigma0 > 0 && delta > 0.5 && ...
            delta < 1.5 && fitRSquare > 0.75;
        if ~fitValid
            error('PDS:test:ColdBoxOptimalFitInvalid', ...
                ['The frozen Gaussian fit is invalid for %s: SNR %.6f, ', ...
                'delta %.6f, sigma0 %.6f, R2 %.6f.'], ...
                caseName, snr, delta, sigma0, fitRSquare);
        end

        if ~isfolder(outputDirectory)
            mkdir(outputDirectory);
        end
        plotPath = fullfile(outputDirectory, ...
            lower(caseName) + "_optimal_filter.png");
        createDiagnosticPlot(normalizedAllScores, normalizedScores, ...
            normalizedBinWidth, evaluationAxis, fittedCurve, mu0, sigma0, ...
            mu1, snr, fitRSquare, caseName, channel, plotPath);

        flagCounts = qualityFlagCounts( ...
            pedestalDiagnostics.qualityFlags, evaluationMask);
        resultCells(caseIndex, :) = { ...
            caseName, channel, contractId, recordCount, ...
            sum(trainingMask), sum(evaluationMask), sum(trainingAccepted), ...
            sum(evaluationAccepted), mean(qualityMask(evaluationMask)), ...
            pedestalSampleCount, pedestalMethod, pedestalBlockSize, ...
            quantileLimits(1), quantileLimits(2), filterLength, ...
            samplesBeforePeak, shrinkageFraction, normalizedBinWidth, ...
            priorWeight, dedicatedNoiseRecordCount, ...
            dedicatedNoiseAcceptedCount, dedicatedNoiseWindowStart, ...
            templatePeakIndex, dataPeakIndex, sum(candidateMask), ...
            mean(candidateMask), mu0, sigma0, mu1, sigma1, delta, snr, ...
            fitRSquare, fitValid, legacyBaselines(caseIndex), ...
            snr - legacyBaselines(caseIndex), string(plotPath)};
        details{caseIndex} = struct( ...
            'caseName', caseName, ...
            'pedestalLimits', pedestalLimits, ...
            'qualityFlagCounts', flagCounts, ...
            'candidateFit', candidateFit, ...
            'candidateMask', candidateMask, ...
            'trainingFit', trainingFit, ...
            'finalCenters', finalCenters, ...
            'dedicatedNoisePath', dedicatedNoisePath, ...
            'dedicatedPedestalLimits', dedicatedLimits, ...
            'optimalDiagnostics', optimalDiagnostics, ...
            'allEvaluationScores', normalizedAllScores, ...
            'selectedEvaluationScores', normalizedScores);
        clear shaped shapedTraining trainingWindow allEvaluationWindow ...
            selectedEvaluationWindow;
    end

    variableNames = {'Case', 'Channel', 'ContractId', 'RecordCount', ...
        'TrainingRecordCount', 'EvaluationRecordCount', ...
        'TrainingAcceptedCount', 'EvaluationAcceptedCount', ...
        'EvaluationAcceptedFraction', 'PedestalSampleCount', ...
        'PedestalMethod', 'PedestalBlockSize', 'QuantileLower', ...
        'QuantileUpper', 'FilterLength', 'SamplesBeforePeak', ...
        'ShrinkageFraction', 'NormalizedBinWidth', 'PriorWeight', ...
        'DedicatedNoiseRecordCount', 'DedicatedNoiseAcceptedCount', ...
        'DedicatedNoiseWindowStart', 'TemplatePeakIndex', ...
        'DataPeakIndex', 'NoiseCandidateCount', 'NoiseCandidateFraction', ...
        'Mu0', 'Sigma0', 'Mu1', 'Sigma1', 'Delta', 'SNR', ...
        'FitRSquare', 'FitValid', 'LegacyBaselineSNR', ...
        'SNRImprovement', 'PlotPath'};
    details = vertcat(details{:});
    results = cell2table(resultCells, 'VariableNames', variableNames);
    writetable(results, fullfile(outputDirectory, 'summary.csv'));
    save(fullfile(outputDirectory, 'summary.mat'), 'results', 'details');
    writeMarkdownSummary(results, details, ...
        fullfile(outputDirectory, 'summary.md'));
end

function shaped = applyLegacyShaping(waveforms, lowPassNumerator, ...
        lowPassDenominator, coefficients)
    shaped = filter(lowPassNumerator, lowPassDenominator, waveforms, [], 2);
    shaped = filter(coefficients.integratorNumerator, ...
        coefficients.integratorDenominator, shaped, [], 2);
    shaped = filter(coefficients.movingMeanNumerator, ...
        coefficients.movingMeanDenominator, shaped, [], 2);
end

function fitResult = fitLegacyTrainingScores(scores)
    binWidths = 0.02:0.01:0.05;
    trialSnr = -Inf(size(binWidths));
    trialFits = cell(size(binWidths));
    for index = 1:numel(binWidths)
        figureHandle = figure('Visible', 'off');
        cleanupFigure = onCleanup(@() closeIfValid(figureHandle));
        try
            [mu0, sigma0, mu1, sigma1, delta, snr] = ...
                gaussian_fit_SNR(scores, binWidths(index), 0.8, -0.5, ...
                -0.25, 4, -0.5, 0.5, 0.3, 6, 45);
            if all(isfinite([mu0, sigma0, mu1, sigma1, delta, snr])) && ...
                    sigma0 > 0 && delta > 0
                trialSnr(index) = snr;
                trialFits{index} = struct('mu0', mu0, 'sigma0', sigma0, ...
                    'mu1', mu1, 'sigma1', sigma1, 'delta', delta, ...
                    'snr', snr, 'binWidth', binWidths(index));
            end
        catch
            % Failed training fits remain unavailable and cannot be selected.
        end
        clear cleanupFigure;
    end
    [bestSnr, bestIndex] = max(trialSnr);
    if ~isfinite(bestSnr)
        error('PDS:test:ColdBoxCandidateFitFailed', ...
            'No valid training fit was available for candidate selection.');
    end
    fitResult = trialFits{bestIndex};
end

function anchors = anchorOptimalScoresFromLegacyClasses( ...
        optimalScores, legacyScores, legacyFit)
    halfWidth = 0.35 * legacyFit.delta;
    pedestalMask = abs(legacyScores - legacyFit.mu0) <= halfWidth;
    onePeMask = abs(legacyScores - legacyFit.mu1) <= halfWidth;
    if sum(pedestalMask) < 100 || sum(onePeMask) < 100
        error('PDS:test:ColdBoxTrainingAnchorCount', ...
            'At least 100 training records are required for each PE anchor.');
    end
    mu0 = median(optimalScores(pedestalMask));
    mu1 = median(optimalScores(onePeMask));
    anchors = struct( ...
        'mu0', mu0, ...
        'mu1', mu1, ...
        'delta', mu1 - mu0, ...
        'pedestalCount', sum(pedestalMask), ...
        'onePeCount', sum(onePeMask), ...
        'legacyHalfWidth', halfWidth, ...
        'method', "legacy-training-class medians");
end

function result = fitFrozenGaussianPeaks(scores, binWidth)
    edges = -0.5:binWidth:4.5;
    counts = histcounts(scores, edges);
    centers = (edges(1:end-1) + edges(2:end)) / 2;
    fits = cell(2, 1);
    fitQuality = zeros(2, 1);
    for peakIndex = 1:2
        approximateCenter = peakIndex - 1;
        fitMask = abs(centers - approximateCenter) < 0.42;
        options = fitoptions('gauss1');
        options.StartPoint = [max(counts(fitMask)), ...
            approximateCenter, 1 / 3];
        options.Lower = [0, approximateCenter - 0.25, eps];
        options.Upper = [Inf, approximateCenter + 0.25, 1];
        [fits{peakIndex}, goodness] = fit(centers(fitMask).', ...
            counts(fitMask).', 'gauss1', options);
        fitQuality(peakIndex) = goodness.rsquare;
    end
    mu0 = fits{1}.b1;
    sigma0 = abs(fits{1}.c1) / sqrt(2);
    mu1 = fits{2}.b1;
    sigma1 = abs(fits{2}.c1) / sqrt(2);
    evaluationAxis = linspace(-0.5, 4.5, 1000);
    result = struct( ...
        'mu0', mu0, ...
        'sigma0', sigma0, ...
        'mu1', mu1, ...
        'sigma1', sigma1, ...
        'delta', mu1 - mu0, ...
        'snr', (mu1 - mu0) / sigma0, ...
        'evaluationAxis', evaluationAxis, ...
        'fittedCurve', fits{1}(evaluationAxis) + ...
            fits{2}(evaluationAxis), ...
        'rSquare', min(fitQuality), ...
        'peakRSquare', fitQuality);
end

function counts = qualityFlagCounts(flags, evaluationMask)
    fields = fieldnames(flags);
    counts = struct();
    for index = 1:numel(fields)
        counts.(fields{index}) = sum(flags.(fields{index})(evaluationMask));
    end
end

function createDiagnosticPlot(allScores, selectedScores, binWidth, ...
        evaluationAxis, fittedCurve, mu0, sigma0, mu1, snr, fitRSquare, ...
        caseName, channel, plotPath)
    figureHandle = figure('Visible', 'off', ...
        'Position', [100, 100, 1300, 600]);
    cleanupFigure = onCleanup(@() closeIfValid(figureHandle));

    subplot(1, 2, 1);
    histogram(allScores, 'BinWidth', binWidth, ...
        'DisplayStyle', 'stairs', 'LineWidth', 1.25);
    grid on;
    xlim([-0.5, 4.5]);
    xlabel('Optimal-filter amplitude [training PE units]');
    ylabel('Events per bin');
    title('All evaluation records');

    subplot(1, 2, 2);
    histogram(selectedScores, 'BinWidth', binWidth, ...
        'DisplayStyle', 'stairs', 'LineWidth', 1.25);
    hold on;
    plot(evaluationAxis, fittedCurve, 'r', 'LineWidth', 1.25);
    xline(mu0, 'r--');
    xline(mu0 - sigma0, 'b--');
    xline(mu0 + sigma0, 'b--');
    xline(mu1, 'r--');
    grid on;
    xlim([-0.5, 4.5]);
    xlabel('Optimal-filter amplitude [training PE units]');
    ylabel('Events per bin');
    title(sprintf('Quality-selected: SNR %.3f, R^2 %.3f', ...
        snr, fitRSquare));
    sgtitle(sprintf('%s M3 channel %d covariance optimal filter', ...
        caseName, channel));

    if isfile(plotPath)
        delete(plotPath);
    end
    exportgraphics(figureHandle, plotPath, 'Resolution', 180);
end

function coefficients = loadLegacyCoefficients(path)
    required = {'numz_planta_integrator', 'denz_planta_integrator', ...
        'numz_planta_movmean_hpk', 'denz_planta_movmean_hpk'};
    contents = load(path, required{:});
    for index = 1:numel(required)
        name = required{index};
        if ~isfield(contents, name) || ~isnumeric(contents.(name)) || ...
                ~isvector(contents.(name)) || any(~isfinite(contents.(name)))
            error('PDS:test:InvalidLegacyFilterCoefficients', ...
                'Invalid or missing coefficient vector: %s.', name);
        end
    end
    coefficients = struct( ...
        'integratorNumerator', contents.numz_planta_integrator, ...
        'integratorDenominator', contents.denz_planta_integrator, ...
        'movingMeanNumerator', contents.numz_planta_movmean_hpk, ...
        'movingMeanDenominator', contents.denz_planta_movmean_hpk);
end

function data = readColdBoxArchive(archivePath, expectedMember, ...
        sampleCount, expectedRecordCount)
    sevenZipPath = 'C:\Program Files\7-Zip\7z.exe';
    if ~isfile(sevenZipPath)
        error('PDS:test:SevenZipMissing', ...
            '7-Zip executable not found: %s', sevenZipPath);
    end
    extractionDirectory = tempname;
    mkdir(extractionDirectory);
    cleanupDirectory = onCleanup(@() removeDirectory(extractionDirectory));

    listCommand = sprintf('"%s" l -slt "%s"', sevenZipPath, archivePath);
    [listStatus, listing] = system(listCommand);
    if listStatus ~= 0
        error('PDS:test:ColdBoxArchiveListFailed', ...
            '7-Zip could not list %s (status %d): %s', ...
            archivePath, listStatus, listing);
    end
    pathTokens = regexp(listing, '(?m)^Path = ([^\r\n]+)', 'tokens');
    listedPaths = string(cellfun(@(token) strtrim(token{1}), ...
        pathTokens, 'UniformOutput', false));
    if numel(listedPaths) ~= 2 || listedPaths(2) ~= expectedMember
        error('PDS:test:UnexpectedColdBoxArchiveContents', ...
            'Archive %s must contain only %s.', archivePath, expectedMember);
    end
    expectedByteCount = expectedRecordCount * sampleCount * 2;
    sizeTokens = regexp(listing, '(?m)^Size = (\d+)', 'tokens');
    if numel(sizeTokens) ~= 1 || str2double(sizeTokens{1}{1}) ~= expectedByteCount
        error('PDS:test:UnexpectedColdBoxArchiveSize', ...
            'Archive member %s must contain %d bytes.', ...
            expectedMember, expectedByteCount);
    end

    extractCommand = sprintf('"%s" x -y -o"%s" "%s"', ...
        sevenZipPath, extractionDirectory, archivePath);
    [extractStatus, message] = system(extractCommand);
    if extractStatus ~= 0
        error('PDS:test:ColdBoxExtractionFailed', ...
            '7-Zip failed with status %d: %s', extractStatus, message);
    end
    dataPath = fullfile(extractionDirectory, expectedMember);
    fileIdentifier = fopen(dataPath, 'r', 'ieee-le');
    if fileIdentifier < 0
        error('PDS:test:ColdBoxDataOpenFailed', ...
            'Unable to open extracted data: %s', dataPath);
    end
    cleanupFile = onCleanup(@() fclose(fileIdentifier));
    rawSamples = fread(fileIdentifier, Inf, 'uint16=>double');
    clear cleanupFile;
    if numel(rawSamples) ~= expectedByteCount / 2
        error('PDS:test:UnexpectedColdBoxDataSize', ...
            'Extracted member %s has an unexpected sample count.', ...
            expectedMember);
    end
    data = reshape(rawSamples, sampleCount, []).';
end

function writeMarkdownSummary(results, details, outputPath)
    fileIdentifier = fopen(outputPath, 'w');
    if fileIdentifier < 0
        error('PDS:test:SummaryOpenFailed', ...
            'Unable to create summary: %s', outputPath);
    end
    cleanupFile = onCleanup(@() fclose(fileIdentifier));
    fprintf(fileIdentifier, '# ColdBox M3 covariance optimal-filter contract\n\n');
    fprintf(fileIdentifier, ['Contract: `coldbox-m3-covariance-optimal-v1`. ', ...
        'Odd records train; even records evaluate.\n\n']);
    fprintf(fileIdentifier, ['Pedestal: median-of-means over samples 1:100, ', ...
        'block size 10. Quality flags and training pedestal quantiles ', ...
        '15--85%% reject spurious records.\n\n']);
    fprintf(fileIdentifier, ['Covariance: 75%% acquisition candidates plus ', ...
        '25%% trace-normalized dedicated M3 noise (%d/%d records accepted), ', ...
        'followed by 1e-4 diagonal shrinkage.\n\n'], ...
        results.DedicatedNoiseAcceptedCount(1), ...
        results.DedicatedNoiseRecordCount(1));
    fprintf(fileIdentifier, ['| Dataset | Accepted evaluation | Noise candidates ', ...
        '| Delta | Sigma0 | SNR | Legacy SNR | Improvement | R^2 |\n']);
    fprintf(fileIdentifier, ...
        '|---|---:|---:|---:|---:|---:|---:|---:|---:|\n');
    for index = 1:height(results)
        fprintf(fileIdentifier, ...
            '| %s | %d | %d | %.6f | %.6f | %.6f | %.6f | %.6f | %.6f |\n', ...
            results.Case(index), results.EvaluationAcceptedCount(index), ...
            results.NoiseCandidateCount(index), results.Delta(index), ...
            results.Sigma0(index), results.SNR(index), ...
            results.LegacyBaselineSNR(index), ...
            results.SNRImprovement(index), results.FitRSquare(index));
    end
    fprintf(fileIdentifier, '\nEvaluation quality-flag counts:\n\n');
    for index = 1:numel(details)
        flags = details(index).qualityFlagCounts;
        fprintf(fileIdentifier, ['- %s: contaminated=%d, nonstationary=%d, ', ...
            'excessive-outliers=%d, unstable-blocks=%d.\n'], ...
            details(index).caseName, flags.pretriggerContaminated, ...
            flags.nonstationaryBaseline, flags.excessiveOutliers, ...
            flags.unstableBlocks);
    end
    fprintf(fileIdentifier, ['\nResults are acquisition-specific exploratory ', ...
        'measurements, not universal detector calibrations. September has ', ...
        'visible non-Gaussian structure; its R^2 is reported rather than ', ...
        'hidden.\n']);
end

function closeIfValid(figureHandle)
    if isgraphics(figureHandle)
        close(figureHandle);
    end
end

function removeDirectory(directory)
    if isfolder(directory)
        rmdir(directory, 's');
    end
end
