classdef TestEstimateDiscreteTransferFunction < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addProjectSource(testCase)
            repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            addpath(sourceDirectory);
            testCase.addTeardown(@() rmpath(sourceDirectory));
        end
    end

    methods (Test)
        function suffixMutationCannotLeakForAnyDelaySign(testCase)
            sampleTime = 0.1;
            sampleCount = 100;
            trainingCount = 70;
            sampleIndex = (0:(sampleCount - 1)).';
            inputSignal = sin(0.17 * sampleIndex) + ...
                0.3 * cos(0.41 * sampleIndex);
            outputSignal = filter([0, 0.25], [1, -0.72], inputSignal);
            mutatedInput = inputSignal;
            mutatedOutput = outputSignal;
            suffix = (trainingCount + 1):sampleCount;
            mutatedInput(suffix) = 20 * sin((1:numel(suffix)).');
            mutatedOutput(suffix) = -15 + (1:numel(suffix)).';

            for delay = [-2, 0, 2]
                [referenceModel, referenceDiagnostics] = ...
                    pds.identification.estimateDiscreteTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=sampleTime, ...
                    MaxOrder=2, DelayRange=delay, ...
                    TrainingSampleCount=trainingCount, ...
                    SelectionCriterion="best-fit");
                [mutatedModel, mutatedDiagnostics] = ...
                    pds.identification.estimateDiscreteTransferFunction( ...
                    mutatedInput, mutatedOutput, SampleTime=sampleTime, ...
                    MaxOrder=2, DelayRange=delay, ...
                    TrainingSampleCount=trainingCount, ...
                    SelectionCriterion="best-fit");

                testCase.verifyEqual(mutatedDiagnostics.candidateTable, ...
                    referenceDiagnostics.candidateTable);
                testCase.verifyEqual(mutatedDiagnostics.selectedPoleOrder, ...
                    referenceDiagnostics.selectedPoleOrder);
                testCase.verifyEqual(mutatedDiagnostics.selectedZeroOrder, ...
                    referenceDiagnostics.selectedZeroOrder);
                testCase.verifyEqual(mutatedDiagnostics.selectedDelaySamples, ...
                    referenceDiagnostics.selectedDelaySamples);
                testCase.verifyEqual(mutatedModel.Numerator, ...
                    referenceModel.Numerator, AbsTol=0);
                testCase.verifyEqual(mutatedModel.Denominator, ...
                    referenceModel.Denominator, AbsTol=0);
            end
        end

        function temporalHoldoutIsExcludedFromFitAndScoredSeparately(testCase)
            sampleTime = 0.1;
            sampleCount = 120;
            trainingCount = 80;
            inputSignal = zeros(sampleCount, 1);
            inputSignal(5) = 1;
            cleanOutput = filter(0.4, [1, -0.8], inputSignal);
            outputSignal = cleanOutput;
            outputSignal((trainingCount + 1):end) = ...
                outputSignal((trainingCount + 1):end) + 0.2;

            [model, diagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=0, TrainingSampleCount=trainingCount);

            fullPrediction = filter( ...
                model.Numerator, model.Denominator, inputSignal);
            validationIndices = (trainingCount + 1):sampleCount;
            expectedValidationRmse = sqrt(mean(( ...
                outputSignal(validationIndices) - ...
                fullPrediction(validationIndices)).^2));
            testCase.verifyEqual(diagnostics.trainingIndices, 1:trainingCount);
            testCase.verifyEqual( ...
                diagnostics.validationIndices, validationIndices);
            testCase.verifyEqual( ...
                diagnostics.validationRmse, expectedValidationRmse, ...
                AbsTol=1e-12);
            testCase.verifyEqual(diagnostics.validationMode, "temporal-holdout");
            testCase.verifyEqual( ...
                diagnostics.candidateTable.trainingSampleCount, ...
                repmat(trainingCount, height(diagnostics.candidateTable), 1));
        end

        function noFiniteAiccUsesApiIdentifierAndRestoresRng(testCase)
            warningState = warning('off', 'all');
            warningCleanup = onCleanup(@() warning(warningState));
            rng(123, 'twister');
            inputSignal = randn(8, 1);
            outputSignal = randn(8, 1);
            callerState = rng;

            testCase.verifyError(@() ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=0.1, MaxOrder=4, ...
                DelayRange=0, SelectionCriterion="aicc"), ...
                ['pds:identification:estimateDiscreteTransferFunction:' ...
                'NoFiniteSelectionScore']);
            testCase.verifyEqual(rng, callerState);
        end

        function bestFitDoesNotRequireFiniteAicc(testCase)
            sampleTime = 0.1;
            rng(2, 'twister');
            inputSignal = randn(8, 1);
            outputSignal = randn(8, 1);
            warningState = warning('off', 'all');
            warningCleanup = onCleanup(@() warning(warningState));

            [~, diagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=5, DelayRange=0, ...
                SelectionCriterion="best-fit");

            candidates = diagnostics.candidateTable;
            eligible = candidates.stable & ...
                isfinite(candidates.fitPercent) & ...
                isfinite(candidates.rmse) & ...
                isfinite(candidates.nrmse);
            expectedFit = max(candidates.fitPercent(eligible));

            testCase.verifyEqual( ...
                diagnostics.selectedFitPercent, expectedFit, AbsTol=1e-10);
            selected = candidates.poleOrder == ...
                diagnostics.selectedPoleOrder & ...
                candidates.delaySamples == ...
                diagnostics.selectedDelaySamples;
            testCase.verifyTrue(isinf(candidates.aicc(selected)));
            clear warningCleanup
        end

        function informationCriteriaCountDiscreteFreeCoefficients(testCase)
            sampleTime = 0.1;
            sampleIndex = (0:39).';
            inputSignal = sin(0.21 * sampleIndex) + ...
                0.2 * cos(0.47 * sampleIndex);
            outputSignal = filter([0, 0.3], [1, -0.7], inputSignal);

            [~, diagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=0, ...
                SelectionCriterion="best-fit");

            candidates = diagnostics.candidateTable;
            sampleCount = numel(inputSignal);
            for row = 1:height(candidates)
                if candidates.zeroOrder(row) == 0
                    parameterCount = candidates.poleOrder(row) + 1;
                else
                    parameterCount = candidates.poleOrder(row) + ...
                        candidates.zeroOrder(row);
                end
                protectedMse = max(candidates.rmse(row) ^ 2, ...
                    realmin('double'));
                expectedBic = sampleCount * log(protectedMse) + ...
                    parameterCount * log(sampleCount);
                expectedAic = sampleCount * log(protectedMse) + ...
                    2 * parameterCount;
                expectedAicc = expectedAic + ...
                    2 * parameterCount * (parameterCount + 1) / ...
                    (sampleCount - parameterCount - 1);

                testCase.verifyEqual( ...
                    candidates.bic(row), expectedBic, AbsTol=1e-10);
                testCase.verifyEqual( ...
                    candidates.aicc(row), expectedAicc, AbsTol=1e-10);
            end
        end

        function recoversDiscreteDelayAndExposesCandidateMetrics(testCase)
            sampleTime = 0.1;
            sampleCount = 250;
            inputSignal = zeros(sampleCount, 1);
            inputSignal(25) = 1;
            delayedInput = [zeros(4, 1); inputSignal(1:end-4)];
            outputSignal = filter(0.25, [1, -0.8], delayedInput);

            [~, diagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=0:5, FitTolerance=0.1);

            testCase.verifyEqual(diagnostics.selectedDelaySamples, 4);
            testCase.verifyTrue(all(ismember( ...
                ["fitPercent", "rmse", "nrmse", "bic", "aicc", ...
                "stable", "valid", "failureMessage"], ...
                string(diagnostics.candidateTable.Properties.VariableNames))));
        end

        function identifiesDirectStableIirInInverseZ(testCase)
            sampleTime = 0.1;
            sampleIndex = (0:299).';
            inputSignal = sin(0.17 * sampleIndex) + ...
                0.35 * sin(0.53 * sampleIndex);
            outputSignal = filter([0, 0.3], [1, -0.7], inputSignal);

            [model, diagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=0, FitTolerance=0.5);

            testCase.verifyEqual(model.Ts, sampleTime);
            testCase.verifyEqual(string(model.Variable), "z^-1");
            testCase.verifyTrue(isstable(model));
            testCase.verifyEqual(diagnostics.domain, "discrete");
            testCase.verifyLessThanOrEqual(diagnostics.selectedPoleOrder, 2);
            testCase.verifyGreaterThan(diagnostics.selectedFitPercent, 95);

            numerator = model.Numerator;
            denominator = model.Denominator;
            reconstructed = filter(numerator, denominator, inputSignal);
            transientEnd = 30;
            testCase.verifyLessThan( ...
                norm(reconstructed(transientEnd:end) - ...
                outputSignal(transientEnd:end)) / ...
                norm(outputSignal(transientEnd:end)), 0.05);
        end

        function recoversKnownSlowPoleAndLongTail(testCase)
            sampleTime = 16e-9;
            sampleCount = 800;
            slowPole = exp(-sampleTime / 2e-6);
            inputSignal = zeros(sampleCount, 1);
            inputSignal(4) = 1;
            outputSignal = filter(1 - slowPole, [1, -slowPole], inputSignal);

            [model, diagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=0, FitTolerance=0.1, ...
                SelectionCriterion="best-fit");
            recoveredSlowPole = max(abs(pole(model)));
            recoveredTimeConstant = -sampleTime / log(recoveredSlowPole);

            testCase.verifyEqual(recoveredTimeConstant, 2e-6, RelTol=0.02);
            testCase.verifyGreaterThan(diagnostics.selectedFitPercent, 99.9);
            testCase.verifyLessThan(abs(diagnostics.fullPrediction(end)), 1e-4);
        end
    end
end
