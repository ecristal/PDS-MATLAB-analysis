classdef TestDesignCovarianceOptimalFilter < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addProjectSource(testCase)
            repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                sourceDirectory));
        end
    end

    methods (Test)
        function producesUnitResponseWithCausalCoefficientOrientation(testCase)
            reference = [0, 1, 2, 0];
            noise = [1, 0, 0, 0; -1, 0, 0, 0; ...
                0, 2, 0, 0; 0, -2, 0, 0; ...
                0, 0, 3, 0; 0, 0, -3, 0; ...
                0, 0, 0, 4; 0, 0, 0, -4];

            [coefficients, diagnostics] = ...
                pds.signal.designCovarianceOptimalFilter( ...
                reference, noise, ShrinkageFraction=0.01);
            score = pds.signal.applyOptimalFilter( ...
                reference, coefficients, PedestalSampleCount=0);

            testCase.verifyEqual(score, 1, AbsTol=1e-12);
            testCase.verifyEqual(fliplr(coefficients), diagnostics.weights, ...
                AbsTol=1e-14);
            testCase.verifyEqual(dot(diagnostics.weights, reference), 1, ...
                AbsTol=1e-12);
            testCase.verifyEqual(diagnostics.normalization, "unit-response");
            testCase.verifyEqual(diagnostics.noiseRecordCount, 8);
            testCase.verifyEqual(diagnostics.sampleCount, 4);
            testCase.verifyGreaterThan(diagnostics.predictedNoiseVariance, 0);
        end

        function inverseCovarianceWeightsMatchAnalyticDiagonalCase(testCase)
            reference = [1, 1, 0];
            noise = [1, 0, 0; -1, 0, 0; ...
                0, 2, 0; 0, -2, 0; ...
                0, 0, 3; 0, 0, -3];

            [~, diagnostics] = pds.signal.designCovarianceOptimalFilter( ...
                reference, noise, ShrinkageFraction=0);
            covariance = diag([1, 4, 9]) / 3;
            expected = covariance \ reference.';
            expected = (expected / (reference * expected)).';

            testCase.verifyEqual(diagnostics.covariance, covariance, ...
                AbsTol=1e-14);
            testCase.verifyEqual(diagnostics.weights, expected, ...
                AbsTol=1e-12);
            testCase.verifyEqual(diagnostics.shrinkageFraction, 0);
        end

        function blendsTraceNormalizedPriorCovariance(testCase)
            reference = [1, 0.5, 0.25];
            noise = [1, 0, 0; -1, 0, 0; ...
                0, 2, 0; 0, -2, 0; ...
                0, 0, 3; 0, 0, -3];
            prior = diag([9, 4, 1]);

            [~, diagnostics] = ...
                pds.signal.designCovarianceOptimalFilter( ...
                reference, noise, ShrinkageFraction=0, ...
                PriorCovariance=prior, PriorWeight=0.25);

            empirical = diag([1, 4, 9]) / 3;
            priorScale = trace(empirical) / trace(prior);
            expected = 0.75 * empirical + 0.25 * priorScale * prior;
            testCase.verifyEqual(diagnostics.empiricalCovariance, ...
                empirical, AbsTol=1e-12);
            testCase.verifyEqual(diagnostics.priorScale, ...
                priorScale, AbsTol=1e-12);
            testCase.verifyEqual(diagnostics.covariance, ...
                expected, AbsTol=1e-12);
            testCase.verifyEqual(diagnostics.priorWeight, 0.25);
        end

        function rejectsInexactIntegerInputsBeforeDoubleConversion(testCase)
            unsafePositive = uint64(flintmax) + uint64(1);
            unsafeNegative = -int64(flintmax) - int64(1);
            validReference = [1, 0.5];
            validNoise = [1, 0; -1, 0; 0, 1; 0, -1];
            identifier = ['pds:signal:designCovarianceOptimalFilter:' ...
                'InexactIntegerConversion'];

            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                [uint64(1), unsafePositive], validNoise), identifier);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                [int64(1), unsafeNegative], validNoise), identifier);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, [uint64(1), unsafePositive; ...
                uint64(2), unsafePositive]), identifier);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, [int64(1), unsafeNegative; ...
                int64(2), unsafeNegative]), identifier);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, validNoise, ...
                PriorCovariance=diag([unsafePositive, uint64(1)]), ...
                PriorWeight=0.25), identifier);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, validNoise, ...
                PriorCovariance=diag([unsafeNegative, int64(1)]), ...
                PriorWeight=0.25), identifier);
        end

        function rejectsInvalidShapesAndShrinkage(testCase)
            validReference = [0, 1, 0];
            validNoise = randn(10, 3);
            prefix = 'pds:signal:designCovarianceOptimalFilter:';

            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                [0, 1], validNoise), [prefix, 'NoiseLength']);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, ones(1, 3)), ...
                [prefix, 'InsufficientNoiseRecords']);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, validNoise, ShrinkageFraction=-1), ...
                [prefix, 'InvalidShrinkage']);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, validNoise, ShrinkageFraction=1.1), ...
                [prefix, 'InvalidShrinkage']);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                zeros(1, 3), validNoise), ...
                [prefix, 'DegenerateReference']);
            testCase.verifyError(@() ...
                pds.signal.designCovarianceOptimalFilter( ...
                validReference, validNoise, PriorCovariance=eye(4), ...
                PriorWeight=0.25), ...
                [prefix, 'InvalidPriorCovariance']);
        end
    end
end
