        function streamSettingsSupportSubstreamReplayAndRejectGlobalHandle(testCase)
            saved = rng; cleanup = onCleanup(@() rng(saved));
            globalBefore = rng;
            s = RandStream.create('mrg32k3a','NumStreams',3,'StreamIndices',2,'Seed',11);
            s.Substream = 4; s.NormalTransform = 'Inversion';
            s.Antithetic = true; s.FullPrecision = false;
            initial = get(s);
            [wave,t] = pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,ResponseNumerator=1,OnePeAmplitude=40,RandomStream=s, ...
                BaselineMode='wander',BaselineWanderStepRms=.1, ...
                EventOptions=struct('SignalMultiplicity',0));
            testCase.verifyEqual(t.random.settings,initial);
            replay = RandStream.create(initial.Type,'NumStreams',initial.NumStreams, ...
                'StreamIndices',initial.StreamIndex,'Seed',initial.Seed);
            replay.Substream = initial.Substream; replay.NormalTransform = initial.NormalTransform;
            replay.Antithetic = initial.Antithetic; replay.FullPrecision = initial.FullPrecision;
            replay.State = initial.State;
            expected = [0,cumsum(.1*randn(replay,1,t.parentSampleCount-1),2)];
            testCase.verifyEqual(wave,expected(t.cropIndices));
            testCase.verifyEqual(s.State,replay.State);
            testCase.verifyEqual(rng,globalBefore);
            testCase.verifyError(@() pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,ResponseNumerator=1,OnePeAmplitude=40, ...
                RandomStream=RandStream.getGlobalStream,EventOptions=struct('DarkRateHz',1e5)), ...
                'pds:simulation:simulatePedestalStressWaveforms:InvalidRandomStream');
            testCase.verifyEqual(rng,globalBefore);
        end
