        function saturationIsExplicitAfterFloatingPointComposition(testCase)
            common = {'ResponseNumerator',[1 -1], 'ResponseDenominator',[1 -.9], ...
                'OnePeAmplitude',30000,'BaselineOffset',100,'EventCount',2};
            [raw,t] = pds.simulation.simulatePedestalStressWaveforms(256,16e-9,common{:});
            testCase.verifyClass(raw,'double');
            testCase.verifyGreaterThan(max(raw,[],'all'),2^14);
            testCase.verifyLessThan(min(raw,[],'all'),0);
            testCase.verifyEqual(t.postAdc,raw); testCase.verifyFalse(any(t.saturationMask,'all'));
            [clipped,u] = pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,common{:},SaturationRange=uint16([0 16383]));
            testCase.verifyEqual(clipped,min(max(raw,0),16383));
            testCase.verifyEqual(u.preAdc,raw); testCase.verifyEqual(u.postAdc,clipped);
            testCase.verifyEqual(u.saturationMask,raw<0 | raw>16383);
            testCase.verifyEqual(u.saturationRange,[0 16383]);
            testCase.verifyEqual(u.configuration.OnePeAmplitude,30000);
            testCase.verifyEqual(u.preAdc,u.components.baseline+u.components.reference+ ...
                u.components.dark+u.components.largeEvent+u.components.noise);
            for range = {[1 1],[2 1],[0 Inf],1,'invalid'}
                testCase.verifyError(@() pds.simulation.simulatePedestalStressWaveforms( ...
                    256,16e-9,common{:},SaturationRange=range{1}), ...
                    'pds:simulation:simulatePedestalStressWaveforms:InvalidSaturationRange');
            end
        end
        function coloredNoiseUsesParentGridAfterEventsAndWander(testCase)
            common = {'ResponseNumerator',[1 -.5],'OnePeAmplitude',40, ...
                'EventCount',2,'BaselineMode','wander','BaselineWanderStepRms',.1, ...
                'BurnInSampleCount',512,'PretriggerSampleCount',100, ...
                'EventOptions',struct('DarkRateHz',1e5),'Seed',31};
            [~,before] = pds.simulation.simulatePedestalStressWaveforms(256,16e-9,common{:});
            m = before.parentSampleCount;
            psd = 1e-7*(2+cos(2*pi*(0:m-1)/m));
            [wave,t] = pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,common{:},NoisePsd=psd,NoiseRms=3);
            stream = RandStream('mt19937ar','Seed',31); stream.State = before.random.finalState;
            [noise,d] = pds.simulation.generateColoredNoise(m,16e-9, ...
                NoisePsd=psd,TargetRms=3,EventCount=2,RandomStream=stream);
            testCase.verifyGreaterThan(m,256);
            testCase.verifyEqual(t.parent.components.noise,noise);
            testCase.verifyEqual(t.components.noise,noise(:,t.cropIndices));
            testCase.verifyEqual(t.noiseDiagnostics,d);
            testCase.verifyEqual(t.random.finalState,stream.State);
            testCase.verifyEqual(sqrt(mean(noise.^2,2)),[3;3],AbsTol=1e-12);
            testCase.verifyEqual(wave,t.components.baseline+t.components.reference+ ...
                t.components.dark+t.components.largeEvent+t.components.noise);
            [again,replay] = pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,common{:},NoisePsd=psd,NoiseRms=3);
            testCase.verifyEqual(again,wave); testCase.verifyEqual(replay,t);
            [~,absolute] = pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,common{:},NoisePsd=psd);
            testCase.verifyEqual(absolute.noiseDiagnostics.normalization,"none");
            testCase.verifyError(@() pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,common{:},NoiseRms=3), ...
                'pds:simulation:simulatePedestalStressWaveforms:InvalidNoise');
        end
        function wanderFollowsEventsOnOneLocalReplayableStream(testCase)
            saved = rng; cleanup = onCleanup(@() rng(saved));
            rng(918); globalBefore = rng;
            eventOptions = struct('SignalMultiplicityDistribution','poisson', ...
                'SignalMultiplicityLambda',2,'DarkRateHz',1e5,'LargeEventRateHz',2e4, ...
                'LargeAmplitude',8000);
            common = {'ResponseNumerator', [1 -.5], 'OnePeAmplitude', 40, ...
                'BaselineMode','wander','BaselineOffset',6000, ...
                'BaselineWanderStepRms',.2,'EventCount',2,'EventOptions',eventOptions};
            [wave,t] = pds.simulation.simulatePedestalStressWaveforms(256,16e-9,common{:},Seed=17);
            [again,replay] = pds.simulation.simulatePedestalStressWaveforms(256,16e-9,common{:},Seed=17);
            testCase.verifyEqual(again,wave); testCase.verifyEqual(replay,t);
            testCase.verifyEqual(rng,globalBefore);
            stream = RandStream('mt19937ar','Seed',17);
            [~,e] = pds.simulation.generateEventTrain(t.parentSampleCount,16e-9, ...
                EventCount=2,ReferenceIndex=t.parentReferenceIndex,ReferenceAmplitude=40, ...
                SignalMultiplicityDistribution='poisson',SignalMultiplicityLambda=2, ...
                DarkRateHz=1e5,LargeEventRateHz=2e4,RandomStream=stream);
            expected = 6000 + [zeros(2,1),cumsum(.2*randn(stream,2,t.parentSampleCount-1),2)];
            testCase.verifyEqual(t.parent.components.baseline,expected);
            testCase.verifyEqual(t.eventTruth.signalMultiplicity,e.signalMultiplicity);
            testCase.verifyEqual(t.eventTruth.darkComponent,40*e.darkComponent);
            testCase.verifyEqual(t.random.finalState,stream.State);
            supplied = RandStream('mt19937ar','Seed',17); initial = supplied.State;
            [other,u] = pds.simulation.simulatePedestalStressWaveforms(256,16e-9,common{:},RandomStream=supplied);
            testCase.verifyEqual(other,wave);
            testCase.verifyEqual(u.random.initialState,initial);
            testCase.verifyEqual(u.random.finalState,supplied.State);
            testCase.verifyNotEqual(initial,supplied.State);
            prefix = 'pds:simulation:simulatePedestalStressWaveforms:';
            testCase.verifyError(@() pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,common{:},Seed=2,RandomStream=supplied),[prefix 'ConflictingRandomSource']);
            testCase.verifyError(@() pds.simulation.simulatePedestalStressWaveforms( ...
                256,16e-9,ResponseNumerator=1,OnePeAmplitude=40,BaselineMode='wander'), ...
                [prefix 'InvalidBaseline']);
        end
        function deterministicBaselineModesUseParentReference(testCase)
            common = {'ResponseNumerator', 1, 'OnePeAmplitude', 40, ...
                'BaselineOffset', 6000, 'EventCount', 2, ...
                'EventOptions', struct('SignalMultiplicity', 0)};
            [wave, t] = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, common{:}, BaselineMode="slope", ...
                BaselineSlopePerSample=.25);
