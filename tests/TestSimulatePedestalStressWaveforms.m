        function normalizedIirRetainsUndershootBeyondFir(testCase)
            common = {'OnePeAmplitude', 40, 'PretriggerSampleCount', 100, ...
                'PedestalSampleCount', 50};
            [wave, truth] = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, common{:}, ResponseNumerator=[0 2 -2], ...
                ResponseDenominator=[1 -.9]);
            h = filter([0 1 -1], [1 -.9], [1 zeros(1, 155)]);
            testCase.verifyEqual(wave(101:end), 40*h, AbsTol=1e-12);
            testCase.verifyEqual(truth.response.peakMagnitude, 2);
            testCase.verifyEqual(truth.responsePeakIndex, 102);
            testCase.verifyEqual(max(abs(truth.response.impulse)), 1);
            testCase.verifyLessThan(min(wave), 0);
            fir = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, common{:}, ResponseNumerator=h(1:12));
            testCase.verifyEqual(fir(101:112), wave(101:112), AbsTol=1e-12);
            testCase.verifyEqual(fir(113:end), zeros(1, 144));
            testCase.verifyGreaterThan(abs(wave(113)), 0);
            [~, slow] = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, common{:}, ResponseNumerator=[1 -1], ...
                ResponseDenominator=[1 -.999], ResponseTolerance=1e-5);
            testCase.verifyGreaterThan(slow.burnInSampleCount, 10000);
            testCase.verifyGreaterThanOrEqual(slow.cropIndices(1)-1, ...
                slow.burnInSampleCount);
            testCase.verifyLessThanOrEqual(slow.response.terminalRelativePeak, 1e-5);
            testCase.verifyEqual(slow.parentReferenceIndex, ...
                ceil(slow.parentSampleCount/2));
        end
