        function parentArrivalsRemainDistinctFromPedestalResponseTails(testCase)
            args = {'ResponseNumerator', [1 -1], ...
                'ResponseDenominator', [1 -.9], 'OnePeAmplitude', 40, ...
                'EventCount', 3, 'PretriggerSampleCount', 100, ...
                'PedestalSampleCount', 80, ...
                'EventOptions', struct('SignalMultiplicity', 0)};
            [~, geometry] = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, args{:});
            c = geometry.cropIndices;
            p = geometry.pedestalIndices;
            injected = [1 c(1)-2 1 40; 2 c(p(4)) 1 40; 3 c(p(7)) 2 30000];
            [wave, truth] = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, args{:}, InjectedEvents=injected, ...
                InjectedEventProvenance="synthetic deterministic tail fixture");
            testCase.verifyLessThan(wave(1,p(1)), 0);
            testCase.verifyFalse(any(truth.arrivalMasks.dark(1,:)));
            testCase.verifyTrue(truth.pedestalContamination.dark(1));
            testCase.verifyTrue(truth.arrivalMasks.dark(2,p(4)));
            testCase.verifyTrue(truth.arrivalMasks.largeEvent(3,p(7)));
            testCase.verifyEqual(truth.components.dark(2,p(4)), 40);
            testCase.verifyEqual(truth.components.largeEvent(3,p(7)), 30000);
            testCase.verifyEqual(truth.injectedEvents, injected);
            testCase.verifyEqual(truth.preAdc, truth.components.baseline + ...
                truth.components.reference + truth.components.dark + ...
                truth.components.largeEvent + truth.components.noise);
            testCase.verifyEqual(wave, truth.preAdc);
            testCase.verifyEqual(truth.parent.components.dark(:,c), truth.components.dark);
            testCase.verifySize(truth.filterStates.dark.initial, [3 1]);
            testCase.verifyGreaterThan(abs(truth.filterStates.dark.atCrop(1)), 0);
            testCase.verifyEqual(truth.eventTruth.darkRateHz, 0);
        end
