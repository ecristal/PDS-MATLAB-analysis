            testCase.verifyEqual(wave, expected);
            testCase.verifyEqual(t.baselineAtReference, [6000;6000]);
            testCase.verifyEqual(t.pedestalBaselineMean, mean(expected(:,29:128),2));
            [wave, t] = pds.simulation.simulatePedestalStressWaveforms( ...
                256, 16e-9, common{:}, BaselineMode="step", ...
