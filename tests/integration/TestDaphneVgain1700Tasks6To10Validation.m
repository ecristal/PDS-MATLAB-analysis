classdef TestDaphneVgain1700Tasks6To10Validation < matlab.unittest.TestCase
    properties (Constant, Access = private)
        ExpectedTemplateSha256 = ...
            '3170b4d8090140cf62a38651d4cdebe22ae6fc6ccaa53c94b45977bc504a2a2d'
        AnalysisRecordCount = 3000
        PretriggerSampleCount = 300
    end

    methods (TestClassSetup)
        function addProjectPaths(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            helperDirectory = fullfile(repositoryRoot, 'tests', 'helpers');
            addpath(sourceDirectory, helperDirectory);
            testCase.addTeardown(@() rmpath(sourceDirectory, helperDirectory));
        end
    end

    methods (Test)
        function createsScientificReviewArtifactsFromFrozenDaphneData(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            validationRoot = fullfile(repositoryRoot, 'outputs', 'validation');
            testCase.verifyError(@() resetOutputDirectory(validationRoot), ...
                'PDS:test:UnsafeOutputDirectory');
            testCase.verifyError(@() resetOutputDirectory(repositoryRoot), ...
                'PDS:test:UnsafeOutputDirectory');
            [waveforms, acquisitionMetadata] = ...
                readDaphneReferenceForTest(repositoryRoot);
            testCase.assertGreaterThanOrEqual(size(waveforms, 1), ...
                testCase.AnalysisRecordCount);
            selectedWaveforms = waveforms(1:testCase.AnalysisRecordCount, :);

            outputRoot = validationRoot;
            pedestalArtifacts = validatePedestalDiagnostics( ...
                selectedWaveforms, acquisitionMetadata, ...
                fullfile(outputRoot, ...
                'pedestal-daphne-fbk-vgain-1700'));
            coloredNoiseArtifacts = validateMeasuredColoredNoise( ...
                selectedWaveforms, acquisitionMetadata, ...
                fullfile(outputRoot, ...
                'colored-noise-daphne-fbk-vgain-1700'));
            clear waveforms selectedWaveforms;
            transferArtifacts = validateTransferFunctions( ...
                repositoryRoot, fullfile(outputRoot, ...
                'iir-daphne-fbk-vgain-1700', 'scientific-validation'), ...
                testCase.ExpectedTemplateSha256);

            verifyArtifacts(testCase, pedestalArtifacts);
            verifyArtifacts(testCase, coloredNoiseArtifacts);
            verifyArtifacts(testCase, transferArtifacts);
        end
    end
end


function artifacts = validatePedestalDiagnostics( ...
        waveforms, acquisitionMetadata, outputDirectory)
resetOutputDirectory(outputDirectory);
pretriggerIndices = 1:300;
[levels, diagnostics] = pds.preprocess.estimatePedestal( ...
    waveforms, SampleIndices=pretriggerIndices, Method="median", ...
    MinimumQualitySampleCount=8, NonstationarityThreshold=3, ...
    OutlierThreshold=3.5, MaximumOutlierFraction=0.10, ...
    QualityBlockCount=4, BlockLocationThreshold=3, ...
    BlockScaleRatioThreshold=3);
flagNames = fieldnames(diagnostics.qualityFlags);
flagFractions = zeros(numel(flagNames), 1);
for flagIndex = 1:numel(flagNames)
    flagFractions(flagIndex) = mean( ...
        diagnostics.qualityFlags.(flagNames{flagIndex}));
end

reviewFigure = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [100, 100, 1200, 850]);
cleanup = onCleanup(@() closeIfValid(reviewFigure));
layout = tiledlayout(reviewFigure, 2, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');
title(layout, ['DAPHNE FBK SiPM VGAIN 1700, channel 24: ', ...
    'pedestal quality diagnostics']);
nexttile(layout);
histogram(levels, 80);
grid on;
xlabel('Median pedestal [ADU]');
ylabel('Events');
title(sprintf('Pedestal levels, N=%d', numel(levels)));
nexttile(layout);
histogram(diagnostics.slopePerSample, 80);
grid on;
xlabel('Robust diagnostic slope [ADU/sample]');
ylabel('Events');
title('Pretrigger slope distribution');
nexttile(layout);
histogram(diagnostics.outlierFraction, ...
    'BinEdges', linspace(0, max(0.05, max(diagnostics.outlierFraction)), 41));
grid on;
xlabel('Outlier fraction');
ylabel('Events');
title('Robust residual outlier fraction');
nexttile(layout);
displayFlagNames = ["insufficient samples", "nonstationary baseline", ...
    "pretrigger contaminated", "excessive outliers", "unstable blocks"];
flagCategories = categorical(displayFlagNames, displayFlagNames, ...
    'Ordinal', true);
flagBars = bar(flagCategories, flagFractions);
xtickangle(25);
text(flagBars.XEndPoints, flagBars.YEndPoints, ...
    compose('%.3f', flagFractions), 'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'bottom');
grid on;
ylabel('Flagged event fraction');
ylim([0, max(0.05, 1.15 * max(flagFractions))]);
title(sprintf('Valid-event fraction: %.3f', ...
    mean(diagnostics.validEventMask)));

artifacts = struct( ...
    'reviewPng', fullfile(outputDirectory, ...
        'pedestal-quality-diagnostics.png'), ...
    'reviewFig', fullfile(outputDirectory, ...
        'pedestal-quality-diagnostics.fig'), ...
    'eventTableCsv', fullfile(outputDirectory, ...
        'pedestal-event-diagnostics.csv'), ...
    'metricsJson', fullfile(outputDirectory, ...
        'pedestal-quality-metrics.json'));
exportgraphics(reviewFigure, artifacts.reviewPng, 'Resolution', 180);
savefig(reviewFigure, artifacts.reviewFig);
clear cleanup;

eventIndex = (1:numel(levels)).';
eventTable = table(eventIndex, levels, diagnostics.sampleNoiseSigma, ...
    diagnostics.slopePerSample, diagnostics.outlierFraction, ...
    diagnostics.blockLocationScore, diagnostics.blockScaleRatio, ...
    diagnostics.validEventMask, 'VariableNames', ...
    {'eventIndex', 'pedestalAdc', 'sampleNoiseSigmaAdc', ...
    'slopeAdcPerSample', 'outlierFraction', 'blockLocationScore', ...
    'blockScaleRatio', 'validEvent'});
writetable(eventTable, artifacts.eventTableCsv);
metrics = struct( ...
    'dataset', 'DAPHNE/FBK_SiPM/vgain_1700/channel_24', ...
    'channel', acquisitionMetadata.channel, ...
    'samplePeriodSeconds', acquisitionMetadata.samplePeriod, ...
    'recordSelection', 'first-3000-records', ...
    'recordCount', numel(levels), ...
    'pretriggerSampleCount', numel(pretriggerIndices), ...
    'method', 'median', ...
    'medianPedestalAdc', median(levels), ...
    'medianSampleNoiseSigmaAdc', median(diagnostics.sampleNoiseSigma), ...
    'validEventFraction', mean(diagnostics.validEventMask), ...
    'flagNames', {flagNames}, ...
    'flagFractions', flagFractions, ...
    'thresholds', diagnostics.thresholds, ...
    'scientificStatus', ...
        'diagnostic-only; configuration-specific; not calibration');
writeJson(artifacts.metricsJson, metrics);
end


function artifacts = validateMeasuredColoredNoise( ...
        waveforms, acquisitionMetadata, outputDirectory)
resetOutputDirectory(outputDirectory);
noiseRecords = waveforms(:, 1:300);
noiseRecords = noiseRecords - median(noiseRecords, 2);
[targetPsd, frequencyHz] = pds.signal.estimateNoisePsd( ...
    noiseRecords, acquisitionMetadata.samplePeriod, ...
    Window="rectangular", RemoveMean=true);
[generatedNoise, generationDiagnostics] = ...
    pds.simulation.generateColoredNoise( ...
    size(noiseRecords, 2), acquisitionMetadata.samplePeriod, ...
    NoisePsd=targetPsd, EventCount=size(noiseRecords, 1), Seed=1700);
[realizedPsd, realizedFrequencyHz] = pds.signal.estimateNoisePsd( ...
    generatedNoise, acquisitionMetadata.samplePeriod, ...
    Window="rectangular", RemoveMean=true);
positiveIndices = 2:(floor(numel(targetPsd) / 2) + 1);
logPsdCorrelation = corr(log(targetPsd(positiveIndices).'), ...
    log(realizedPsd(positiveIndices).'));
relativePsdError = norm(realizedPsd - targetPsd) / norm(targetPsd);

reviewFigure = figure('Visible', 'off', 'Color', 'w', ...
    'Position', [100, 100, 1200, 800]);
cleanup = onCleanup(@() closeIfValid(reviewFigure));
layout = tiledlayout(reviewFigure, 2, 1, ...
    'TileSpacing', 'compact', 'Padding', 'compact');
title(layout, ['DAPHNE FBK SiPM VGAIN 1700, channel 24: ', ...
    'measured-PSD colored-noise validation']);
nexttile(layout);
semilogy(frequencyHz(positiveIndices) / 1e6, ...
    targetPsd(positiveIndices), 'k-', 'LineWidth', 1.5, ...
    'DisplayName', 'measured target PSD');
hold on;
semilogy(realizedFrequencyHz(positiveIndices) / 1e6, ...
    realizedPsd(positiveIndices), 'r--', 'LineWidth', 1.3, ...
    'DisplayName', 'generated ensemble PSD');
grid on;
xlabel('Frequency [MHz]');
ylabel('PSD [ADU^2/Hz]');
legend('Location', 'best');
title(sprintf('Bilateral PSD validation: log correlation %.5f', ...
    logPsdCorrelation));
nexttile(layout);
timeMicroseconds = (0:(size(noiseRecords, 2) - 1)) * ...
    acquisitionMetadata.samplePeriod * 1e6;
colors = lines(3);
hold on;
for recordIndex = 1:3
    plot(timeMicroseconds, noiseRecords(recordIndex, :), '-', ...
        'Color', colors(recordIndex, :), 'LineWidth', 1.0, ...
        'HandleVisibility', 'off');
    plot(timeMicroseconds, generatedNoise(recordIndex, :), '--', ...
        'Color', colors(recordIndex, :), 'LineWidth', 1.0, ...
        'HandleVisibility', 'off');
end
plot(NaN, NaN, 'k-', 'DisplayName', 'measured records');
plot(NaN, NaN, 'k--', 'DisplayName', 'generated records');
grid on;
xlabel('Time [microseconds]');
ylabel('Baseline-subtracted amplitude [ADU]');
title('Three measured records (solid) and three generated records (dashed)');
legend('Location', 'best');

artifacts = struct( ...
    'reviewPng', fullfile(outputDirectory, ...
        'measured-psd-colored-noise-validation.png'), ...
    'reviewFig', fullfile(outputDirectory, ...
        'measured-psd-colored-noise-validation.fig'), ...
    'psdCsv', fullfile(outputDirectory, ...
        'measured-vs-generated-psd.csv'), ...
    'metricsJson', fullfile(outputDirectory, ...
        'colored-noise-validation-metrics.json'));
exportgraphics(reviewFigure, artifacts.reviewPng, 'Resolution', 180);
savefig(reviewFigure, artifacts.reviewFig);
clear cleanup;

psdTable = table(frequencyHz(:), targetPsd(:), realizedPsd(:), ...
    'VariableNames', {'frequencyHz', 'targetPsdAdc2PerHz', ...
    'generatedEnsemblePsdAdc2PerHz'});
writetable(psdTable, artifacts.psdCsv);
metrics = struct( ...
    'dataset', 'DAPHNE/FBK_SiPM/vgain_1700/channel_24', ...
    'recordSelection', 'first-3000-records-pretrigger', ...
    'recordCount', size(noiseRecords, 1), ...
    'sampleCount', size(noiseRecords, 2), ...
    'samplePeriodSeconds', acquisitionMetadata.samplePeriod, ...
    'psdSidedness', 'bilateral', ...
    'frequencyOrder', 'fft', ...
    'seed', generationDiagnostics.seed, ...
    'logPsdCorrelationPositiveNonDc', logPsdCorrelation, ...
    'relativePsdL2Error', relativePsdError, ...
    'measuredRmsAdc', sqrt(mean(noiseRecords(:).^2)), ...
    'generatedRmsAdc', sqrt(mean(generatedNoise(:).^2)), ...
    'scientificStatus', ...
        'measured-PSD reproduction check; not an electronics noise model');
writeJson(artifacts.metricsJson, metrics);
end


function artifacts = validateTransferFunctions( ...
        repositoryRoot, outputDirectory, expectedTemplateSha256)
resetOutputDirectory(outputDirectory);
templatePath = fullfile(repositoryRoot, 'data', 'DAPHNE', 'FBK_SiPM', ...
    'vgain_1700', 'figures', 'average_single_PE_ch_24.fig');
if sha256File(templatePath) ~= string(expectedTemplateSha256)
    error('PDS:test:FrozenTemplateHashMismatch', ...
        'The DAPHNE single-PE template hash does not match the frozen fixture.');
end
figureHandle = openfig(templatePath, 'invisible');
figureCleanup = onCleanup(@() closeIfValid(figureHandle));
lineHandles = findall(figureHandle, 'Type', 'line');
if numel(lineHandles) ~= 1
    error('PDS:test:UnexpectedTemplateFigure', ...
        'Expected exactly one line in the frozen template figure.');
end
timeMicroseconds = double(lineHandles.XData(:));
rawTemplate = double(lineHandles.YData(:));
clear figureCleanup;

sampleTime = median(diff(timeMicroseconds)) * 1e-6;
[template, preparation] = pds.identification.prepareSinglePeTemplate( ...
    rawTemplate, BaselineIndices=1:100, Polarity="positive");
template = template(:);
onsetIndex = find(template >= 0.05, 1, 'first');
inputImpulse = zeros(size(template));
inputImpulse(onsetIndex) = 1;
trainingSampleCount = 1200;
commonOptions = {'SampleTime', sampleTime, 'MaxOrder', 4, ...
    'DelayRange', -2:2, 'FitTolerance', 0.5, ...
    'SelectionCriterion', 'parsimonious-fit', ...
    'TrainingSampleCount', trainingSampleCount};
[continuousModel, continuousDiagnostics] = ...
    pds.identification.estimateContinuousTransferFunction( ...
    inputImpulse, template, commonOptions{:});
[~, discreteDiagnostics] = ...
    pds.identification.estimateDiscreteTransferFunction( ...
    inputImpulse, template, commonOptions{:});
continuousPrediction = continuousDiagnostics.fullPrediction;
discretePrediction = discreteDiagnostics.fullPrediction;
continuousDiscreteModel = c2d(continuousModel, sampleTime, 'zoh');
continuousDiscreteInput = shiftWithZeroPadding(inputImpulse, ...
    continuousDiagnostics.selectedDelaySamples);
timeSeconds = (0:(numel(template) - 1)).' * sampleTime;
continuousDiscretePrediction = lsim( ...
    continuousDiscreteModel, continuousDiscreteInput, timeSeconds);
continuousDiscretePrediction = double(continuousDiscretePrediction(:));

tailStartIndex = trainingSampleCount + 1;
continuousMetrics = pds.identification.evaluateTransferFunctionResponse( ...
    template, continuousPrediction, SampleTime=sampleTime, ...
    TailStartIndex=tailStartIndex, ReturnBand=0.01, ...
    ReturnConsecutiveSamples=10);
discreteMetrics = pds.identification.evaluateTransferFunctionResponse( ...
    template, discretePrediction, SampleTime=sampleTime, ...
    TailStartIndex=tailStartIndex, ReturnBand=0.01, ...
    ReturnConsecutiveSamples=10);
continuousDiscreteMetrics = ...
    pds.identification.evaluateTransferFunctionResponse( ...
    template, continuousDiscretePrediction, SampleTime=sampleTime, ...
    TailStartIndex=tailStartIndex, ReturnBand=0.01, ...
    ReturnConsecutiveSamples=10);

[reviewFigure, reviewAxes] = pds.plotting.plotTransferFunctionEstimate( ...
    template, [continuousPrediction.'; discretePrediction.'; ...
    continuousDiscretePrediction.'], SampleTime=sampleTime, ...
    ModelLabels=["continuous direct", "discrete direct", ...
    "continuous to c2d (ZOH)"], ...
    TrainingSampleCount=trainingSampleCount, ...
    TailStartIndex=tailStartIndex, Visible="off", ...
    Title=['DAPHNE FBK SiPM VGAIN 1700, channel 24: ', ...
    'temporal tail extrapolation']);
title(reviewAxes(3), sprintf([ ...
    'Tail/undershoot: target %.4f, continuous %.4g, ', ...
    'discrete %.4g, c2d %.4g'], ...
    continuousMetrics.targetUndershootAmplitude, ...
    continuousMetrics.predictedUndershootAmplitude, ...
    discreteMetrics.predictedUndershootAmplitude, ...
    continuousDiscreteMetrics.predictedUndershootAmplitude));
reviewCleanup = onCleanup(@() closeIfValid(reviewFigure));
artifacts = struct( ...
    'reviewPng', fullfile(outputDirectory, ...
        'transfer-function-tail-holdout-comparison.png'), ...
    'reviewFig', fullfile(outputDirectory, ...
        'transfer-function-tail-holdout-comparison.fig'), ...
    'metricsCsv', fullfile(outputDirectory, ...
        'transfer-function-comparison-metrics.csv'), ...
    'metricsJson', fullfile(outputDirectory, ...
        'transfer-function-comparison-metrics.json'), ...
    'continuousCandidatesCsv', fullfile(outputDirectory, ...
        'continuous-candidate-table.csv'), ...
    'discreteCandidatesCsv', fullfile(outputDirectory, ...
        'discrete-candidate-table.csv'));
exportgraphics(reviewFigure, artifacts.reviewPng, 'Resolution', 180);
savefig(reviewFigure, artifacts.reviewFig);
clear reviewCleanup;

modelName = ["continuous-direct"; "discrete-direct"; ...
    "continuous-to-c2d-zoh"];
trainingFitPercent = [continuousDiagnostics.selectedFitPercent; ...
    discreteDiagnostics.selectedFitPercent; NaN];
validationRmse = [continuousDiagnostics.validationRmse; ...
    discreteDiagnostics.validationRmse; ...
    continuousDiscreteMetrics.tailRmse];
peakAmplitude = [continuousMetrics.predictedPeakAmplitude; ...
    discreteMetrics.predictedPeakAmplitude; ...
    continuousDiscreteMetrics.predictedPeakAmplitude];
undershootAmplitude = [continuousMetrics.predictedUndershootAmplitude; ...
    discreteMetrics.predictedUndershootAmplitude; ...
    continuousDiscreteMetrics.predictedUndershootAmplitude];
negativeArea = [continuousMetrics.predictedNegativeArea; ...
    discreteMetrics.predictedNegativeArea; ...
    continuousDiscreteMetrics.predictedNegativeArea];
tailRmse = [continuousMetrics.tailRmse; discreteMetrics.tailRmse; ...
    continuousDiscreteMetrics.tailRmse];
returnedToBand = [continuousMetrics.predictedReturnedToBand; ...
    discreteMetrics.predictedReturnedToBand; ...
    continuousDiscreteMetrics.predictedReturnedToBand];
returnIndex = [continuousMetrics.predictedReturnIndex; ...
    discreteMetrics.predictedReturnIndex; ...
    continuousDiscreteMetrics.predictedReturnIndex];
settledToBand = [continuousMetrics.predictedSettledToBand; ...
    discreteMetrics.predictedSettledToBand; ...
    continuousDiscreteMetrics.predictedSettledToBand];
settlingIndex = [continuousMetrics.predictedSettlingIndex; ...
    discreteMetrics.predictedSettlingIndex; ...
    continuousDiscreteMetrics.predictedSettlingIndex];
comparisonTable = table(modelName, trainingFitPercent, validationRmse, ...
    peakAmplitude, undershootAmplitude, negativeArea, tailRmse, ...
    returnedToBand, returnIndex, settledToBand, settlingIndex);
writetable(comparisonTable, artifacts.metricsCsv);
writetable(continuousDiagnostics.candidateTable, ...
    artifacts.continuousCandidatesCsv);
writetable(discreteDiagnostics.candidateTable, ...
    artifacts.discreteCandidatesCsv);
metrics = struct( ...
    'dataset', 'DAPHNE/FBK_SiPM/vgain_1700/channel_24-single-PE-template', ...
    'templateSha256', char(expectedTemplateSha256), ...
    'sampleTimeSeconds', sampleTime, ...
    'preparation', preparation, ...
    'onsetIndex', onsetIndex, ...
    'trainingSampleCount', trainingSampleCount, ...
    'validationMode', 'temporal-tail-extrapolation-single-waveform', ...
    'targetMetrics', pds.identification.evaluateTransferFunctionResponse( ...
        template, template, SampleTime=sampleTime, ...
        TailStartIndex=tailStartIndex, ReturnBand=0.01, ...
        ReturnConsecutiveSamples=10), ...
    'continuousDirect', continuousMetrics, ...
    'discreteDirect', discreteMetrics, ...
    'continuousToDiscreteZoh', continuousDiscreteMetrics, ...
    'continuousSelectedPoleOrder', ...
        continuousDiagnostics.selectedPoleOrder, ...
    'discreteSelectedPoleOrder', discreteDiagnostics.selectedPoleOrder, ...
    'continuousSelectedDelaySamples', ...
        continuousDiagnostics.selectedDelaySamples, ...
    'discreteSelectedDelaySamples', ...
        discreteDiagnostics.selectedDelaySamples, ...
    'scientificApproval', false, ...
    'scientificStatus', [ ...
        'exploratory temporal tail extrapolation; single averaged waveform; ', ...
        'not event-independent holdout; models do not reproduce undershoot']);
writeJson(artifacts.metricsJson, metrics);

if continuousDiagnostics.validationMode ~= "temporal-holdout" || ...
        discreteDiagnostics.validationMode ~= "temporal-holdout"
    error('PDS:test:MissingTemporalHoldout', ...
        'Both direct models must use the temporal holdout.');
end
if metrics.targetMetrics.targetUndershootAmplitude >= -0.02
    error('PDS:test:UnexpectedDaphneUndershoot', ...
        'The frozen DAPHNE template must retain its negative undershoot.');
end
if continuousMetrics.predictedUndershootAmplitude <= -0.01 || ...
        discreteMetrics.predictedUndershootAmplitude <= -0.01
    error('PDS:test:ScientificFindingChanged', ...
        'The current bounded models unexpectedly crossed the review threshold.');
end
end


function shifted = shiftWithZeroPadding(signal, delay)
shifted = zeros(size(signal));
if delay >= 0
    shifted((delay + 1):end) = signal(1:(end - delay));
else
    advance = -delay;
    shifted(1:(end - advance)) = signal((advance + 1):end);
end
end


function resetOutputDirectory(outputDirectory)
repositoryRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
validationRoot = string(java.io.File(fullfile( ...
    repositoryRoot, 'outputs', 'validation')).getCanonicalPath());
canonicalOutput = string(java.io.File(outputDirectory).getCanonicalPath());
requiredPrefix = validationRoot + string(filesep);
if canonicalOutput == validationRoot || ...
        ~startsWith(canonicalOutput, requiredPrefix, 'IgnoreCase', true)
    error('PDS:test:UnsafeOutputDirectory', ...
        'Refusing to reset a path outside outputs/validation: %s', ...
        canonicalOutput);
end
if isfolder(outputDirectory)
    rmdir(outputDirectory, 's');
end
mkdir(outputDirectory);
end


function verifyArtifacts(testCase, artifacts)
artifactPaths = struct2cell(artifacts);
for artifactIndex = 1:numel(artifactPaths)
    path = artifactPaths{artifactIndex};
    testCase.verifyTrue(isfile(path), ...
        sprintf('Missing review artifact: %s', path));
    fileInfo = dir(path);
    testCase.verifyGreaterThan(fileInfo.bytes, 0, ...
        sprintf('Empty review artifact: %s', path));
end
end


function closeIfValid(figureHandle)
if isgraphics(figureHandle)
    close(figureHandle);
end
end


function writeJson(filePath, value)
fileIdentifier = fopen(filePath, 'wt');
if fileIdentifier < 0
    error('PDS:test:ArtifactWriteFailed', ...
        'Could not open review artifact for writing: %s', filePath);
end
cleanup = onCleanup(@() fclose(fileIdentifier));
fprintf(fileIdentifier, '%s', jsonencode(value, PrettyPrint=true));
end


function digest = sha256File(filePath)
fileIdentifier = fopen(filePath, 'rb');
if fileIdentifier < 0
    error('PDS:test:ArtifactReadFailed', ...
        'Could not open file for hashing: %s', filePath);
end
cleanup = onCleanup(@() fclose(fileIdentifier));
bytes = fread(fileIdentifier, Inf, '*uint8');
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(bytes);
digestBytes = typecast(engine.digest(), 'uint8');
digest = string(lower(reshape(dec2hex(digestBytes, 2).', 1, [])));
end
