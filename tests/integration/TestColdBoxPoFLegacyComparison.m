classdef TestColdBoxPoFLegacyComparison < matlab.unittest.TestCase
    methods (Test)
        function comparesAvailablePoFConfigurations(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            dataFunctionsDirectory = fullfile(sourceDirectory, 'data');
            helperDirectory = fullfile(repositoryRoot, 'tests', 'helpers');
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                sourceDirectory));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                dataFunctionsDirectory));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                helperDirectory));

            coefficientPath = fullfile('C:\Users\e_cri\OneDrive\Documents', ...
                'PhD', 'Investigacion', 'Electronica', 'DAPHNE test', ...
                'daphne_configuration', 'Filters', 'fit_filter_vars.mat');
            poFRoot = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                'ColdBox', 'September2026', 'PoF_data');
            testCase.assumeTrue(isfile(coefficientPath), ...
                'Legacy filter coefficients are unavailable.');
            testCase.assumeTrue(isfolder(poFRoot), ...
                'PoF data are unavailable.');
            testCase.assumeFalse(isempty(which('fit')), ...
                'Curve Fitting Toolbox function fit is required.');

            outputDirectory = fullfile(repositoryRoot, 'outputs', ...
                'validation', 'coldbox-september2026-pof-comparison');
            [results, barData] = runColdBoxPoFLegacyComparisonForTest( ...
                repositoryRoot, coefficientPath, outputDirectory);

            testCase.verifyEqual(height(results), 14);
            testCase.verifyEqual(results.Configuration, ...
                [repmat("PoF_OFF", 2, 1); repmat("PoF_OLD", 4, 1); ...
                repmat("PoF_NEW", 4, 1); repmat("PoF_ALL", 4, 1)]);
            testCase.verifyEqual(results.Module, ...
                [repmat(3, 2, 1); repelem([3; 6], 2); ...
                repelem([3; 6], 2); repelem([3; 6], 2)]);
            testCase.verifyEqual(results.LogicalChannel, ...
                repmat([1; 2], 7, 1));
            expectedDaphneChannels = [8; 9; 8; 9; 20; 21; 8; 9; ...
                20; 21; 8; 9; 20; 21];
            testCase.verifyEqual(results.DaphneChannel, expectedDaphneChannels);
            testCase.verifyEqual(results.LowPassApplied, results.Module == 3);
            testCase.verifyEqual(results.LowPassCutoffHz(results.Module == 3), ...
                repmat(2e6, 8, 1));
            testCase.verifyEqual(results.LowPassCutoffHz(results.Module == 6), ...
                zeros(6, 1));
            testCase.verifyEqual(results.RecordCount, repmat(30000, 14, 1));
            testCase.verifyEqual(results.SampleCount, repmat(1024, 14, 1));
            testCase.verifyEqual(results.SampleRateHz, repmat(62.5e6, 14, 1));
            testCase.verifyEqual(results.PedestalSampleCount, ...
                repmat(100, 14, 1));
            testCase.verifyEqual(results.PedestalMethod, ...
                repmat("mean", 14, 1));
            testCase.verifyTrue(all(contains(results.HistogramTitle, ...
                "Histogram - COLDBOX SEPT 2026")));
            testCase.verifyTrue(all(contains(results.HistogramTitle, ...
                "VBIAS=")));
            testCase.verifyTrue(all(contains(results.HistogramTitle, ...
                "PoF_{")));
            testCase.verifyTrue(all(isfinite(results.NominalSNR)));
            testCase.verifyTrue(all(isfinite(results.SNR(results.FitValid))));
            testCase.verifyTrue(all(isnan(results.SNR(~results.FitValid))));
            testCase.verifyTrue(all(results.FitValid));
            fallbackRows = results.FitMethod == "local-gaussian";
            testCase.verifyEqual(sum(fallbackRows), 2);
            testCase.verifyEqual(results.Configuration(fallbackRows), ...
                ["PoF_OLD"; "PoF_NEW"]);
            testCase.verifyEqual(results.Module(fallbackRows), [6; 6]);
            testCase.verifyEqual(results.LogicalChannel(fallbackRows), [2; 2]);
            testCase.verifyTrue(all(strlength(results.ArchiveSha256) == 64));
            testCase.verifyTrue(all(isfile(results.HistogramPlotPath)));

            testCase.verifyEqual(height(barData), 16);
            missingRows = barData.Configuration == "PoF_OFF" & ...
                barData.Module == 6;
            testCase.verifyEqual(sum(missingRows), 2);
            testCase.verifyTrue(all(barData.DataAvailable(~missingRows)));
            testCase.verifyFalse(any(barData.DataAvailable(missingRows)));
            testCase.verifyTrue(all(isnan(barData.SNR(missingRows))));
            testCase.verifyTrue(all(barData.FitValid(~missingRows)));

            requiredOutputs = [ ...
                "summary.csv"; "summary.mat"; "summary.md"; ...
                "snr_by_configuration.csv"; "snr_bar_chart.png"; ...
                "histograms_montage.png"];
            testCase.verifyTrue(all(isfile(fullfile(outputDirectory, ...
                requiredOutputs))));

            fprintf(['COLDBOX_POF_LEGACY_COMPARISON cases=%d valid=%d ', ...
                'configs=%d outputs=%s\n'], height(results), ...
                sum(results.FitValid), numel(unique(results.Configuration)), ...
                outputDirectory);
        end
    end
end
