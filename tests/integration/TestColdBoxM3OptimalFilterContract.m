classdef TestColdBoxM3OptimalFilterContract < matlab.unittest.TestCase
    methods (Test)
        function commonContractMeetsNovemberAndImprovesSeptember(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            dataFunctionsDirectory = fullfile(sourceDirectory, 'data');
            helperDirectory = fullfile(repositoryRoot, 'tests', 'helpers');
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                sourceDirectory));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                dataFunctionsDirectory));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                helperDirectory));

            coefficientPath = fullfile('C:\Users\e_cri\OneDrive\Documents', ...
                'PhD', 'Investigacion', 'Electronica', 'DAPHNE test', ...
                'daphne_configuration', 'Filters', 'fit_filter_vars.mat');
            templatePath = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                'ColdBox', 'Template', 'M3', 'template.csv');
            novemberArchive = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                'ColdBox', 'November2025', 'M3', 'channel_28.7z');
            septemberArchive = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                'ColdBox', 'September2026', 'M3', 'channel_8.7z');
            dedicatedNoiseArchive = fullfile(repositoryRoot, 'data', ...
                'DAPHNE', 'ColdBox', 'September2026', 'M3_noise', ...
                'channel_8.7z');
            testCase.assumeTrue(all(isfile([string(coefficientPath), ...
                string(templatePath), string(novemberArchive), ...
                string(septemberArchive), string(dedicatedNoiseArchive)])), ...
                'Local ColdBox inputs or filter coefficients are unavailable.');
            testCase.assumeFalse(isempty(which('fit')), ...
                'Curve Fitting Toolbox function fit is required.');

            outputDirectory = fullfile(repositoryRoot, 'outputs', ...
                'validation', 'coldbox-m3-covariance-optimal-v1');
            results = runColdBoxM3OptimalFilterContractForTest( ...
                repositoryRoot, coefficientPath, outputDirectory);

            testCase.verifySize(results, [2, 37]);
            testCase.verifyEqual(results.Case, ...
                ["November2025"; "September2026"]);
            testCase.verifyEqual(results.Channel, [28; 8]);
            testCase.verifyEqual(results.ContractId, repmat( ...
                "coldbox-m3-covariance-optimal-v1", 2, 1));
            testCase.verifyEqual(results.RecordCount, repmat(30000, 2, 1));
            testCase.verifyEqual(results.TrainingRecordCount, ...
                repmat(15000, 2, 1));
            testCase.verifyEqual(results.EvaluationRecordCount, ...
                repmat(15000, 2, 1));
            testCase.verifyEqual(results.PedestalSampleCount, ...
                repmat(100, 2, 1));
            testCase.verifyEqual(results.PedestalMethod, ...
                repmat("median-of-means", 2, 1));
            testCase.verifyEqual(results.PedestalBlockSize, repmat(10, 2, 1));
            testCase.verifyEqual(results.FilterLength, repmat(128, 2, 1));
            testCase.verifyEqual(results.ShrinkageFraction, ...
                repmat(1e-4, 2, 1), AbsTol=eps);
            testCase.verifyEqual(results.PriorWeight, ...
                repmat(0.25, 2, 1), AbsTol=eps);
            testCase.verifyEqual(results.DedicatedNoiseRecordCount, ...
                repmat(50000, 2, 1));
            testCase.verifyGreaterThan(results.DedicatedNoiseAcceptedCount, ...
                repmat(25000, 2, 1));
            testCase.verifyEqual(results.DedicatedNoiseWindowStart, ...
                repmat(501, 2, 1));
            testCase.verifyEqual(results.NormalizedBinWidth, ...
                repmat(0.02, 2, 1), AbsTol=eps);
            testCase.verifyGreaterThan(results.NoiseCandidateCount, ...
                repmat(1000, 2, 1));
            testCase.verifyGreaterThan(results.EvaluationAcceptedCount, ...
                repmat(7000, 2, 1));
            testCase.verifyGreaterThan(results.FitRSquare, ...
                repmat(0.75, 2, 1));
            testCase.verifyTrue(all(results.FitValid));
            testCase.verifyGreaterThanOrEqual(results.SNR(1), 5.81);
            testCase.verifyGreaterThan(results.SNR(2), 4.19146707701183);
            testCase.verifyLessThan(results.SNR, [7; 6]);
            testCase.verifyTrue(all(isfile(results.PlotPath)));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.csv')));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.mat')));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.md')));

            fprintf(['COLDBOX_OPTIMAL_V1 NovemberSNR=%.9g ', ...
                'SeptemberSNR=%.9g accepted=[%d,%d] noise=[%d,%d]\n'], ...
                results.SNR(1), results.SNR(2), ...
                results.EvaluationAcceptedCount(1), ...
                results.EvaluationAcceptedCount(2), ...
                results.NoiseCandidateCount(1), ...
                results.NoiseCandidateCount(2));
        end
    end
end
