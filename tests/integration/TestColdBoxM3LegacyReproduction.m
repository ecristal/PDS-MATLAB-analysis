classdef TestColdBoxM3LegacyReproduction < matlab.unittest.TestCase
    methods (Test)
        function november2025ReproducesResolvedPhotoelectronPeaks(testCase)
            [repositoryRoot, coefficientPath] = ...
                testCase.configureEnvironment();
            configuration = testCase.novemberConfiguration(repositoryRoot);
            testCase.assumeTrue(isfile(configuration.ReferencePlotPath), ...
                'The local November reference plot is unavailable.');

            outputDirectory = fullfile(repositoryRoot, 'outputs', ...
                'validation', 'coldbox-m3-legacy-reproduction');
            result = runColdBoxM3LegacyContractForTest( ...
                coefficientPath, outputDirectory, configuration);

            testCase.verifyCommonContract(result, outputDirectory, ...
                "November2025", 28);
            testCase.verifyEqual(result.SelectedCount, 14701);
            testCase.verifyGreaterThan(result.SNR, 5);
            testCase.verifyLessThan(result.SNR, 7);
            testCase.verifyGreaterThan(result.Delta, 0.9);
            testCase.verifyLessThan(result.Delta, 1.2);
            testCase.verifyGreaterThan(result.FitRSquare, 0.95);
            testCase.verifyTrue(result.FitValid);
            testCase.verifyTrue(isfile(result.PlotPath));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.csv')));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.mat')));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.md')));

            fprintf(['COLDBOX_M3_LEGACY_REPRO SNR=%.9g delta=%.9g ', ...
                'sigma0=%.9g selected=%d plot=%s\n'], ...
                result.SNR, result.Delta, result.Sigma0, ...
                result.SelectedCount, result.PlotPath);
        end

        function september2026UsesIdenticalLegacyContract(testCase)
            [repositoryRoot, coefficientPath] = ...
                testCase.configureEnvironment();
            configuration = testCase.septemberConfiguration(repositoryRoot);
            outputDirectory = fullfile(repositoryRoot, 'outputs', ...
                'validation', 'coldbox-m3-legacy-contract-september2026');

            result = runColdBoxM3LegacyContractForTest( ...
                coefficientPath, outputDirectory, configuration);

            testCase.verifyCommonContract(result, outputDirectory, ...
                "September2026", 8);
            testCase.verifyTrue(all(isfinite([result.Mu0, result.Sigma0, ...
                result.Mu1, result.Sigma1, result.Delta, result.SNR, ...
                result.FitRSquare])));

            fprintf(['COLDBOX_M3_SEPTEMBER_CONTRACT SNR=%.9g delta=%.9g ', ...
                'sigma0=%.9g selected=%d valid=%d plot=%s\n'], ...
                result.SNR, result.Delta, result.Sigma0, ...
                result.SelectedCount, result.FitValid, result.PlotPath);
        end
    end

    methods (Access = private)
        function [repositoryRoot, coefficientPath] = ...
                configureEnvironment(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            dataFunctionsDirectory = fullfile(sourceDirectory, 'data');
            helperDirectory = fullfile(repositoryRoot, 'tests', 'helpers');
            addpath(sourceDirectory);
            addpath(dataFunctionsDirectory);
            addpath(helperDirectory);
            testCase.addTeardown(@() rmpath(helperDirectory));
            testCase.addTeardown(@() rmpath(dataFunctionsDirectory));
            testCase.addTeardown(@() rmpath(sourceDirectory));

            coefficientPath = fullfile('C:\Users\e_cri\OneDrive\Documents', ...
                'PhD', 'Investigacion', 'Electronica', 'DAPHNE test', ...
                'daphne_configuration', 'Filters', 'fit_filter_vars.mat');
            testCase.assumeTrue(isfile(coefficientPath), ...
                'The preserved legacy filter coefficients are unavailable.');
            testCase.assumeFalse(isempty(which('fit')), ...
                'Curve Fitting Toolbox function fit is required.');
        end

        function verifyCommonContract(testCase, result, outputDirectory, ...
                expectedCase, expectedChannel)
            testCase.verifyEqual(result.Case, expectedCase);
            testCase.verifyEqual(result.Channel, expectedChannel);
            testCase.verifyEqual(result.RecordCount, 30000);
            testCase.verifyEqual(result.PedestalSampleCount, 100);
            testCase.verifyEqual(result.PedestalMethod, "mean");
            testCase.verifyEqual(result.ContractId, ...
                "coldbox-m3-legacy-shaping-v1");
            testCase.verifyTrue(isfile(result.PlotPath));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.csv')));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.mat')));
            testCase.verifyTrue(isfile(fullfile(outputDirectory, 'summary.md')));
        end
    end

    methods (Static, Access = private)
        function configuration = novemberConfiguration(repositoryRoot)
            configuration = struct( ...
                'Case', "November2025", ...
                'Channel', 28, ...
                'ArchivePath', fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                    'ColdBox', 'November2025', 'M3', 'channel_28.7z'), ...
                'ArchiveMember', "channel_28.dat", ...
                'ReferencePlotPath', fullfile(repositoryRoot, 'data', ...
                    'DAPHNE', 'ColdBox', 'November2025', 'M3', ...
                    'histogram_ch_28.png'), ...
                'PlotFileName', "november2025_legacy_reproduction.png", ...
                'PlotTitle', {{'Histogram of integrals - Module M3 CH1 - DMEM FBK', ...
                    'OV = 4.5V - VGAIN 500 - HD Mezzanine CH 28'}});
        end

        function configuration = septemberConfiguration(repositoryRoot)
            configuration = struct( ...
                'Case', "September2026", ...
                'Channel', 8, ...
                'ArchivePath', fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                    'ColdBox', 'September2026', 'M3', 'channel_8.7z'), ...
                'ArchiveMember', "channel_8.dat", ...
                'ReferencePlotPath', "", ...
                'PlotFileName', "september2026_legacy_contract.png", ...
                'PlotTitle', {{'Histogram of integrals - Module M3', ...
                    'September 2026 - Channel 8 - legacy contract'}});
        end
    end
end
