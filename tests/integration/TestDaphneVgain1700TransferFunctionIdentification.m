classdef TestDaphneVgain1700TransferFunctionIdentification < matlab.unittest.TestCase
    properties (Constant, Access = private)
        ExpectedFigureSha256 = ...
            '3170b4d8090140cf62a38651d4cdebe22ae6fc6ccaa53c94b45977bc504a2a2d'
    end

    methods (TestClassSetup)
        function addProjectSource(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            addpath(sourceDirectory);
            testCase.addTeardown(@() rmpath(sourceDirectory));
        end
    end

    methods (Test)
        function highGlobalFitDoesNotImplyUndershootFidelity(testCase)
            repositoryRoot = fileparts(fileparts(fileparts( ...
                mfilename('fullpath'))));
            figurePath = fullfile(repositoryRoot, 'data', 'DAPHNE', ...
                'FBK_SiPM', 'vgain_1700', 'figures', ...
                'average_single_PE_ch_24.fig');
            testCase.assumeTrue(isfile(figurePath), ...
                'Local DAPHNE vgain_1700 integration fixture is unavailable.');
            testCase.verifyEqual(sha256File(figurePath), ...
                testCase.ExpectedFigureSha256, ...
                'Local DAPHNE integration fixture does not match the frozen bytes.');

            figureHandle = openfig(figurePath, 'invisible');
            figureCleanup = onCleanup(@() closeIfValid(figureHandle));
            lines = findall(figureHandle, 'Type', 'line');
            testCase.assertNumElements(lines, 1);
            timeMicroseconds = double(lines.XData(:));
            template = double(lines.YData(:));
            clear figureCleanup;

            sampleTime = median(diff(timeMicroseconds)) * 1e-6;
            template = template - median(template(1:100));
            template = template / max(template);
            onsetIndex = find(template >= 0.05, 1, 'first');
            inputImpulse = zeros(size(template));
            inputImpulse(onsetIndex) = 1;

            [discreteModel, discreteDiagnostics] = ...
                pds.identification.estimateDiscreteTransferFunction( ...
                inputImpulse, template, SampleTime=sampleTime, ...
                MaxOrder=4, DelayRange=-2:2, FitTolerance=0.5);

            discreteInput = shiftWithZeroPadding( ...
                inputImpulse, discreteDiagnostics.selectedDelaySamples);
            discreteReconstruction = filter( ...
                discreteModel.Numerator, discreteModel.Denominator, ...
                discreteInput);

            [continuousModel, continuousDiagnostics] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputImpulse, template, SampleTime=sampleTime, ...
                MaxOrder=4, DelayRange=-2:2, FitTolerance=0.5);
            continuousInput = shiftWithZeroPadding( ...
                inputImpulse, continuousDiagnostics.selectedDelaySamples);
            timeSeconds = (0:(numel(template) - 1)).' * sampleTime;
            continuousReconstruction = lsim( ...
                continuousModel, continuousInput, timeSeconds, 'zoh');

            [~, peakIndex] = max(template);
            targetUndershoot = min(template(peakIndex:end));
            discreteMinimum = min(discreteReconstruction(peakIndex:end));
            continuousMinimum = min(continuousReconstruction(peakIndex:end));

            outputRoot = fullfile(repositoryRoot, 'outputs', ...
                'validation', 'iir-daphne-fbk-vgain-1700');
            discreteArtifacts = writeReviewArtifacts( ...
                fullfile(outputRoot, 'discrete'), timeMicroseconds, ...
                template, discreteReconstruction, peakIndex, ...
                discreteModel, discreteDiagnostics, targetUndershoot, ...
                discreteMinimum);
            continuousArtifacts = writeReviewArtifacts( ...
                fullfile(outputRoot, 'continuous'), timeMicroseconds, ...
                template, continuousReconstruction, peakIndex, ...
                continuousModel, continuousDiagnostics, ...
                targetUndershoot, continuousMinimum);

            testCase.verifyEqual(sampleTime, 16e-9, RelTol=1e-12);
            testCase.verifyEqual( ...
                height(discreteDiagnostics.candidateTable), 20);
            testCase.verifyEqual( ...
                height(continuousDiagnostics.candidateTable), 20);
            testCase.verifyEqual(discreteDiagnostics.selectedPoleOrder, 4);
            testCase.verifyEqual(continuousDiagnostics.selectedPoleOrder, 4);
            testCase.verifyEqual(discreteDiagnostics.selectedDelaySamples, -1);
            testCase.verifyEqual(continuousDiagnostics.selectedDelaySamples, -1);
            testCase.verifyGreaterThan( ...
                discreteDiagnostics.selectedFitPercent, 90);
            testCase.verifyGreaterThan( ...
                continuousDiagnostics.selectedFitPercent, 90);
            testCase.verifyLessThan(targetUndershoot, -0.02);
            testCase.verifyGreaterThanOrEqual(discreteMinimum, 0);
            testCase.verifyGreaterThanOrEqual(continuousMinimum, 0);
            testCase.verifyGreaterThan( ...
                discreteMinimum - targetUndershoot, 0.02);
            testCase.verifyGreaterThan( ...
                continuousMinimum - targetUndershoot, 0.02);
            testCase.verifyTrue(all(cellfun(@isNonemptyFile, ...
                struct2cell(discreteArtifacts))));
            testCase.verifyTrue(all(cellfun(@isNonemptyFile, ...
                struct2cell(continuousArtifacts))));
        end
    end
end

function shifted = shiftWithZeroPadding(signal, delay)
    shifted = zeros(size(signal));
    if delay >= 0
        shifted((delay + 1):end) = signal(1:(end - delay));
    else
        advance = -delay;
        shifted(1:(end - advance)) = signal((advance + 1):end);
    end
end

function closeIfValid(figureHandle)
    if isgraphics(figureHandle)
        close(figureHandle);
    end
end

function digest = sha256File(filePath)
    fileIdentifier = fopen(filePath, 'rb');
    if fileIdentifier < 0
        error('TestDaphneVgain1700TransferFunctionIdentification:OpenFailed', ...
            'Could not open DAPHNE integration fixture.');
    end
    cleanup = onCleanup(@() fclose(fileIdentifier));
    bytes = fread(fileIdentifier, Inf, '*uint8');
    engine = java.security.MessageDigest.getInstance('SHA-256');
    engine.update(bytes);
    digestBytes = typecast(engine.digest(), 'uint8');
    digest = lower(reshape(dec2hex(digestBytes, 2).', 1, []));
end

function artifactPaths = writeReviewArtifacts(outputDirectory, ...
        timeMicroseconds, target, reconstructed, peakIndex, model, ...
        diagnostics, targetUndershoot, reconstructedMinimum)
    if ~isfolder(outputDirectory)
        mkdir(outputDirectory);
    end

    artifactPaths = struct( ...
        'comparisonPng', fullfile(outputDirectory, ...
            'waveform-comparison.png'), ...
        'comparisonFig', fullfile(outputDirectory, ...
            'waveform-comparison.fig'), ...
        'candidateMapPng', fullfile(outputDirectory, ...
            'candidate-fit-map.png'), ...
        'candidateMapFig', fullfile(outputDirectory, ...
            'candidate-fit-map.fig'), ...
        'candidateCsv', fullfile(outputDirectory, ...
            'candidate-table.csv'), ...
        'metricsJson', fullfile(outputDirectory, ...
            'selected-model-metrics.json'));

    comparisonFigure = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [100, 100, 1100, 850]);
    comparisonCleanup = onCleanup(@() closeIfValid(comparisonFigure));
    layout = tiledlayout(comparisonFigure, 3, 1, ...
        'TileSpacing', 'compact', 'Padding', 'compact');
    title(layout, sprintf( ...
        'DAPHNE FBK SiPM, VGAIN 1700: %s transfer-function identification', ...
        diagnostics.domain));

    nexttile(layout);
    plot(timeMicroseconds, target, 'k-', 'LineWidth', 1.4, ...
        'DisplayName', '1-PE template');
    hold on;
    plot(timeMicroseconds, reconstructed, 'r--', 'LineWidth', 1.3, ...
        'DisplayName', 'selected model');
    yline(0, ':', 'Color', [0.4, 0.4, 0.4], ...
        'HandleVisibility', 'off');
    grid on;
    ylabel('Normalized amplitude');
    title(sprintf('Full waveform: order %d, delay %d, fit %.3f%%', ...
        diagnostics.selectedPoleOrder, diagnostics.selectedDelaySamples, ...
        diagnostics.selectedFitPercent));
    legend('Location', 'best');

    peakWindow = max(1, peakIndex - 30):min(numel(target), peakIndex + 100);
    nexttile(layout);
    plot(timeMicroseconds(peakWindow), target(peakWindow), ...
        'k-', 'LineWidth', 1.4);
    hold on;
    plot(timeMicroseconds(peakWindow), reconstructed(peakWindow), ...
        'r--', 'LineWidth', 1.3);
    grid on;
    ylabel('Normalized amplitude');
    title('Peak region');

    tailStart = min(numel(target), peakIndex + 200);
    tailWindow = tailStart:numel(target);
    nexttile(layout);
    plot(timeMicroseconds(tailWindow), target(tailWindow), ...
        'k-', 'LineWidth', 1.4, 'DisplayName', '1-PE template');
    hold on;
    plot(timeMicroseconds(tailWindow), reconstructed(tailWindow), ...
        'r--', 'LineWidth', 1.3, 'DisplayName', 'selected model');
    yline(0, ':', 'Color', [0.4, 0.4, 0.4], ...
        'HandleVisibility', 'off');
    grid on;
    ylim([-0.04, 0.08]);
    xlabel('Time [microseconds]');
    ylabel('Normalized amplitude');
    title(sprintf(['Tail/undershoot: target min %.4f, ', ...
        'model min %.4g'], targetUndershoot, reconstructedMinimum));

    exportgraphics(comparisonFigure, artifactPaths.comparisonPng, ...
        'Resolution', 180);
    savefig(comparisonFigure, artifactPaths.comparisonFig);
    clear comparisonCleanup;

    candidateTable = diagnostics.candidateTable;
    orders = unique(candidateTable.poleOrder, 'sorted');
    delays = unique(candidateTable.delaySamples, 'sorted');
    fitMap = NaN(numel(orders), numel(delays));
    for row = 1:height(candidateTable)
        orderIndex = find(orders == candidateTable.poleOrder(row), 1);
        delayIndex = find(delays == candidateTable.delaySamples(row), 1);
        fitMap(orderIndex, delayIndex) = candidateTable.fitPercent(row);
    end

    mapFigure = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [100, 100, 900, 550]);
    mapCleanup = onCleanup(@() closeIfValid(mapFigure));
    imagesc(delays, orders, fitMap);
    set(gca, 'YDir', 'normal');
    xticks(delays);
    yticks(orders);
    colorbar;
    colormap(parula);
    hold on;
    plot(diagnostics.selectedDelaySamples, ...
        diagnostics.selectedPoleOrder, 'wo', 'MarkerSize', 12, ...
        'LineWidth', 2, 'HandleVisibility', 'off');
    text(diagnostics.selectedDelaySamples + 0.12, ...
        diagnostics.selectedPoleOrder, 'selected', ...
        'Color', 'k', 'FontWeight', 'bold', ...
        'VerticalAlignment', 'middle', ...
        'BackgroundColor', 'w', 'Margin', 2);
    xlabel('Zero-padded delay [samples]');
    ylabel('Pole order');
    title('Candidate fit map [%]');
    exportgraphics(mapFigure, artifactPaths.candidateMapPng, ...
        'Resolution', 180);
    savefig(mapFigure, artifactPaths.candidateMapFig);
    clear mapCleanup;

    writetable(candidateTable, artifactPaths.candidateCsv);
    metrics = struct( ...
        'dataset', 'DAPHNE/FBK_SiPM/vgain_1700/channel_24', ...
        'domain', char(diagnostics.domain), ...
        'variable', char(model.Variable), ...
        'sampleTimeSeconds', diagnostics.sampleTime, ...
        'selectedPoleOrder', diagnostics.selectedPoleOrder, ...
        'selectedZeroOrder', diagnostics.selectedZeroOrder, ...
        'selectedDelaySamples', diagnostics.selectedDelaySamples, ...
        'selectedFitPercent', diagnostics.selectedFitPercent, ...
        'bestFitPercent', diagnostics.bestFitPercent, ...
        'targetUndershoot', targetUndershoot, ...
        'reconstructedMinimumPostPeak', reconstructedMinimum, ...
        'candidateCount', height(candidateTable));
    writeTextFile(artifactPaths.metricsJson, ...
        jsonencode(metrics, PrettyPrint=true));
end

function writeTextFile(filePath, text)
    fileIdentifier = fopen(filePath, 'wt');
    if fileIdentifier < 0
        error('TestDaphneVgain1700TransferFunctionIdentification:WriteFailed', ...
            'Could not write integration review artifact.');
    end
    cleanup = onCleanup(@() fclose(fileIdentifier));
    fprintf(fileIdentifier, '%s\n', text);
end

function result = isNonemptyFile(filePath)
    fileInformation = dir(filePath);
    result = isfile(filePath) && ~isempty(fileInformation) && ...
        fileInformation.bytes > 0;
end
