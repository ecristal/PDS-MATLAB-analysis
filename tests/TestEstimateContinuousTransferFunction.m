classdef TestEstimateContinuousTransferFunction < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addProjectSource(testCase)
            repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
            sourceDirectory = fullfile(repositoryRoot, 'src');
            addpath(sourceDirectory);
            testCase.addTeardown(@() rmpath(sourceDirectory));
        end
    end

    methods (Test)
        function residualMetricsUseZeroOrderHoldInput(testCase)
            sampleTime = 0.01;
            time = (0:249).' * sampleTime;
            inputSignal = sin(2 * pi * 0.9 * time) + ...
                0.25 * sin(2 * pi * 3.7 * time);
            outputSignal = lsim(tf(1.2, [0.09, 1]), inputSignal, time);

            [model, diagnostics] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=1, DelayRange=0, ...
                SelectionCriterion="best-fit");

            zeroOrderHoldPrediction = lsim( ...
                model, inputSignal, time, 'zoh');
            expectedRmse = sqrt(mean( ...
                (outputSignal - zeroOrderHoldPrediction) .^ 2));

            testCase.verifyEqual( ...
                diagnostics.selectedRmse, expectedRmse, AbsTol=1e-12);
        end

        function selectsLowerOrderWithinFitTolerance(testCase)
            sampleTime = 0.01;
            time = (0:249).' * sampleTime;
            inputSignal = sin(2 * pi * 0.9 * time) + ...
                0.25 * sin(2 * pi * 3.7 * time);
            outputSignal = lsim(tf(1.2, [0.09, 1]), inputSignal, time);

            [~, diagnostics] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=3, DelayRange=0, FitTolerance=1.5);

            testCase.verifyEqual(diagnostics.selectedPoleOrder, 1);
            testCase.verifyFalse(diagnostics.maxOrderReached);
            testCase.verifyEqual( ...
                diagnostics.numeratorOrderPolicy, ...
                "pole-order-minus-one");
        end

        function preservesRngAndRejectsInvalidContracts(testCase)
            inputSignal = (1:20).';
            outputSignal = filter(1, [1, -0.5], inputSignal);
            rng(11, 'twister');
            [modelA, diagnosticsA] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputSignal, outputSignal, SampleTime=1, ...
                MaxOrder=1, DelayRange=0);
            rng(29, 'twister');
            stateBefore = rng;
            [modelB, diagnosticsB] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputSignal, outputSignal, SampleTime=1, ...
                MaxOrder=1, DelayRange=0);
            stateAfter = rng;
            testCase.verifyEqual(stateAfter, stateBefore);
            testCase.verifyEqual(modelA.Numerator, modelB.Numerator, ...
                AbsTol=1e-12);
            testCase.verifyEqual(modelA.Denominator, modelB.Denominator, ...
                AbsTol=1e-12);
            testCase.verifyEqual(diagnosticsA.candidateTable.fitPercent, ...
                diagnosticsB.candidateTable.fitPercent, AbsTol=1e-12);

            invalidCalls = { ...
                @() pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal(1:end-1), SampleTime=1), ...
                @() pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=0), ...
                @() pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=1, MaxOrder=1.5), ...
                @() pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=1, DelayRange=[0, 0]), ...
                @() pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=1, FitTolerance=-1), ...
                @() pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=1, ...
                    SelectionCriterion="unknown")};
            expectedIdentifiers = { ...
                'pds:identification:estimateContinuousTransferFunction:InvalidSignals', ...
                'pds:identification:estimateContinuousTransferFunction:InvalidSampleTime', ...
                'pds:identification:estimateContinuousTransferFunction:InvalidMaxOrder', ...
                'pds:identification:estimateContinuousTransferFunction:InvalidDelayRange', ...
                'pds:identification:estimateContinuousTransferFunction:InvalidFitTolerance', ...
                'pds:identification:estimateContinuousTransferFunction:UnknownSelectionCriterion'};
            for index = 1:numel(invalidCalls)
                testCase.verifyError(invalidCalls{index}, ...
                    expectedIdentifiers{index});
            end
        end

        function recoversZeroPaddedDelayWithoutCircularWrapping(testCase)
            sampleTime = 0.02;
            sampleCount = 200;
            inputSignal = zeros(sampleCount, 1);
            inputSignal(20) = 1;
            delayedInput = [zeros(3, 1); inputSignal(1:end-3)];
            time = (0:(sampleCount - 1)).' * sampleTime;
            outputSignal = lsim(tf(1.5, [0.12, 1]), delayedInput, time);

            [~, diagnostics] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=-1:4, FitTolerance=0.1);

            testCase.verifyEqual(diagnostics.selectedDelaySamples, 3);
            testCase.verifyEqual(height(diagnostics.candidateTable), 12);
        end

        function supportsResidualBasedSelectionCriteria(testCase)
            sampleTime = 0.01;
            time = (0:149).' * sampleTime;
            inputSignal = sin(2 * pi * 0.8 * time) + ...
                0.3 * sin(2 * pi * 3.1 * time);
            outputSignal = lsim(tf(1.7, [0.07, 1]), inputSignal, time);

            criteria = ["best-fit", "bic", "aicc"];
            scoreNames = ["fitPercent", "bic", "aicc"];
            for index = 1:numel(criteria)
                [~, diagnostics] = ...
                    pds.identification.estimateContinuousTransferFunction( ...
                    inputSignal, outputSignal, SampleTime=sampleTime, ...
                    MaxOrder=2, DelayRange=0, ...
                    SelectionCriterion=criteria(index));
                candidates = diagnostics.candidateTable;
                valid = candidates.valid;
                selected = candidates.poleOrder == ...
                    diagnostics.selectedPoleOrder & ...
                    candidates.delaySamples == ...
                    diagnostics.selectedDelaySamples;
                if criteria(index) == "best-fit"
                    expected = max(candidates.(scoreNames(index))(valid));
                    testCase.verifyEqual( ...
                        candidates.fitPercent(selected), expected, ...
                        AbsTol=1e-10);
                else
                    expected = min(candidates.(scoreNames(index))(valid));
                    testCase.verifyEqual( ...
                        candidates.(scoreNames(index))(selected), expected, ...
                        AbsTol=1e-10);
                end
            end
        end

        function identifiesStableContinuousModelWithinMaximumOrder(testCase)
            sampleTime = 0.01;
            time = (0:199).' * sampleTime;
            inputSignal = sin(2 * pi * 0.7 * time) + ...
                0.4 * sin(2 * pi * 2.3 * time);
            trueModel = tf(2, [0.08, 1]);
            outputSignal = lsim(trueModel, inputSignal, time);

            [model, diagnostics] = ...
                pds.identification.estimateContinuousTransferFunction( ...
                inputSignal, outputSignal, SampleTime=sampleTime, ...
                MaxOrder=2, DelayRange=0, FitTolerance=0.5);

            testCase.verifyEqual(model.Ts, 0);
            testCase.verifyTrue(isstable(model));
            testCase.verifyEqual(diagnostics.domain, "continuous");
            testCase.verifyLessThanOrEqual(diagnostics.selectedPoleOrder, 2);
            testCase.verifyEqual(diagnostics.selectedZeroOrder, ...
                max(0, diagnostics.selectedPoleOrder - 1));
            testCase.verifyGreaterThan(diagnostics.selectedFitPercent, 95);
            testCase.verifyEqual(height(diagnostics.candidateTable), 2);
        end
    end
end
