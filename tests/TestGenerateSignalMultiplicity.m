        function poissonMultiplicityIncludesZeroAndMatchesMoments(testCase)
            eventCount = 6000;
            lambda = 2.5;
            [eventTrain, truth] = pds.simulation.generateEventTrain( ...
                8, 1, EventCount=eventCount, ReferenceIndex=3, ...
                ReferenceAmplitude=4, ...
                SignalMultiplicityDistribution="poisson", ...
                SignalMultiplicityLambda=lambda, Seed=120);

            multiplicity = truth.signalMultiplicity;
            testCase.verifySize(multiplicity, [eventCount, 1]);
            testCase.verifyGreaterThanOrEqual(multiplicity, 0);
            testCase.verifyEqual(multiplicity, fix(multiplicity));
            testCase.verifyTrue(any(multiplicity == 0));
            testCase.verifyTrue(any(multiplicity > 1));
            zeroProbability = exp(-lambda);
            zeroTolerance = 6 * sqrt(zeroProbability * ...
                (1 - zeroProbability) / eventCount) + 0.005;
            testCase.verifyEqual(mean(multiplicity == 0), zeroProbability, ...
                AbsTol=zeroTolerance);
            testCase.verifyEqual(truth.referenceComponent(:, 3), ...
                4 * multiplicity, AbsTol=0);
            testCase.verifyEqual(truth.referenceComponent(:, [1:2, 4:8]), ...
                zeros(eventCount, 7), AbsTol=0);
            testCase.verifyEqual(eventTrain, truth.referenceComponent, AbsTol=0);
            testCase.verifyEqual(truth.signalMultiplicityDistribution, "poisson");
            testCase.verifyEqual(truth.signalMultiplicityLambda, lambda);
            testCase.verifyEqual(truth.expectedSignalMultiplicity, lambda);

            meanTolerance = 6 * sqrt(lambda / eventCount) + 0.01;
            varianceTolerance = 6 * sqrt( ...
                (lambda + 2 * lambda^2) / eventCount) + 0.02;
            testCase.verifyEqual(mean(multiplicity), lambda, ...
                AbsTol=meanTolerance);
            testCase.verifyEqual(var(multiplicity, 1), lambda, ...
                AbsTol=varianceTolerance);
        end

        function empiricalPmfPreservesZeroMassAndMatchesFrequencies(testCase)
            eventCount = 10000;
            support = [0, 1, 3];
            probability = [0.2, 0.5, 0.3];
            expectedMultiplicity = sum(support .* probability);
            [eventTrain, truth] = pds.simulation.generateEventTrain( ...
                5, 1, EventCount=eventCount, ReferenceIndex=2, ...
                ReferenceAmplitude=2, ...
                SignalMultiplicityDistribution="empirical-pmf", ...
                SignalMultiplicitySupport=support, ...
                SignalMultiplicityPmf=probability, Seed=220);

            multiplicity = truth.signalMultiplicity;
            testCase.verifyTrue(all(ismember(multiplicity, support)));
            testCase.verifyTrue(any(multiplicity == 0));
            testCase.verifyEqual(truth.signalMultiplicityDistribution, ...
                "empirical-pmf");
            testCase.verifyEqual(truth.signalMultiplicitySupport, support);
            testCase.verifyEqual(truth.signalMultiplicityPmf, probability, ...
                AbsTol=1e-15);
            testCase.verifyEqual(truth.expectedSignalMultiplicity, ...
                expectedMultiplicity, AbsTol=1e-15);
            testCase.verifyEqual(truth.referenceComponent(:, 2), ...
                2 * multiplicity, AbsTol=0);
            testCase.verifyEqual(eventTrain, truth.referenceComponent, AbsTol=0);

            empiricalFrequency = zeros(size(support));
            for supportIndex = 1:numel(support)
                empiricalFrequency(supportIndex) = mean( ...
                    multiplicity == support(supportIndex));
                frequencyTolerance = 6 * sqrt(probability(supportIndex) * ...
                    (1 - probability(supportIndex)) / eventCount) + 0.005;
                testCase.verifyEqual(empiricalFrequency(supportIndex), ...
                    probability(supportIndex), AbsTol=frequencyTolerance);
            end
            testCase.verifyEqual(sum(empiricalFrequency), 1, AbsTol=0);

            [~, pointMassTruth] = pds.simulation.generateEventTrain( ...
                2, 1, EventCount=1000, ...
                SignalMultiplicityDistribution="empirical-pmf", ...
                SignalMultiplicitySupport=[0, 1, 3], ...
                SignalMultiplicityPmf=[0, 1, 0], Seed=221);
            testCase.verifyEqual(pointMassTruth.signalMultiplicity, ...
                ones(1000, 1));
        end

