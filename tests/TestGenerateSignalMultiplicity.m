        function multiplicityIsSeparateFromDarkAndLargeProcesses(testCase)
            eventCount = 6000;
            multiplicityLambda = 2;
            darkLambda = 3;
            largeLambda = 4;
            [~, truth] = pds.simulation.generateEventTrain( ...
                1, 1, EventCount=eventCount, ...
                SignalMultiplicityDistribution="poisson", ...
                SignalMultiplicityLambda=multiplicityLambda, ...
                DarkRateHz=darkLambda, LargeEventRateHz=largeLambda, ...
                LargeAmplitude=5, Seed=580);

            multiplicity = truth.signalMultiplicity;
            darkCount = truth.darkEventCount;
            largeCount = truth.largeEventCount;
            multiplicityDarkCovariance = mean((multiplicity - ...
                mean(multiplicity)) .* (darkCount - mean(darkCount)));
            multiplicityLargeCovariance = mean((multiplicity - ...
                mean(multiplicity)) .* (largeCount - mean(largeCount)));
            darkTolerance = 6 * sqrt( ...
                multiplicityLambda * darkLambda / eventCount) + 0.05;
            largeTolerance = 6 * sqrt( ...
                multiplicityLambda * largeLambda / eventCount) + 0.05;
            testCase.verifyEqual(multiplicityDarkCovariance, 0, ...
                AbsTol=darkTolerance);
            testCase.verifyEqual(multiplicityLargeCovariance, 0, ...
                AbsTol=largeTolerance);
            testCase.verifyEqual(truth.unsaturatedEventTrain, ...
                truth.referenceComponent + truth.darkComponent + ...
                truth.largeEventComponent, AbsTol=0);
            testCase.verifyEqual(truth.expectedSignalMultiplicity, ...
                multiplicityLambda);
            testCase.verifyEqual(truth.expectedDarkEventCount, darkLambda);
            testCase.verifyEqual(truth.expectedLargeEventCount, largeLambda);
        end

        function multiplicityIsAppliedBeforeExplicitClipping(testCase)
            [eventTrain, truth] = pds.simulation.generateEventTrain( ...
                1, 1, EventCount=2, ReferenceAmplitude=5, ...
                SignalMultiplicity=3, DarkRateHz=1, ...
                LargeEventRateHz=1, LargeAmplitude=7, ...
                SaturationRange=[0, 10], Seed=620);

            reconstructed = truth.referenceComponent + truth.darkComponent + ...
                truth.largeEventComponent;
            testCase.verifyEqual(truth.unsaturatedEventTrain, ...
                reconstructed, AbsTol=0);
            testCase.verifyEqual(truth.referenceComponent, 15 * ones(2, 1), ...
                AbsTol=0);
            testCase.verifyEqual(eventTrain, min(reconstructed, 10), AbsTol=0);
            testCase.verifyEqual(truth.saturationMask, reconstructed > 10);
            testCase.verifyClass(eventTrain, 'double');
        end
