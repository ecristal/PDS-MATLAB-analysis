        function poissonOperationalLimitIsFailFastAndShapeChecked(testCase)
            maximumLambda = 1e9;
            eventCount = 20000;
            [~, truth] = pds.simulation.generateEventTrain( ...
                1, 1, EventCount=eventCount, ...
                SignalMultiplicityDistribution="poisson", ...
                SignalMultiplicityLambda=maximumLambda, Seed=591);
            multiplicity = truth.signalMultiplicity;
            standardized = (multiplicity - maximumLambda) / ...
                sqrt(maximumLambda);
            testCase.verifyEqual(var(multiplicity, 1) / maximumLambda, 1, ...
                AbsTol=0.05);
            testCase.verifyEqual(mean(abs(standardized) <= 1), ...
                0.682689492137086, AbsTol=0.02);
            testCase.verifyEqual(mean(standardized <= 0), 0.5, ...
                AbsTol=0.02);
            testCase.verifyEqual(mean(mod(multiplicity, 2) == 1), 0.5, ...
                AbsTol=0.02);

            stream = RandStream('mt19937ar', 'Seed', 592);
            stateBefore = stream.State;
            testCase.verifyError(@() ...
                pds.simulation.generateEventTrain(1, 1, ...
                SignalMultiplicityDistribution="poisson", ...
                SignalMultiplicityLambda=maximumLambda + 1, ...
                RandomStream=stream), ...
                'pds:simulation:generateEventTrain:InvalidSignalMultiplicityLambda');
            testCase.verifyEqual(stream.State, stateBefore);
        end

        function poissonGroupedCdfMatchesAtModerateMeans(testCase)
            eventCount = 20000;
            lambdas = [10, 25];
            thresholds = {[4, 7, 10, 13, 16], ...
                [15, 20, 25, 30, 35]};
            for lambdaIndex = 1:numel(lambdas)
                lambda = lambdas(lambdaIndex);
                [~, truth] = pds.simulation.generateEventTrain( ...
                    1, 1, EventCount=eventCount, ...
                    SignalMultiplicityDistribution="poisson", ...
                    SignalMultiplicityLambda=lambda, ...
                    Seed=600 + lambdaIndex);
                multiplicity = truth.signalMultiplicity;
                for threshold = thresholds{lambdaIndex}
                    expectedCdf = poissonCdfAt(threshold, lambda);
                    tolerance = 6 * sqrt(expectedCdf * ...
                        (1 - expectedCdf) / eventCount) + 0.003;
                    testCase.verifyEqual(mean(multiplicity <= threshold), ...
                        expectedCdf, AbsTol=tolerance);
                end
            end
        end

