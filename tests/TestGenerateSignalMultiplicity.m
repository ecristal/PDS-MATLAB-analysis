        function randomSourcesReplayWithoutChangingGlobalRng(testCase)
            callerState = rng;
            cleanup = onCleanup(@() rng(callerState));
            rng(9876, 'twister');
            globalState = rng;

            commonOptions = { ...
                'EventCount', 40, ...
                'SignalMultiplicityDistribution', 'empirical-pmf', ...
                'SignalMultiplicitySupport', [0, 1, 4], ...
                'SignalMultiplicityPmf', [0.25, 0.5, 0.25], ...
                'DarkRateHz', 0.1, ...
                'LargeEventRateHz', 0.05};
            [firstTrain, firstTruth] = pds.simulation.generateEventTrain( ...
                20, 1, commonOptions{:}, Seed=420);
            [secondTrain, secondTruth] = pds.simulation.generateEventTrain( ...
                20, 1, commonOptions{:}, Seed=420);
            testCase.verifyEqual(firstTrain, secondTrain, AbsTol=0);
            testCase.verifyEqual(firstTruth.signalMultiplicity, ...
                secondTruth.signalMultiplicity);
            testCase.verifyEqual(rng, globalState);

            [poissonTrain, poissonTruth] = ...
                pds.simulation.generateEventTrain(20, 1, EventCount=40, ...
                SignalMultiplicityDistribution="poisson", ...
                SignalMultiplicityLambda=3, Seed=422);
            [poissonReplayTrain, poissonReplayTruth] = ...
                pds.simulation.generateEventTrain(20, 1, EventCount=40, ...
                SignalMultiplicityDistribution="poisson", ...
                SignalMultiplicityLambda=3, Seed=422);
            testCase.verifyEqual(poissonTrain, poissonReplayTrain, AbsTol=0);
            testCase.verifyEqual(poissonTruth.signalMultiplicity, ...
                poissonReplayTruth.signalMultiplicity);
            testCase.verifyEqual(rng, globalState);

            stream = RandStream('mt19937ar', 'Seed', 421);
            streamInitialState = stream.State;
            [streamTrain, streamTruth] = pds.simulation.generateEventTrain( ...
                20, 1, commonOptions{:}, RandomStream=stream);
            advancedState = stream.State;
            replayStream = RandStream('mt19937ar', 'Seed', 421);
            [replayTrain, replayTruth] = pds.simulation.generateEventTrain( ...
                20, 1, commonOptions{:}, RandomStream=replayStream);
            testCase.verifyEqual(streamTrain, replayTrain, AbsTol=0);
            testCase.verifyEqual(streamTruth.signalMultiplicity, ...
                replayTruth.signalMultiplicity);
            testCase.verifyNotEqual(advancedState, streamInitialState);
            testCase.verifyEqual(replayStream.State, advancedState);
            testCase.verifyEqual(rng, globalState);
            clear cleanup;
        end

